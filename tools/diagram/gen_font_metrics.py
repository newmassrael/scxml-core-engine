"""Generate the print diagram's glyph-advance table from the font it prints in.

Usage: python3 tools/diagram/gen_font_metrics.py <NotoSansCJK-Regular.ttc> \
           --out sce-build/src/diagram/metrics_table.rs

The print diagram decides whether a figure fits a page at a minimum font size,
so the width of every label is a fact the split depends on. A guessed width is
a guessed fit: measured 2026-09-29, every Hangul syllable of Noto Sans CJK KR is
920/1000 em, so a 1 em estimate over-measures Korean text by 8.7 %, and Latin
advances range 224..946. So the widths are read from the font file, not typed.

The output is run-length encoded: consecutive code points of one width in one
face share a row. The font's own version string is stamped into the table, and
`sce-build`'s tests pin it, so moving to another font revision is a visible
regeneration rather than a silent change of every figure's fit.
"""
import sys

from fontTools.ttLib import TTCollection

FACES = {
    # The face labels and bodies are set in, and the one code is set in.
    "PROPORTIONAL": "Noto Sans CJK KR",
    "MONO": "Noto Sans Mono CJK KR",
}

# The code points a figure can carry. A label outside them is refused by the
# measuring code rather than given a width nobody measured.
#
# What a specification's values hold decides the list, and it is wider than the
# words of a sentence: a unit is Ω or μs, a condition is ≥ or ≠, a check is ✓, a
# Korean specification names a Hanja term. Measured 2026-10-03, a document with
# any one of those in a value was refused WHOLE (`cli/diagram-unavailable`), the
# field table included, for one character the font has a glyph for. A code point
# the font has no glyph for (a colour emoji) is still left out, and still refused
# by name: `runs` skips what the face does not carry.
#
# Cyrillic stays out on purpose: the measuring code's own tests use it as the
# script that is NOT measured.
RANGES = [
    (0x0020, 0x007E),  # printable ASCII
    (0x00A0, 0x00FF),  # Latin-1 supplement
    (0x0100, 0x024F),  # Latin extended-A and -B
    (0x0370, 0x03FF),  # Greek and Coptic (Ω, μ, π, Δ)
    (0x2000, 0x206F),  # general punctuation: spaces, dashes, quotes, per mille
    (0x2070, 0x209F),  # superscripts and subscripts
    (0x20A0, 0x20CF),  # currency symbols
    (0x2100, 0x214F),  # letterlike symbols (℃, №, Ω, ™)
    (0x2150, 0x218F),  # number forms (fractions, Roman numerals)
    (0x2190, 0x21FF),  # arrows
    (0x2200, 0x22FF),  # mathematical operators (≤ ≥ ≠ ≈ ∞ √ ∑)
    (0x2300, 0x23FF),  # miscellaneous technical
    (0x2460, 0x24FF),  # enclosed alphanumerics (circled numbers)
    (0x2500, 0x257F),  # box drawing
    (0x25A0, 0x25FF),  # geometric shapes
    (0x2600, 0x26FF),  # miscellaneous symbols
    (0x2700, 0x27BF),  # dingbats (✓ ✗)
    (0x3000, 0x303F),  # CJK symbols and punctuation
    (0x3040, 0x30FF),  # Hiragana and Katakana
    (0x3131, 0x318E),  # Hangul compatibility jamo
    (0x3400, 0x4DBF),  # CJK unified ideographs, extension A
    (0x4E00, 0x9FFF),  # CJK unified ideographs (Hanja)
    (0xAC00, 0xD7A3),  # Hangul syllables
    (0xFF01, 0xFFEE),  # fullwidth and halfwidth forms
]


def face(collection, name):
    for f in collection.fonts:
        if f["name"].getDebugName(4) == name:
            return f
    sys.exit(f"{name}: not in the collection")


def runs(font):
    cmap, hmtx = font.getBestCmap(), font["hmtx"].metrics
    out = []
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            if cp not in cmap:
                continue
            width = hmtx[cmap[cp]][0]
            if out and out[-1][1] == cp - 1 and out[-1][2] == width:
                out[-1] = (out[-1][0], cp, width)
            else:
                out.append((cp, cp, width))
    return out


def main():
    args = sys.argv[1:]
    if len(args) != 3 or args[1] != "--out":
        sys.exit(__doc__)
    font_path, out_path = args[0], args[2]
    collection = TTCollection(font_path)
    fonts = {key: face(collection, name) for key, name in FACES.items()}
    versions = {f["name"].getDebugName(5) for f in fonts.values()}
    if len(versions) != 1:
        sys.exit(f"the faces disagree on their version: {sorted(versions)}")
    upm = {f["head"].unitsPerEm for f in fonts.values()}
    if upm != {1000}:
        sys.exit(f"unitsPerEm is {sorted(upm)}; the table is in thousandths of an em")

    lines = [
        "// @generated by tools/diagram/gen_font_metrics.py — do not edit by hand.",
        "//",
        "// Glyph advances in thousandths of an em, as (first, last, advance):",
        "// every code point in first..=last has that advance in that face.",
        "",
        f'pub const FONT_VERSION: &str = "{versions.pop()}";',
    ]
    for key, name in FACES.items():
        os2 = fonts[key]["OS/2"]
        if os2.sTypoAscender - os2.sTypoDescender != 1000:
            sys.exit(f"{name}: typo ascender and descender do not span one em")
        lines += [
            "",
            "/// The family a renderer names, so it sets the face these widths",
            "/// were measured in.",
            f'pub const {key}_FAMILY: &str = "{name}";',
            "",
            f"/// {name}: the typographic ascender, where a line's baseline sits",
            "/// below the top of its em box.",
            f"pub const {key}_ASCENT: u16 = {os2.sTypoAscender};",
        ]
        lines += ["", f"/// {name}.", f"pub const {key}: &[(u32, u32, u16)] = &["]
        lines += [f"    (0x{lo:04X}, 0x{hi:04X}, {width})," for lo, hi, width in runs(fonts[key])]
        lines.append("];")
    with open(out_path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
