"""The cases a second implementation of the revision judgment is held to are the Python's own.

ADR 0011 (D1 (c)) puts the judgment of a revision in the product, and a port is "the same" only if
it passes the same cases as the reference. `sce-build/tests/fixtures/revision_judgment/cases.json`
is those cases, generated by `eval/revision_judgment_cases.py` from this package. What these tests
hold is the file itself:

* it is what the Python gives NOW, so a change to the reference that is not carried to the file
  (and so to the port) fails here rather than going unnoticed;
* every pair the join's table can meet has a case, whatever is added to the table later;
* every refusal a lineage check can make has a case that reaches it for that reason, and every
  case that is meant to be accepted is accepted: a case that refuses for another reason than its
  name says would hold nothing.
"""

from __future__ import annotations

import json
import pathlib
import unittest

from sce_author import requirement_lineage as rl, revision
from eval import revision_judgment_cases as generator

HERE = pathlib.Path(__file__).resolve().parent


def held() -> dict:
    return json.loads(generator.CASES.read_text(encoding="utf-8"))


def refusal(case) -> str | None:
    expect = case["expect"]
    return expect.get("refused") if isinstance(expect, dict) else None


class TheFileIsWhatThePythonGivesNow(unittest.TestCase):
    def test_the_file_is_current(self):
        self.assertEqual(generator.text(), generator.CASES.read_text(encoding="utf-8"),
                         "the cases are not what the Python gives: run "
                         "tools/authoring/eval/revision_judgment_cases.py")

    def test_every_lineage_a_case_names_is_in_the_table(self):
        cases = held()
        table = cases["lineages"]
        for section, keys in (("between", ("older", "newer")), ("extends", ("previous", "following")),
                              ("belongs_to_manifest", ("lineage",))):
            for case in cases[section]:
                for key in keys:
                    self.assertIn(case[key], table, f"{section}: {case['name']}")

    def test_every_lineage_in_the_table_is_used(self):
        cases = held()
        used = set()
        for section, keys in (("between", ("older", "newer")), ("extends", ("previous", "following")),
                              ("belongs_to_manifest", ("lineage",))):
            for case in cases[section]:
                used.update(case[key] for key in keys)
        self.assertEqual(set(), set(cases["lineages"]) - used)


class EveryPairTheTableCanMeetHasACase(unittest.TestCase):
    def test_each_pair_of_the_table_and_each_evidence_of_a_requirement_the_words_do_not_list(self):
        have = {c["name"] for c in held()["join"]}
        for words, evidence in revision._TABLE:
            self.assertIn(f"table: words {words}, evidence {evidence or 'none'}", have)
        for evidence in revision.EVIDENCE:
            self.assertIn(f"table: words unlisted, evidence {evidence}", have)

    def test_each_case_of_the_table_gives_the_kind_and_severity_the_table_says(self):
        for case in held()["join"]:
            if not case["name"].startswith("table: "):
                continue
            row = case["expect"]["ok"]["requirements"][0]
            words = case["name"].split("words ")[1].split(",")[0]
            evidence = case["name"].split("evidence ")[1]
            key = (None if words == "unlisted" else words, None if evidence == "none" else evidence)
            expected = revision._TABLE.get(key, ("unlisted", revision.LOOK))
            self.assertEqual(expected, (row["kind"], row["severity"]), case["name"])

    def test_the_refused_deltas_are_all_refused(self):
        for case in held()["join"]:
            if case["name"].startswith("refused "):
                self.assertIsNotNone(refusal(case), case["name"])

    def test_the_neighbour_rule_has_the_case_that_explains_and_the_cases_that_do_not(self):
        kinds = {}
        for case in held()["join"]:
            if case["name"].startswith("neighbour: "):
                kinds[case["name"]] = [r["kind"] for r in case["expect"]["ok"]["requirements"]]
        explained = [n for n, k in kinds.items() if revision.SHARED in k]
        refused = [n for n, k in kinds.items() if revision.SHARED not in k]
        self.assertGreaterEqual(len(explained), 3, kinds)
        self.assertGreaterEqual(len(refused), 6, kinds)


class EveryRefusalOfALineageCheckHasACaseThatReachesItForThatReason(unittest.TestCase):
    EXTENDS = {
        "another specification": "one lineage follows one specification",
        "fewer revisions": "revisions are never taken back",
        "an earlier revision rewritten": "is not rewritten",
        "a revision with another after it is final": "is not rewritten",
        "an id forgotten": "an id is never forgotten",
        "an id first issued in another revision": "was first issued in revision",
        "a retired id made live again": "a retired id is never issued again",
        "a requirement's history rewritten": "history is only added to",
        "the last words replaced in an earlier revision": "are not the ones the work holds",
        "a new id numbered below the work's next": "would be issued twice",
        "a new id that was already issued by number": "would be issued twice",
        "a next that is behind": "is behind the work's",
    }
    MANIFEST = {
        "the manifest of another revision": "last revision is",
        "the manifest of another specification": "the lineage is of",
        "the same list spelt another way": "another manifest than this one",
        "a lineage with a null digest": "does not say which manifest",
        "a lineage with no digest at all": "does not say which manifest",
        "a manifest that is not JSON": "the manifest is not JSON",
        "a manifest that is not an object": "the manifest is not a JSON object",
    }
    BELONGS = {
        "another specification": "is of specification",
        "an earlier step": "starts from revision 2",
        "a later step": "starts from revision 4",
        "no specification named": "names no specification",
        "no starting revision named": "names no specification",
        "a specification that is not text": "names no specification",
        "a delta that is not an object": "names no specification",
        "another copy under the same name and revision": "not the same list",
        "no digest of the list it starts from": "does not say which list",
        "a digest that is not text": "does not say which list",
        "a record that pins no manifest": "pins no manifest",
        "a record whose manifest has no digest": "pins no manifest",
        "a record whose manifest has no revision": "pins no manifest",
        "a record that is not an object": "pins no manifest",
    }

    def reasons(self, section, wanted):
        by_name = {c["name"]: c for c in held()[section]}
        self.assertEqual(set(wanted), {n for n, c in by_name.items() if refusal(c)}, section)
        for name, fragment in wanted.items():
            self.assertIn(fragment, refusal(by_name[name]), f"{section}: {name}")

    def test_extends(self):
        by_name = {c["name"]: c for c in held()["extends"]}
        for name, fragment in self.EXTENDS.items():
            self.assertIn(fragment, refusal(by_name[name]), name)
        self.assertEqual(set(self.EXTENDS), {n for n, c in by_name.items() if refusal(c)})

    def test_belongs_to_manifest(self):
        self.reasons("belongs_to_manifest", self.MANIFEST)

    def test_belongs_to(self):
        self.reasons("belongs_to", self.BELONGS)

    def test_what_is_meant_to_be_accepted_is_accepted(self):
        accepted = {"extends": 6, "belongs_to": 1, "belongs_to_manifest": 1}
        for section, count in accepted.items():
            ok = [c for c in held()[section] if c["expect"] == "ok"]
            self.assertEqual(count, len(ok), section)

    def test_between_refuses_only_what_does_not_continue_and_says_which(self):
        by_name = {c["name"]: c for c in held()["between"]}
        self.assertEqual(3, sum(1 for c in by_name.values() if refusal(c)))
        for name in ("a state against itself", "one step says what it dropped", "two steps at once",
                     "words that changed keep their id and are changed",
                     "words reworded and reworded back are carried"):
            self.assertIn("ok", by_name[name]["expect"], name)
        self.assertEqual(["R5"], by_name["one step says what it dropped"]["expect"]["ok"][
            "requirements"]["retired"])


class ThePageIsInTheFile(unittest.TestCase):
    def test_each_page_is_what_render_gives_for_its_result(self):
        for case in held()["render"]:
            self.assertEqual(revision.render(case["result"], case["sentences"], title=case["title"]),
                             case["expect"], case["name"])

    def test_the_pages_say_what_the_owner_is_told(self):
        pages = {c["name"]: c["expect"] for c in held()["render"]}
        self.assertIn("Verdict: within-reach", pages["a clean revision"])
        self.assertIn("# Revision report: revision 1 to 2", pages["a clean revision"])
        self.assertIn("local artefact", pages["sentences are printed only when given"])
        self.assertNotIn("local artefact", pages["a violation, a look, an ok and a carry-over"])
        self.assertIn("shared with R2", pages["a neighbour explains a move and is named"])
        self.assertIn("saw no evidence", pages["a check that saw nothing says so"])


if __name__ == "__main__":
    unittest.main()
