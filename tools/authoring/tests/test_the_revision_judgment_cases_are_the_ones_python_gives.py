"""The cases a second implementation of the revision judgment is held to are the Python's own.

ADR 0011 (D1 (c)) puts the judgment of a revision in the product, and a port is "the same" only if
it passes the same cases as the reference. `sce-build/tests/fixtures/revision_judgment/cases.json`
is those cases, generated by `eval/revision_judgment_cases.py` from this package. What these tests
hold is the file itself:

* it is what the Python gives NOW, so a change to the reference that is not carried to the file
  (and so to the port) fails here rather than going unnoticed;
* every pair the join's table can meet has a case, whatever is added to the table later;
* every refusal a lineage check can make has a case that reaches it for that reason, and every
  case that is meant to be accepted is accepted: a case that refuses for another reason than its
  name says would hold nothing.
"""

from __future__ import annotations

import json
import pathlib
import unittest

from sce_author import requirement_lineage as rl, revision
from eval import revision_judgment_cases as generator

HERE = pathlib.Path(__file__).resolve().parent


def held() -> dict:
    return json.loads(generator.CASES.read_text(encoding="utf-8"))


def refusal(case) -> str | None:
    expect = case["expect"]
    return expect.get("refused") if isinstance(expect, dict) else None


class TheFileIsWhatThePythonGivesNow(unittest.TestCase):
    def test_the_file_is_current(self):
        self.assertEqual(generator.text(), generator.CASES.read_text(encoding="utf-8"),
                         "the cases are not what the Python gives: run "
                         "tools/authoring/eval/revision_judgment_cases.py")

    def test_every_lineage_a_case_names_is_in_the_table(self):
        cases = held()
        table = cases["lineages"]
        for section, keys in (("between", ("older", "newer")), ("extends", ("previous", "following")),
                              ("belongs_to_list", ("lineage",))):
            for case in cases[section]:
                for key in keys:
                    self.assertIn(case[key], table, f"{section}: {case['name']}")

    def test_every_lineage_in_the_table_is_used(self):
        cases = held()
        used = set()
        for section, keys in (("between", ("older", "newer")), ("extends", ("previous", "following")),
                              ("belongs_to_list", ("lineage",))):
            for case in cases[section]:
                used.update(case[key] for key in keys)
        self.assertEqual(set(), set(cases["lineages"]) - used)


class EveryPairTheTableCanMeetHasACase(unittest.TestCase):
    def test_each_pair_of_the_table_and_each_evidence_of_a_requirement_the_words_do_not_list(self):
        have = {c["name"] for c in held()["join"]}
        for words, evidence in revision._TABLE:
            self.assertIn(f"table: words {words}, evidence {evidence or 'none'}", have)
        for evidence in revision.EVIDENCE:
            self.assertIn(f"table: words unlisted, evidence {evidence}", have)

    def test_each_case_of_the_table_gives_the_kind_and_severity_the_table_says(self):
        for case in held()["join"]:
            if not case["name"].startswith("table: "):
                continue
            row = case["expect"]["ok"]["requirements"][0]
            words = case["name"].split("words ")[1].split(",")[0]
            evidence = case["name"].split("evidence ")[1]
            key = (None if words == "unlisted" else words, None if evidence == "none" else evidence)
            expected = revision._TABLE.get(key, ("unlisted", revision.LOOK))
            self.assertEqual(expected, (row["kind"], row["severity"]), case["name"])

    def test_the_refused_deltas_are_all_refused(self):
        for case in held()["join"]:
            if case["name"].startswith("refused "):
                self.assertIsNotNone(refusal(case), case["name"])

    def test_the_neighbour_rule_has_the_case_that_explains_and_the_cases_that_do_not(self):
        kinds = {}
        for case in held()["join"]:
            if case["name"].startswith("neighbour: "):
                kinds[case["name"]] = [r["kind"] for r in case["expect"]["ok"]["requirements"]]
        explained = [n for n, k in kinds.items() if revision.SHARED in k]
        refused = [n for n, k in kinds.items() if revision.SHARED not in k]
        self.assertGreaterEqual(len(explained), 3, kinds)
        self.assertGreaterEqual(len(refused), 6, kinds)


