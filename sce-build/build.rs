//! Embeds the generator's own commit and its Jinja2 template tree into
//! the binary.
//!
//! # Template registry
//!
//! The template set has exactly one source of truth: the on-disk tree at
//! `tools/codegen/templates/`. This script walks it and emits an
//! `include_str!` registry so the in-memory template path (WASM, and any
//! caller without a filesystem) cannot carry a hand-maintained copy of
//! that list. A hand-maintained copy is not a hypothetical failure: the
//! `_macros/` family added by §synth-5-O was never added to the previous
//! hardcoded list, and because `include_str!` only ever names files that
//! *do* exist, nothing rejected the omission at compile time — the
//! templates rendered fine natively and failed only in the browser.
//!
//! Deriving the list removes the ability to state it twice. What it
//! cannot check is that a template's `{% import %}` / `{% include %}`
//! targets resolve, since minijinja binds those at render time; that is
//! the job of `template_registry::tests` in the library crate.
//!
//! The crate version is frozen at `0.1.0` under the pre-1.0 no-versioning
//! rule, so it identifies nothing. Without a second signal a consumer that
//! commits generated output has no way to ask a binary which generator it
//! is, and must hand-maintain a version sidecar instead — bookkeeping that
//! drifts silently and leaves a committed tree unattributable to any
//! single commit.
//!
//! Scope is deliberately the commit alone. A dirty-worktree flag cannot be
//! kept honest here: the rerun triggers below watch the ref, not the
//! worktree, so a flag computed at build time would go stale on the next
//! edit — and a stale "clean" claim is worse than no claim. The stamp
//! therefore names the committed state the build started from, which is
//! exactly what a pinned or hermetic build has. Uncommitted edits are the
//! job of the §synth-6.2.6 source/template hashes, which are recomputed
//! per run from the actual bytes.

use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let commit = git_commit().unwrap_or_else(|| "unknown".to_string());
    println!("cargo:rustc-env=SCE_GIT_COMMIT={commit}");
    emit_template_registry();
}

/// Template tree root, relative to this crate's manifest directory.
const TEMPLATE_ROOT: &str = "../tools/codegen/templates";

/// Walk the template tree and write `$OUT_DIR/embedded_templates.rs`.
///
/// Entries are `(name, contents)` where `name` is the path relative to
/// the tree root with `/` separators — the same name the filesystem
/// loader derives, so a caller can swap sources without renaming.
/// The list is sorted so the emitted file is a function of the tree
/// alone and not of `read_dir` order.
fn emit_template_registry() {
    let manifest_dir = PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"),
    );
    // Canonicalize so the emitted `include_str!` paths are absolute:
    // the generated file lives in OUT_DIR, where a path relative to
    // this crate would resolve against the wrong directory.
    let root = manifest_dir
        .join(TEMPLATE_ROOT)
        .canonicalize()
        .unwrap_or_else(|e| {
            // The tree is part of this repository, so absence means a
            // broken checkout rather than a supported build shape. Failing
            // here names the missing path; emitting an empty registry
            // instead would defer the failure to a render error in whatever
            // consumer happened to ask for a template first.
            panic!(
                "Jinja2 template tree not found at {}/{TEMPLATE_ROOT}: {e}",
                manifest_dir.display()
            )
        });

    let mut entries = Vec::new();
    collect_templates(&root, &root, &mut entries);
    entries.sort();

    // Watch the tree root so a file added or removed re-runs this
    // script; `include_str!` already forces a rebuild when the contents
    // of an *already listed* file change.
    watch(&root);

    let mut out = String::from(
        "// @generated by sce-build/build.rs from tools/codegen/templates/ — do not edit.\n\
         pub(crate) static EMBEDDED_TEMPLATES: &[(&str, &str)] = &[\n",
    );
    for (name, path) in &entries {
        out.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            name,
            path.display().to_string()
        ));
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo"))
        .join("embedded_templates.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("Cannot write {}: {e}", dest.display()));
}

/// Recursively collect `(relative_name, absolute_path)` for every
/// `.jinja2` file under `current`.
fn collect_templates(root: &Path, current: &Path, out: &mut Vec<(String, PathBuf)>) {
    let entries = std::fs::read_dir(current)
        .unwrap_or_else(|e| panic!("Cannot read {}: {e}", current.display()));
    for entry in entries {
        let path = entry
            .unwrap_or_else(|e| panic!("Dir entry error under {}: {e}", current.display()))
            .path();
        if path.is_dir() {
            collect_templates(root, &path, out);
        } else if path.extension().and_then(|e| e.to_str()) == Some("jinja2") {
            let rel = path
                .strip_prefix(root)
                .unwrap_or_else(|e| panic!("Path error for {}: {e}", path.display()));
            out.push((rel.to_string_lossy().replace('\\', "/"), path));
        }
    }
}

/// Short commit of `HEAD`, or `None` when this is not a git checkout (a
/// vendored crate, a release tarball, a Bazel-style fetched dependency).
/// Absence is a normal build shape, not a failure — the build must not
/// break just because provenance is unavailable.
fn git_commit() -> Option<String> {
    let git_dir = git_dir()?;
    // Rebuild when the ref moves, so the embedded value cannot go stale
    // within a working session. A stamp that silently describes the wrong
    // commit is the failure mode this whole surface exists to remove.
    watch(&git_dir.join("HEAD"));
    if let Some(reference) = head_ref(&git_dir) {
        watch(&git_dir.join(&reference));
        // Refs living in `packed-refs` have no file of their own.
        watch(&git_dir.join("packed-refs"));
    }

    let out = Command::new("git")
        .args(["rev-parse", "--short=12", "HEAD"])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    let commit = String::from_utf8(out.stdout).ok()?.trim().to_string();
    (!commit.is_empty()).then_some(commit)
}

/// Resolve the `.git` directory, following the `gitdir:` indirection a
/// worktree or submodule checkout uses. The field report's own repro
/// pins a generator via `git worktree add`, so that shape has to work.
fn git_dir() -> Option<PathBuf> {
    let out = Command::new("git")
        .args(["rev-parse", "--git-dir"])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    let dir = PathBuf::from(String::from_utf8(out.stdout).ok()?.trim());
    Some(if dir.is_absolute() {
        dir
    } else {
        std::env::current_dir().ok()?.join(dir)
    })
}

/// Symbolic ref `HEAD` points at (`refs/heads/main`), if any. A detached
/// HEAD has none, and the `HEAD` watch alone covers that case.
fn head_ref(git_dir: &Path) -> Option<String> {
    let head = std::fs::read_to_string(git_dir.join("HEAD")).ok()?;
    head.strip_prefix("ref: ").map(|r| r.trim().to_string())
}

fn watch(path: &Path) {
    println!("cargo:rerun-if-changed={}", path.display());
}
