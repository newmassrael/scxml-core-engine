//! Every C11 program of the test tree that compiles a generated machine links
//! what that machine requires through `sce_c_link_runtime`
//! (backends/c/runtime/CMakeLists.txt), and none names a library of the
//! runtime by hand.
//!
//! A generated C11 machine states what it needs linked beside it (`lua`, `dom`,
//! `http`, `clock`; `a_c11_machine_includes_what_it_states_it_requires`), its
//! plan records the statement against every file it writes, and
//! `sce_c_link_runtime` reads it from the files a program compiles. Before
//! that, 96 programs of `backends/c/tests/CMakeLists.txt` named `lua54`,
//! `sce_c_scripting`, `sce_c_base` and `sce_c_runtime_posix` by hand: one list
//! per program of what its machine needed, written when the program was, and
//! kept true by nothing. A machine that stopped needing Lua kept linking it,
//! and the programs whose point is a machine without one could only say so in
//! a comment.
//!
//! What this holds, read from the CMake text, since CMake is not run here:
//!
//! * no `target_link_libraries` names a library that implements a
//!   requirement, except on a program that tests that library itself and
//!   compiles no generated machine;
//! * every program that compiles the sources a plan route hands its caller is
//!   linked by `sce_c_link_runtime`;
//! * what a program's own code requires of the runtime (`REQUIRES`) is a
//!   requirement the runtime knows, either one a machine states
//!   (`SCE_C_RUNTIME_REQUIREMENTS`) or one only a program's code needs
//!   (`SCE_C_RUNTIME_PROGRAM_REQUIREMENTS`, the directory a suite's runner
//!   program makes), each registered by a tier, and the two share no name.

use std::path::{Path, PathBuf};

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("sce-build has a parent")
        .to_path_buf()
}

fn c11_tests() -> String {
    std::fs::read_to_string(repo_root().join("backends/c/tests/CMakeLists.txt"))
        .expect("read backends/c/tests/CMakeLists.txt")
}

fn c11_runtime() -> String {
    std::fs::read_to_string(repo_root().join("backends/c/runtime/CMakeLists.txt"))
        .expect("read backends/c/runtime/CMakeLists.txt")
}

/// What a machine states (`SCE_C_RUNTIME_REQUIREMENTS`).
const MACHINE_VOCABULARY: &str = "SCE_C_RUNTIME_REQUIREMENTS";

/// What only a program's own code needs (`SCE_C_RUNTIME_PROGRAM_REQUIREMENTS`).
const PROGRAM_VOCABULARY: &str = "SCE_C_RUNTIME_PROGRAM_REQUIREMENTS";

/// The keywords of `sce_c_link_runtime`, each opening a list of requirements.
const LINK_KEYWORDS: [&str; 3] = ["REQUIRES", "PROVIDES", "EXCLUDES"];

/// The libraries of the runtime that implement a requirement a machine states.
const REQUIREMENT_LIBRARIES: [&str; 4] = [
    "lua54",
    "sce_c_scripting",
    "sce_c_base",
    "sce_c_runtime_posix",
];

/// Programs that test a library of the runtime itself, and so name it: each
/// compiles no generated machine.
const LIBRARY_TESTS: [&str; 2] = ["sce_c_dom_unit_test", "sce_c_http_client_unit_test"];

/// The spellings by which a program's sources name what a plan generated:
/// every variable the W3C, integration and generation routes hand their
/// callers ends so (`W3C_C_AOT_TEST_<n>_SOURCES`,
/// `INTEGRATION_C_TEST_<stem>_SOURCES`, `<PREFIX>_HEADERS` of
/// `sce_codegen_generation`), as does a saved-state test's sources. No file
/// of the C11 tests is generated by a command of its own
/// (`no_cmake_file_of_the_tree_declares_a_generation_by_hand`), so a
/// generated file reaches a program only through one of them.
const GENERATED_SOURCES: [&str; 2] = ["_SOURCES}", "_HEADERS}"];

/// The text without its comments: a `#` outside a quoted string ends a line.
fn code(text: &str) -> String {
    text.lines()
        .map(|line| {
            let mut quoted = false;
            let mut kept = String::new();
            for c in line.chars() {
                match c {
                    '"' => {
                        quoted = !quoted;
                        kept.push(c);
                    }
                    '#' if !quoted => break,
                    _ => kept.push(c),
                }
            }
            kept
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Every call of `name`, as the text between its parentheses.
fn calls(code: &str, name: &str) -> Vec<String> {
    let opening = format!("{name}(");
    let mut found = Vec::new();
    let mut from = 0;
    while let Some(at) = code[from..].find(&opening) {
        let start = from + at;
        let preceded_by_name_char = code[..start]
            .chars()
            .next_back()
            .is_some_and(|c| c.is_alphanumeric() || c == '_');
        let body_start = start + opening.len();
        let mut depth = 1;
        let mut end = body_start;
        for (offset, c) in code[body_start..].char_indices() {
            match c {
                '(' => depth += 1,
                ')' => {
                    depth -= 1;
                    if depth == 0 {
                        end = body_start + offset;
                        break;
                    }
                }
                _ => {}
            }
        }
        if !preceded_by_name_char {
            found.push(code[body_start..end].to_string());
        }
        from = end.max(body_start);
    }
    found
}

/// The first word of a call's arguments: the target it is about.
fn target_of(arguments: &str) -> &str {
    arguments.split_whitespace().next().unwrap_or_default()
}

fn words(text: &str) -> impl Iterator<Item = &str> {
    text.split(|c: char| !(c.is_alphanumeric() || c == '_' || c == ':'))
        .filter(|w| !w.is_empty())
}

/// Every way the C11 tests link a library of the runtime by hand, or compile
/// a generated machine without linking what it requires.
fn violations(text: &str) -> Vec<String> {
    let code = code(text);
    let mut found = Vec::new();
    let executables = calls(&code, "add_executable");
    let linked: Vec<String> = calls(&code, "sce_c_link_runtime")
        .iter()
        .map(|arguments| target_of(arguments).to_string())
        .collect();

    for arguments in calls(&code, "target_link_libraries") {
        let target = target_of(&arguments);
        let named: Vec<&str> = words(&arguments)
            .filter(|w| REQUIREMENT_LIBRARIES.contains(w))
            .collect();
        if named.is_empty() {
            continue;
        }
        let compiles_a_machine = executables.iter().any(|executable| {
            target_of(executable) == target
                && GENERATED_SOURCES.iter().any(|s| executable.contains(s))
        });
        if !LIBRARY_TESTS.contains(&target) || compiles_a_machine {
            found.push(format!(
                "`{target}` names {named:?} by hand; a program links what the machines it \
                 compiles require through `sce_c_link_runtime`"
            ));
        }
    }

    for executable in &executables {
        let target = target_of(executable);
        if GENERATED_SOURCES.iter().any(|s| executable.contains(s))
            && !linked.iter().any(|t| t == target)
        {
            found.push(format!(
                "`{target}` compiles a generated machine and is not linked by \
                 `sce_c_link_runtime`, so nothing links what its machine requires"
            ));
        }
    }
    found
}

/// The words of the runtime's `set_property(GLOBAL PROPERTY <property> ...)`,
/// empty where it declares none.
fn vocabulary(runtime: &str, property: &str) -> Vec<String> {
    let opening = format!("set_property(GLOBAL PROPERTY {property} ");
    code(runtime)
        .lines()
        .find_map(|line| {
            line.trim()
                .strip_prefix(opening.as_str())
                .and_then(|rest| rest.strip_suffix(')'))
                .map(|rest| rest.split_whitespace().map(str::to_string).collect())
        })
        .unwrap_or_default()
}

/// The words a `sce_c_link_runtime` call lists after `keyword`.
fn listed_after<'a>(arguments: &'a str, keyword: &str) -> Vec<&'a str> {
    let mut listing = false;
    let mut found = Vec::new();
    for word in arguments.split_whitespace().skip(1) {
        if LINK_KEYWORDS.contains(&word) {
            listing = word == keyword;
        } else if listing {
            found.push(word);
        }
    }
    found
}

/// Every requirement a program of the C11 tests states by `REQUIRES` that the
/// runtime does not know or registers no library for, and every name both
/// vocabularies of the runtime hold.
fn unknown_requirements(tests: &str, runtime: &str) -> Vec<String> {
    let machine = vocabulary(runtime, MACHINE_VOCABULARY);
    let program = vocabulary(runtime, PROGRAM_VOCABULARY);
    let mut found: Vec<String> = program
        .iter()
        .filter(|name| machine.contains(*name))
        .map(|name| {
            format!(
                "`{name}` is in both {MACHINE_VOCABULARY} and {PROGRAM_VOCABULARY}; what a \
                 machine states is the generator's, and only a program's own code needs the other"
            )
        })
        .collect();
    for arguments in calls(&code(tests), "sce_c_link_runtime") {
        let target = target_of(&arguments);
        for name in listed_after(&arguments, "REQUIRES") {
            if !machine.iter().chain(&program).any(|known| known == name) {
                found.push(format!(
                    "`{target}` requires `{name}`, which the runtime knows in neither \
                     {MACHINE_VOCABULARY} nor {PROGRAM_VOCABULARY}"
                ));
            } else if !runtime.contains(&format!(
                "set_property(GLOBAL PROPERTY SCE_C_RUNTIME_REQUIREMENT_{name} "
            )) {
                found.push(format!(
                    "`{target}` requires `{name}`, for which no tier of the runtime registers \
                     a library"
                ));
            }
        }
    }
    found
}

#[test]
fn every_c11_program_links_what_its_machines_require() {
    let text = c11_tests();
    let linked = calls(&code(&text), "sce_c_link_runtime").len();
    assert!(
        linked >= 90,
        "only {linked} `sce_c_link_runtime` call(s) found; the reader is broken, not the \
         build file, and a clean result would prove nothing"
    );
    let found = violations(&text);
    assert!(
        found.is_empty(),
        "backends/c/tests/CMakeLists.txt links a generated machine's runtime by hand:\n  {}",
        found.join("\n  ")
    );
}

/// The shapes this replaced are refused: a library named for a program that
/// compiles a generated machine, and such a program left unlinked.
#[test]
fn a_runtime_library_named_by_hand_is_refused() {
    let text = c11_tests();
    let call = "sce_c_link_runtime(sce_c_integration_flat_lifecycle)";
    assert!(
        text.contains(call),
        "flat_lifecycle is no longer linked as this case expects"
    );

    let hand = text.replace(
        call,
        "target_link_libraries(sce_c_integration_flat_lifecycle PRIVATE\n        \
         sce_c_runtime sce_c_runtime_posix sce_c_base sce_c_scripting lua54\n    )",
    );
    let found = violations(&hand);
    assert!(
        found
            .iter()
            .any(|v| v.contains("`sce_c_integration_flat_lifecycle` names")),
        "a program that names lua54 by hand was accepted: {found:?}"
    );
    assert!(
        found
            .iter()
            .any(|v| v.contains("`sce_c_integration_flat_lifecycle` compiles a generated machine")),
        "a program compiling a generated machine with no `sce_c_link_runtime` was accepted: \
         {found:?}"
    );

    // A library test may name its library; one that compiled a generated
    // machine as well may not.
    let library_test = "add_executable(sce_c_dom_unit_test unit/dom_test.c)";
    assert!(
        text.contains(library_test),
        "the DOM unit test is no longer declared as this case expects"
    );
    let machine_in_library_test = text.replace(
        library_test,
        "add_executable(sce_c_dom_unit_test unit/dom_test.c \
         ${INTEGRATION_C_TEST_flat_lifecycle_SOURCES})",
    );
    let found = violations(&machine_in_library_test);
    assert!(
        found
            .iter()
            .any(|v| v.contains("`sce_c_dom_unit_test` names")),
        "a library test that compiles a generated machine was allowed to name the library: \
         {found:?}"
    );

    // A comment that names a library is not a link.
    assert!(violations("# target_link_libraries(x PRIVATE lua54)\n").is_empty());
}

/// The runner program of a generated suite, and each test program that makes
/// a suite's log directory, makes it through `sce_directory_make`, which no
/// machine states: the program requires it, and the runtime knows that
/// requirement and registers the tier that implements it.
#[test]
fn what_a_program_requires_of_the_runtime_is_a_requirement_it_knows() {
    let tests = c11_tests();
    let runtime = c11_runtime();
    assert!(
        vocabulary(&runtime, PROGRAM_VOCABULARY)
            .iter()
            .any(|name| name == "directory"),
        "backends/c/runtime/CMakeLists.txt declares no `directory` in {PROGRAM_VOCABULARY}; \
         the reader is broken, or the runner program has lost its requirement"
    );
    let runners: Vec<String> = calls(&code(&tests), "sce_c_link_runtime")
        .into_iter()
        .filter(|arguments| listed_after(arguments, "REQUIRES").contains(&"directory"))
        .map(|arguments| target_of(&arguments).to_string())
        .collect();
    assert_eq!(
        runners,
        [
            "sce_c_runtime_suite_runner",
            "sce_c_integration_a_runner_program_writes_the_log_of_each_trace",
            "sce_c_integration_a_corpus_suite_replays_to_its_expected_logs",
        ],
        "the programs that make a suite's log directory no longer state `directory`"
    );
    let found = unknown_requirements(&tests, &runtime);
    assert!(
        found.is_empty(),
        "a C11 program requires what the runtime does not link:\n  {}",
        found.join("\n  ")
    );
}

/// A requirement a program states that the runtime does not know, one it
/// knows and registers no tier for, and a name in both vocabularies are each
/// refused.
#[test]
fn a_program_requirement_the_runtime_does_not_link_is_refused() {
    let tests = c11_tests();
    let runtime = c11_runtime();

    let declared = "set_property(GLOBAL PROPERTY SCE_C_RUNTIME_PROGRAM_REQUIREMENTS directory)";
    assert!(
        runtime.contains(declared),
        "the program vocabulary is no longer declared as this case expects"
    );
    let forgotten = runtime.replace(
        declared,
        "set_property(GLOBAL PROPERTY SCE_C_RUNTIME_PROGRAM_REQUIREMENTS none)",
    );
    let found = unknown_requirements(&tests, &forgotten);
    assert!(
        found.iter().any(|v| v.contains(
            "`sce_c_runtime_suite_runner` requires `directory`, which the runtime knows"
        )),
        "a requirement missing from both vocabularies was accepted: {found:?}"
    );

    let registered =
        "set_property(GLOBAL PROPERTY SCE_C_RUNTIME_REQUIREMENT_directory sce_c_runtime_posix)";
    assert!(
        runtime.contains(registered),
        "the directory's registration is no longer spelled as this case expects"
    );
    let unregistered = runtime.replace(registered, "");
    let found = unknown_requirements(&tests, &unregistered);
    assert!(
        found
            .iter()
            .any(|v| v.contains("requires `directory`, for which no tier")),
        "a requirement no tier registers was accepted: {found:?}"
    );

    let doubled = runtime.replace(
        declared,
        "set_property(GLOBAL PROPERTY SCE_C_RUNTIME_PROGRAM_REQUIREMENTS directory clock)",
    );
    let found = unknown_requirements(&tests, &doubled);
    assert!(
        found.iter().any(|v| v.contains("`clock` is in both")),
        "a name in both vocabularies was accepted: {found:?}"
    );

    // A word after another keyword is not a requirement the program states.
    assert_eq!(
        listed_after(
            "t REQUIRES a b EXCLUDES c PROVIDES d REQUIRES e",
            "REQUIRES"
        ),
        ["a", "b", "e"]
    );
}
