//
// Which backend runtimes the spec ledger can actually judge.
//
// `validate-code-refs` enforces two different things about a `§scxml-` cite.
// EXISTENCE — the id names a real ledger section — is checked over the whole
// tree. BINDING — the cite sits on the symbol the ledger says implements that
// section — is checked only inside `[code_refs] paths` in
// `docs/spec/scxml/mnemosyne.toml`, and only where a symbol resolver exists for
// the file's language.
//
// Five backend runtimes implement the same clauses. Two of them are inside that
// scan; three are not, so their cites are spell-checked and nothing more. That
// asymmetry was recorded as prose in the ledger config — which claimed, in the
// present tense, that "no hand-authored §scxml- citation lives in an excluded
// tree" while 62 of them did. Prose cannot hold a claim like that; this can.
//
// The gap is upstream, not local: Mnemosyne ships `tree-sitter-cpp` and
// `tree-sitter-rust` plugin crates and no others, its symbol-axis extension
// table maps `.go` and `.py` to languages that have no backend, and `.kt` is
// not in that table at all. So the list below shrinks when Mnemosyne gains a
// resolver, never because a tree quietly stopped citing the spec.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("sce-build has a parent directory")
        .to_path_buf()
}

/// Backend runtimes, each of which lowers the same SCXML clauses for one
/// language. Test trees and generated output are deliberately absent: this is
/// about hand-authored implementation code.
const RUNTIMES: &[&str] = &[
    "backends/c/runtime",
    "backends/go/runtime",
    "backends/kotlin/runtime",
    "backends/python/runtime",
    "backends/rust/runtime/src",
];

/// Runtimes whose cites the symbol axis cannot reach, with the upstream reason.
/// An entry here is a claim that gets checked below, not an exemption.
const UNREACHED: &[(&str, &str)] = &[
    (
        "backends/go/runtime",
        "Mnemosyne maps .go to the `go` language but ships no resolver plugin for it",
    ),
    (
        "backends/kotlin/runtime",
        "`.kt` is absent from Mnemosyne's symbol-axis extension table entirely",
    ),
    (
        "backends/python/runtime",
        "Mnemosyne maps .py to the `python` language but ships no resolver plugin for it",
    ),
];

/// `[code_refs] paths` from the scxml ledger config — the scan set itself,
/// read rather than restated, so this test cannot disagree with the gate.
fn scanned_paths(root: &Path) -> Vec<String> {
    let toml = fs::read_to_string(root.join("docs/spec/scxml/mnemosyne.toml"))
        .expect("read docs/spec/scxml/mnemosyne.toml");
    let (_, after) = toml
        .split_once("\npaths = [")
        .expect("mnemosyne.toml declares [code_refs] paths");
    let (block, _) = after.split_once("\n]").expect("paths list is closed");
    let out: Vec<String> = block
        .lines()
        .map(|l| l.split('#').next().unwrap_or("").trim())
        .filter_map(|l| l.strip_prefix('"'))
        .filter_map(|l| l.split('"').next())
        .map(str::to_string)
        .collect();
    assert!(
        out.len() > 10,
        "parsed {} scan path(s) from mnemosyne.toml; the parse broke, not the config",
        out.len()
    );
    out
}

fn is_under(rel: &str, dir: &str) -> bool {
    rel == dir || rel.starts_with(&format!("{}/", dir.trim_end_matches('/')))
}

/// Tracked files under `dir` that carry a hand-authored `§scxml-` cite.
/// Generated files are skipped: their cite came from a template, so the tree
/// that owns it is the template tree.
fn citing_files(root: &Path, dir: &str) -> Vec<String> {
    let out = Command::new("git")
        .arg("-C")
        .arg(root)
        .arg("ls-files")
        .arg(dir)
        .output()
        .expect("git ls-files");
    assert!(out.status.success(), "git ls-files {dir} failed");

    String::from_utf8_lossy(&out.stdout)
        .lines()
        .filter(|rel| {
            let Ok(text) = fs::read_to_string(root.join(rel)) else {
                return false;
            };
            let head: String = text.chars().take(2000).collect();
            if head.contains("SCE-GENERATED")
                || head.contains("DO NOT EDIT")
                || head.contains("Code generated by")
            {
                return false;
            }
            text.contains("§scxml-")
        })
        .map(str::to_string)
        .collect()
}

#[test]
fn every_backend_runtime_citing_the_spec_is_reached_or_named() {
    let root = repo_root();
    let paths = scanned_paths(&root);
    let named: BTreeSet<&str> = UNREACHED.iter().map(|(dir, _)| *dir).collect();

    let mut unnamed: Vec<String> = Vec::new();
    let mut examined = 0usize;

    for runtime in RUNTIMES {
        let cites = citing_files(&root, runtime);
        if cites.is_empty() {
            continue;
        }
        examined += 1;
        let reached = paths
            .iter()
            .any(|p| is_under(runtime, p) || is_under(p, runtime));
        if reached || named.contains(runtime) {
            continue;
        }
        unnamed.push(format!(
            "{runtime} ({} file(s) cite the spec), e.g. {}",
            cites.len(),
            cites.first().expect("non-empty")
        ));
    }

    assert!(
        examined >= 4,
        "only {examined} of {} backend runtime(s) were found to cite the spec; \
         the scan broke, not the tree",
        RUNTIMES.len(),
    );

    assert!(
        unnamed.is_empty(),
        "backend runtime(s) cite `§scxml-` from outside the ledger's symbol \
         scan without being named as such:\n  {}\n\
         Their cites are checked for existence only — nothing verifies the \
         cite sits on the symbol the ledger says implements the clause. Add \
         the tree to `[code_refs] paths` once a resolver for its language \
         exists, or record it in UNREACHED with the reason it cannot be.",
        unnamed.join("\n  "),
    );
}

#[test]
fn a_named_gap_disappears_when_it_is_closed_rather_than_lingering() {
    let root = repo_root();
    let paths = scanned_paths(&root);

    let mut stale: Vec<String> = Vec::new();
    for (dir, reason) in UNREACHED {
        if paths.iter().any(|p| is_under(dir, p) || is_under(p, dir)) {
            stale.push(format!(
                "{dir}: now inside the scan set, but still listed — {reason}"
            ));
            continue;
        }
        if citing_files(&root, dir).is_empty() {
            stale.push(format!("{dir}: no longer cites the spec at all — {reason}"));
        }
    }

    assert!(
        stale.is_empty(),
        "UNREACHED entr(ies) no longer describe the tree:\n  {}\n\
         A gap list that outlives its gap reads as coverage that was never \
         won; drop the entry in the commit that closes it.",
        stale.join("\n  "),
    );
}
