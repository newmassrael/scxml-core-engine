#pragma once

#include <string>

namespace SCE::Core {

/// Result of a procedure execution via runToCompletion().
struct ProcedureResult {
    /// Whether the procedure reached a final state.
    bool completed;
    /// Name of the final state reached (empty if not completed).
    std::string final_state;
};

/// CRTP base class for generated procedure state machines.
///
/// Provides the run-to-completion algorithm that drives a procedure from its
/// initial state through transitions until a final state is reached.
///
/// The derived class (generated by SCE Forge) must provide:
///   - static constexpr int INITIAL_STATE;
///   - static constexpr int STATE_COUNT;
///   - static constexpr bool isFinal(int state);
///   - static const char* stateName(int state);
///   - int evaluateTransitions(int current, <input params...>) const;
///
/// The base class forwards input parameters from execute() directly to
/// evaluateTransitions() via variadic templates — no member variable storage,
/// no temporal coupling, no mutable state.
template <typename Derived>
class ProcedureStateMachine {
public:
    /// Execute the procedure to completion with the given inputs.
    /// Forwards all parameters to Derived::evaluateTransitions(current, args...).
    template <typename... Args>
    ProcedureResult execute(Args&&... args) const {
        const auto* self = static_cast<const Derived*>(this);
        int current = Derived::INITIAL_STATE;
        int iterations = 0;

        while (!Derived::isFinal(current) && iterations++ < Derived::STATE_COUNT) {
            int next = self->evaluateTransitions(current, args...);
            if (next < 0) break;
            current = next;
        }

        return {Derived::isFinal(current), Derived::stateName(current)};
    }
};

}  // namespace SCE::Core
