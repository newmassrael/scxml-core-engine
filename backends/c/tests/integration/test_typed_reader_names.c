// W3C SCXML 5.3: typed readers of `<data>` ids that are keywords or no
// identifier in some backend. C11 AOT.
//
// C11's readers are free functions named `<machine>_<id>`, so no keyword
// reaches them. What this backend owns is the prefix's own namespace:
// `<data id="t">` would have been `typed_reader_names_t` — the machine's
// typedef — so `sce-build/src/reader_names.rs` gives it no reader anywhere,
// and this file compiling is what shows none was emitted. The readers that
// every backend can spell are read here, and read their own variables.
//
// Fixture: integration_resources/typed_reader_names/typed_reader_names.scxml
// (canonical, shared with the C++ / Go / Kotlin / Python / Rust channels),
// generated by `sce_generate_static_integration_c_test(typed_reader_names ...)`
// in backends/c/tests/CMakeLists.txt.

#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>

#include "typed_reader_names_sm.h"

static int expect(const char *name, bool ok, int64_t got, int64_t want) {
    if (ok && got == want) {
        return 0;
    }
    fprintf(stderr, "typed_reader_names: FAIL - %s read %lld (ok=%d), expected %lld\n", name, (long long)got, ok,
            (long long)want);
    return 1;
}

// Every reader, against the values it should hold.
static int read_all(const typed_reader_names_t *sm, int64_t box, int64_t object, int64_t pass, int64_t screen_rules,
                    int64_t a_b) {
    int64_t v = 0;
    int bad = 0;
    bool ok = typed_reader_names_box(sm, &v);
    bad |= expect("box", ok, v, box);
    ok = typed_reader_names_object(sm, &v);
    bad |= expect("object", ok, v, object);
    ok = typed_reader_names_pass(sm, &v);
    bad |= expect("pass", ok, v, pass);
    ok = typed_reader_names_screen_rules(sm, &v);
    bad |= expect("screen_rules", ok, v, screen_rules);
    ok = typed_reader_names_a_b(sm, &v);
    bad |= expect("a_b", ok, v, a_b);
    return bad;
}

int main(void) {
    int rc = 0;
    typed_reader_names_t sm;
    typed_reader_names_init(&sm);

    // The value each variable was declared with.
    rc |= read_all(&sm, 1, 2, 3, 4, 10);

    // And the value it holds now: `bump` adds 10 to four of them, and leaves
    // `screen-rules` — which no ECMAScript expression can name — alone.
    typed_reader_names_event_with_meta_t carrier = {0};
    carrier.event = TYPED_READER_NAMES_EVENT_BUMP;
    typed_reader_names_raise_external(&sm, &carrier);
    typed_reader_names_step(&sm);
    rc |= read_all(&sm, 11, 12, 13, 4, 20);

    typed_reader_names_destroy(&sm);
    if (rc == 0) {
        printf("typed_reader_names: PASS\n");
    }
    return rc;
}
