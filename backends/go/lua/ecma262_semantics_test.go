//
// What this backend answers for `datamodel="ecmascript"`, measured against
// what ECMA-262 says.
//
// The expectations are not ours. They live in
// `tests/ecmascript/ecma262_semantics.json`, one claim per case with the
// ECMA-262 clause that backs it, and the Rust, C++ and Kotlin readers ask the
// same file. A per-backend copy of a table drifts toward the backend that
// reads it, which is the blindness the shared table was written to end.
//
// What is different here is where the ECMAScript went. Go never sees it: the
// frontend translated the author's source to Lua at build time, so a
// generated machine calls `EvaluateExpression(session, "_scxml_truthy(a)")`
// and this engine's whole contribution to the datamodel is the runtime
// library underneath that call — go-lua (5.2, no bitwise operators, no
// `string.gsub`), the shared `ecma_semantics.lua`, and the natives registered
// beside it. That is the layer this measures, and until this file existed
// nothing did: `ecma_semantics.lua` grew a standard library that this backend
// embedded and no Go test ever called.
//
// So the emission comes from `tests/ecmascript/ecma262_emitted_lua.json`,
// generated by the frontend itself and drift-gated in
// `sce-build/tests/ecmascript_semantics.rs`. Handwriting the Lua here would
// measure a translation nobody ships.

package scelua

import (
	"encoding/json"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"testing"
)

// One row of the shared table: the claim, and the clause it comes from.
type ecmaCase struct {
	Group  string                 `json:"group"`
	Setup  string                 `json:"setup"`
	Source string                 `json:"source"`
	Form   string                 `json:"form"`
	Expect map[string]interface{} `json:"expect"`
	Clause string                 `json:"clause"`
}

// One row of the emission: the Lua a generated machine would actually run.
type ecmaEmission struct {
	Source     string `json:"source"`
	Setup      string `json:"setup"`
	Expression string `json:"expression"`
}

// The repository root, from this package's own location: the shared table is
// two directories above the module and is named by the same path every other
// reader uses.
func repoRoot(t *testing.T) string {
	t.Helper()
	here, err := os.Getwd()
	if err != nil {
		t.Fatalf("cannot locate this package: %v", err)
	}
	return filepath.Join(here, "..", "..", "..")
}

func readJSONFile(t *testing.T, path string, into interface{}) {
	t.Helper()
	text, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("cannot read %s: %v\nThis test measures nothing without it.", path, err)
	}
	if err := json.Unmarshal(text, into); err != nil {
		t.Fatalf("%s is not a readable case table: %v", path, err)
	}
}

// The table and the emission, paired and cross-checked.
//
// Two files rather than one because they answer different questions — the
// table says what ECMAScript answers, the emission says what this backend is
// handed — and the pairing is asserted rather than assumed: an emission
// regenerated from a table that has since gained a row would otherwise line
// up case 40 against case 41's answer and report a defect that is really a
// stale file.
func loadCases(t *testing.T) ([]ecmaCase, []ecmaEmission) {
	t.Helper()
	root := repoRoot(t)

	var table struct {
		Cases []ecmaCase `json:"cases"`
	}
	readJSONFile(t, filepath.Join(root, "tests", "ecmascript", "ecma262_semantics.json"), &table)

	var emitted struct {
		Cases []ecmaEmission `json:"cases"`
	}
	readJSONFile(t, filepath.Join(root, "tests", "ecmascript", "ecma262_emitted_lua.json"), &emitted)

	// A floor, not an equality: adding a case must not have to touch this
	// number, but a table that stopped being read must not pass either.
	if len(table.Cases) < 55 {
		t.Fatalf("the shared ECMA-262 table produced only %d case(s), so this is not "+
			"measuring the corpus it claims to", len(table.Cases))
	}
	if len(table.Cases) != len(emitted.Cases) {
		t.Fatalf("the table holds %d case(s) and the emission %d — regenerate the "+
			"emission with `UPDATE_EXPECT=1 cargo test -p sce-build --test "+
			"ecmascript_semantics`", len(table.Cases), len(emitted.Cases))
	}
	for i := range table.Cases {
		if table.Cases[i].Source != emitted.Cases[i].Source {
			t.Fatalf("case %d is `%s` in the table and `%s` in the emission — the two "+
				"files are out of step, so every answer below would be compared "+
				"against the wrong claim", i, table.Cases[i].Source, emitted.Cases[i].Source)
		}
	}
	return table.Cases, emitted.Cases
}

// An engine may hold a whole number as an integer or as a double, and
// ECMA-262 has one Number type — so both spellings answer a `number` case.
// The same rule the Rust, C++ and Kotlin readers apply, for the same reason.
func answers(actual interface{}, expect map[string]interface{}, source string) (bool, error) {
	if want, ok := expect["bool"]; ok {
		got, isBool := actual.(bool)
		return isBool && got == want.(bool), nil
	}
	if want, ok := expect["number"]; ok {
		switch got := actual.(type) {
		case int64:
			return math.Abs(float64(got)-want.(float64)) < 1e-9, nil
		case float64:
			return math.Abs(got-want.(float64)) < 1e-9, nil
		default:
			return false, nil
		}
	}
	if want, ok := expect["string"]; ok {
		got, isString := actual.(string)
		return isString && got == want.(string), nil
	}
	// `empty` carries no value of its own — its presence IS the answer, and
	// null and undefined are one answer because ECMAScript's `==` equates
	// them and the SCXML datamodel cannot tell an absent property from a
	// null one.
	if _, ok := expect["empty"]; ok {
		return actual == nil, nil
	}
	// A case whose expectation cannot be read is not a case that passes:
	// reading it as "no answer" would let a typo in a key name retire a case
	// silently, which is the failure mode the shared table exists to remove.
	return false, fmt.Errorf("case [%s] names no expected answer", source)
}

func describe(value interface{}) string {
	switch v := value.(type) {
	case nil:
		return "nil"
	case string:
		return fmt.Sprintf("%q", v)
	default:
		return fmt.Sprintf("%v (%T)", v, v)
	}
}

func describeExpected(expect map[string]interface{}) string {
	for _, key := range []string{"bool", "number", "string"} {
		if want, ok := expect[key]; ok {
			return fmt.Sprintf("%v", want)
		}
	}
	if _, ok := expect["empty"]; ok {
		return "null or undefined"
	}
	return "?"
}

// Every case, run through the engine a generated Go state machine runs on.
func TestGoLuaAnswersWhatEcmaScriptAnswers(t *testing.T) {
	cases, emitted := loadCases(t)

	engine := NewLuaEngine()
	if err := engine.Initialize(); err != nil {
		t.Fatalf("the Lua engine must start: %v", err)
	}
	defer engine.Shutdown()

	// Every case is reported, not just the first: a backend that answers one
	// group wrong and another right is a different problem from one that
	// answers nothing, and the first failure alone cannot tell them apart.
	var failures []string
	for i := range cases {
		testCase, emission := cases[i], emitted[i]
		session := fmt.Sprintf("ecma262_case_%d", i)
		if err := engine.CreateSession(session); err != nil {
			t.Fatalf("CreateSession: %v", err)
		}

		if emission.Setup != "" {
			if err := engine.ExecuteScript(session, emission.Setup); err != nil {
				failures = append(failures, fmt.Sprintf(
					"[%s] setup did not run: %v\n  emitted: %s",
					testCase.Source, err, emission.Setup))
				engine.DestroySession(session)
				continue
			}
		}

		actual, err := engine.EvaluateExpression(session, emission.Expression)
		if err != nil {
			failures = append(failures, fmt.Sprintf(
				"[%s] failed to evaluate: %v\n  emitted: %s",
				testCase.Source, err, emission.Expression))
			engine.DestroySession(session)
			continue
		}

		matched, readErr := answers(actual, testCase.Expect, testCase.Source)
		if readErr != nil {
			t.Fatalf("%v", readErr)
		}
		if !matched {
			failures = append(failures, fmt.Sprintf(
				"[%s] answered %s, ECMAScript says %s (%s, %s)\n  emitted: %s",
				testCase.Source, describe(actual), describeExpected(testCase.Expect),
				testCase.Clause, testCase.Group, emission.Expression))
		}
		engine.DestroySession(session)
	}

	if len(failures) > 0 {
		t.Fatalf("%d of %d expressions disagree with ECMA-262 on this backend.\n"+
			"A document that declares `datamodel=\"ecmascript\"` answers what that "+
			"language answers, whichever backend it was generated for; one that "+
			"does not is a portability defect the W3C suite cannot see, because "+
			"a suite that is green end to end never asks `0 && x`.\n%s",
			len(failures), len(cases), joinLines(failures))
	}
}

func joinLines(lines []string) string {
	out := ""
	for _, line := range lines {
		out += line + "\n"
	}
	return out
}
