"""A parent forwards its child the name an event arrived under (§scxml-6.4, §scxml-5.10).

An event arrives by name from outside the document, and the machine delivers it as
the member of the shorter descriptor the document writes (``request.new`` as
``request``) or, where the document listens with ``event="*"``, as the wildcard
member (``other.thing``): neither member is called what was sent. The copy an
``<invoke autoforward="true">`` child is handed has to carry the name the event
arrived under (``EventMetadata.name``), not the member's.

The machine is ``static_event_wildcard``, generated by
``scripts/regen_static_datamodel_python.sh``, which has no child of its own: the
test marks one active and reads what the policy is asked to forward, which is the
whole of the parent's side of the rule. The same rule is held end to end, with a
child that reads its ``_event.name``, by
``backends/c/tests/integration/test_autoforward_keeps_the_arrival_name.c``.
"""
from __future__ import annotations

import importlib
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
# The tests directory, so this package is importable by the name it has there.
sys.path.insert(0, str(_HERE.parents[1]))
sys.path.insert(0, str(_HERE.parents[2] / "runtime"))
sys.path.insert(0, str(_HERE.parents[2] / "forge-runtime"))

from sce_runtime.invoke import Invoke  # noqa: E402 -- path inserted above


class _InertChild(Invoke):
    """A live child that does nothing: the machine under test declares no invoke,
    and the forward is only asked of an engine that has one running."""

    def start(self, parent_engine) -> None:
        pass

    def tick(self) -> None:
        pass

    def is_done(self) -> bool:
        return False

    def drain_events(self):
        return ()

    def forward_event(self, event_name, metadata) -> None:
        pass

    def cancel(self) -> None:
        pass


def _forwarded(*names: str) -> list[str]:
    """The names the machine asks its policy to forward when each of ``names``
    is delivered to it by name, in turn."""
    module = importlib.import_module("integration.static_datamodel.static_event_wildcard_sm")
    engine = module.create_engine()
    engine.initialize()
    forwarded: list[str] = []
    engine.policy.forward_to_autoforward_children = (
        lambda name, _metadata, _engine: forwarded.append(name)
    )
    engine._active_invokes = {"child": _InertChild()}
    for name in names:
        engine.send_external_by_name(name)
        engine.advance_time(0)
    return forwarded


def test_a_copy_delivered_as_a_shorter_descriptor_is_forwarded_under_the_whole_name() -> None:
    assert _forwarded("request.new") == ["request.new"]


def test_a_copy_delivered_as_the_wildcard_member_is_forwarded_under_the_name_it_arrived_under() -> None:
    assert _forwarded("other.thing", "other") == ["other.thing", "other"]


def test_a_name_the_document_writes_is_forwarded_as_it_is() -> None:
    assert _forwarded("request", "*") == ["request", "*"]
