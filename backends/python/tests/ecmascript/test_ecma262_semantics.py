"""What this backend answers for `datamodel="ecmascript"`, against ECMA-262.

The expectations are not ours. They live in
`tests/ecmascript/ecma262_semantics.json`, one claim per case with the
ECMA-262 clause that backs it, and the Rust, C++, Kotlin and Go readers ask
the same file. A per-backend copy of a table drifts toward the backend that
reads it, which is the blindness the shared table was written to end.

What is different here is where the ECMAScript went. Python never sees it:
the frontend translated the author's source to Lua at build time, so a
generated machine calls `evaluate_expression(session, "_scxml_truthy(a)")`
and this backend's whole contribution to the datamodel is the runtime library
underneath that call — lupa's Lua, the shared `ecma_semantics.lua`, and the
Python natives installed beside it in `_install_ecmascript_builtins`. That is
the layer this measures, and until this file existed nothing did: the shared
semantics file grew a standard library that this backend loaded and no Python
test ever called.

So the emission comes from `tests/ecmascript/ecma262_emitted_lua.json`,
generated by the frontend itself and drift-gated in
`sce-build/tests/ecmascript_semantics.rs`. Handwriting the Lua here would
measure a translation nobody ships.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any, Dict, List, Tuple

from sce_runtime.scripting.i_script_engine import ScriptValueKind
from sce_runtime.scripting.lua_engine import LuaScriptEngine

# The repository root, from this file's own location: the shared table is
# named by the same path every other reader uses.
_REPO_ROOT = Path(__file__).resolve().parents[4]
_TABLE = _REPO_ROOT / "tests" / "ecmascript" / "ecma262_semantics.json"
_EMITTED = _REPO_ROOT / "tests" / "ecmascript" / "ecma262_emitted_lua.json"


def _read(path: Path) -> Dict[str, Any]:
    assert path.is_file(), (
        f"the shared ECMA-262 data is missing at {path}; "
        "this test measures nothing without it"
    )
    return json.loads(path.read_text(encoding="utf-8"))


def _load_cases() -> List[Tuple[Dict[str, Any], Dict[str, str]]]:
    """The table and the emission, paired and cross-checked.

    Two files rather than one because they answer different questions — the
    table says what ECMAScript answers, the emission says what this backend
    is handed — and the pairing is asserted rather than assumed: an emission
    regenerated from a table that has since gained a row would otherwise line
    up case 40 against case 41's answer and report a defect that is really a
    stale file.
    """
    cases = _read(_TABLE)["cases"]
    emitted = _read(_EMITTED)["cases"]

    # A floor, not an equality: adding a case must not have to touch this
    # number, but a table that stopped being read must not pass either.
    assert len(cases) >= 55, (
        f"the shared ECMA-262 table produced only {len(cases)} case(s), "
        "so this is not measuring the corpus it claims to"
    )
    assert len(cases) == len(emitted), (
        f"the table holds {len(cases)} case(s) and the emission {len(emitted)} — "
        "regenerate the emission with `UPDATE_EXPECT=1 cargo test -p sce-build "
        "--test ecmascript_semantics`"
    )
    for index, (case, emission) in enumerate(zip(cases, emitted)):
        assert case["source"] == emission["source"], (
            f"case {index} is `{case['source']}` in the table and "
            f"`{emission['source']}` in the emission — the two files are out of "
            "step, so every answer below would be compared against the wrong claim"
        )
    return list(zip(cases, emitted))


def _answers(actual: Any, expect: Dict[str, Any], source: str) -> bool:
    """An engine may hold a whole number as an integer or as a double, and
    ECMA-262 has one Number type — so both spellings answer a `number` case.
    The same rule the Rust, C++, Kotlin and Go readers apply."""
    if "bool" in expect:
        return actual.kind is ScriptValueKind.BOOL and actual.bool_val == expect["bool"]
    if "number" in expect:
        if actual.kind is ScriptValueKind.INT:
            return math.isclose(actual.int_val, expect["number"], abs_tol=1e-9)
        if actual.kind is ScriptValueKind.DOUBLE:
            return math.isclose(actual.double_val, expect["number"], abs_tol=1e-9)
        return False
    if "string" in expect:
        return (
            actual.kind is ScriptValueKind.STRING
            and actual.string_val == expect["string"]
        )
    # `empty` carries no value of its own — its presence IS the answer, and
    # null and undefined are one answer because ECMAScript's `==` equates them
    # and the SCXML datamodel cannot tell an absent property from a null one.
    if "empty" in expect:
        return actual.kind in (ScriptValueKind.NULL, ScriptValueKind.UNDEFINED)
    # A case whose expectation cannot be read is not a case that passes:
    # reading it as "no answer" would let a typo in a key name retire a case
    # silently, which is the failure mode the shared table exists to remove.
    raise AssertionError(f"case [{source}] names no expected answer")


def _describe(value: Any) -> str:
    if value.kind is ScriptValueKind.STRING:
        return f'"{value.string_val}"'
    if value.kind is ScriptValueKind.BOOL:
        return str(value.bool_val)
    if value.kind is ScriptValueKind.INT:
        return f"{value.int_val} (int)"
    if value.kind is ScriptValueKind.DOUBLE:
        return f"{value.double_val} (double)"
    return value.kind.value


def _describe_expected(expect: Dict[str, Any]) -> str:
    for key in ("bool", "number", "string"):
        if key in expect:
            return str(expect[key])
    if "empty" in expect:
        return "null or undefined"
    return "?"


def test_lupa_answers_what_ecmascript_answers() -> None:
    """Every case, run through the engine a generated Python machine runs on.

    No `importorskip` guard: `lua_engine` imports lupa at module scope, so a
    checkout without it fails collection rather than reporting a pass on a
    backend nothing ran — and the gate that owns this directory checks for
    lupa before it starts, which is where a missing package should be named.
    """
    engine = LuaScriptEngine()
    assert engine.initialize(), "the Lua engine must start"

    # Every case is reported, not just the first: a backend that answers one
    # group wrong and another right is a different problem from one that
    # answers nothing, and the first failure alone cannot tell them apart.
    failures: List[str] = []
    cases = _load_cases()
    for index, (case, emission) in enumerate(cases):
        session = f"ecma262_case_{index}"
        engine.create_session(session)
        try:
            if emission["setup"]:
                try:
                    engine.execute_script(session, emission["setup"])
                except Exception as failure:  # noqa: BLE001 — reported, not raised
                    failures.append(
                        f"[{case['source']}] setup did not run: {failure}\n"
                        f"  emitted: {emission['setup']}"
                    )
                    continue
            try:
                actual = engine.evaluate_expression(session, emission["expression"])
            except Exception as failure:  # noqa: BLE001 — reported, not raised
                failures.append(
                    f"[{case['source']}] failed to evaluate: {failure}\n"
                    f"  emitted: {emission['expression']}"
                )
                continue
            if not _answers(actual, case["expect"], case["source"]):
                failures.append(
                    f"[{case['source']}] answered {_describe(actual)}, ECMAScript "
                    f"says {_describe_expected(case['expect'])} "
                    f"({case['clause']}, {case['group']})\n"
                    f"  emitted: {emission['expression']}"
                )
        finally:
            engine.destroy_session(session)

    assert not failures, (
        f"{len(failures)} of {len(cases)} expressions disagree with ECMA-262 on "
        "this backend.\nA document that declares `datamodel=\"ecmascript\"` "
        "answers what that language answers, whichever backend it was generated "
        "for; one that does not is a portability defect the W3C suite cannot "
        "see, because a suite that is green end to end never asks `0 && x`.\n"
        + "\n".join(failures)
    )
