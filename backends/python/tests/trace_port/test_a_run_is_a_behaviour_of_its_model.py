"""A run of the Python lane, recorded as the trace ``sce-codegen formal traces``
judges a behaviour of the document's model (docs/adr/0115, D4 and D8).

Each W3C case runs one document that ``docs/formal`` has a model of
(``W3CTest388``, ``W3CTest570``, ``W3CTest403c`` over ``AppendixD.tla``),
generated by ``sce-codegen generate-w3c -l python`` into
``backends/python/tests/generated/``, with the engine's trace port set, and holds
what the port was told to the recorded run ``docs/formal/traces.json`` declares
of that model, byte for byte. The judge reads the recorded file, so a run that
moves is seen here first, and a recorded run that no longer is the lane's is
never judged in its place. The Python twin of the Rust lane's
``a_run_is_a_behaviour_of_its_model`` and of the C11 lane's
``c11_a_run_of_test_*_is_the_recorded_run_of_its_model``.

These documents leave a run's steps no choice, so each lane's run of one is the
same run but its lane: the recorded Python run of each is the recorded Rust run
with its lane changed, and a case below holds that too.

Recording again, after a change that moves a run on purpose:
  UPDATE_EXPECT=1 python -m pytest backends/python/tests/trace_port/
then ``sce-codegen formal traces --manifest docs/formal/traces.json``, and read
the diff of the recorded runs.
"""
from __future__ import annotations

import importlib
import os
import sys
from pathlib import Path
from types import ModuleType
from typing import List, Optional, Tuple

import pytest

_TESTS = Path(__file__).resolve().parents[1]
_REPO_ROOT = Path(__file__).resolve().parents[4]
_TRACES = _REPO_ROOT / "docs" / "formal" / "traces"
sys.path.insert(0, str(_TESTS.parent / "runtime"))

from sce_runtime.trace_port import RunTrace, StepKind, TraceStep  # noqa: E402

# The W3C cases ``docs/formal`` has a model of: the id the generator names the
# machine by, and the model its recorded runs are judged against.
_MODELED = [("388", "W3CTest388"), ("570", "W3CTest570"), ("403c", "W3CTest403c")]

# How long a run may take, in the virtual time the engine is driven by, and the
# step it is driven in, as the Rust lane's run waits.
_RUN_LIMIT_MS = 3000
_TICK_MS = 10


def _machine(directory: Path, module: str) -> ModuleType:
    """The generated module ``module`` in ``directory``, imported as the
    generated wrapper beside it imports it."""
    source = directory / f"{module}.py"
    assert source.is_file(), (
        f"{source} is not there: generate it with `sce-codegen generate-w3c -l python` "
        "(the W3C machines) or `scripts/materialize.sh python-integration` (the "
        "integration machines)"
    )
    if str(directory) not in sys.path:
        sys.path.insert(0, str(directory))
    return importlib.import_module(module)


def _w3c_machine(test_id: str) -> ModuleType:
    return _machine(_TESTS / "generated" / f"test{test_id}", f"test{test_id}_sm")


def _computed_event_name_machine() -> ModuleType:
    stem = "a_computed_event_name_is_matched_like_any_other"
    return _machine(_TESTS / "integration" / stem, f"{stem}_sm")


def _drive(engine) -> None:
    """Drive a started engine until the run ends, as the W3C wrapper does."""
    elapsed = 0
    while not engine.reached_final and elapsed < _RUN_LIMIT_MS:
        engine.advance_time(_TICK_MS)
        elapsed += _TICK_MS
    assert engine.reached_final, (
        f"the run reached no final state within {_RUN_LIMIT_MS} ms; "
        f"last leaf={engine.current_state}"
    )


def _run(machine: ModuleType) -> Tuple[RunTrace, object]:
    """The trace port's account of one run of ``machine`` to the end, and the
    engine that ran it."""
    trace = RunTrace()
    engine = machine.create_engine()
    engine.set_trace_port(trace.push)
    engine.initialize()
    _drive(engine)
    return trace, engine


def _recorded_path(model: str, lane: str = "python") -> Path:
    """The recorded run of ``model``'s document by ``lane``, as the traces
    manifest names it."""
    return _TRACES / f"{model}.{lane}.json"


def _holds_to_the_recorded_run(model: str, trace: RunTrace) -> None:
    """Hold ``trace`` to the recorded run of ``model``, or record it again when
    ``UPDATE_EXPECT`` is set."""
    text = trace.to_json()
    path = _recorded_path(model)
    if os.environ.get("UPDATE_EXPECT"):
        path.write_bytes(text.encode("utf-8"))
        return
    assert path.is_file(), (
        f"{path} cannot be read: record it with "
        "`UPDATE_EXPECT=1 python -m pytest backends/python/tests/trace_port/`"
    )
    recorded = path.read_bytes().decode("utf-8")
    assert text == recorded, (
        f"the run of {model} is not the recorded one that `sce-codegen formal traces` judges"
    )


def _starts_and_stops(trace: RunTrace) -> None:
    """The run starts, ends in its pass state, and the interpreter's exit leaves
    that state: the first and the last step a recorded run must hold."""
    steps = trace.steps
    assert steps, "a run has steps"
    assert steps[0].kind is StepKind.START
    last = steps[-1]
    assert last.kind is StepKind.STOP
    assert last.outcome == "pass"
    assert last.exited == ["pass"]


@pytest.mark.parametrize("test_id, model", _MODELED, ids=[model for _, model in _MODELED])
def test_a_run_of_a_modeled_w3c_document_is_the_recorded_run_of_its_model(
    test_id: str, model: str
) -> None:
    trace, engine = _run(_w3c_machine(test_id))
    assert str(engine.terminal_state) == "pass"
    _starts_and_stops(trace)
    _holds_to_the_recorded_run(model, trace)


@pytest.mark.parametrize("model", [model for _, model in _MODELED])
def test_each_recorded_run_is_the_rust_lanes_but_its_lane(model: str) -> None:
    """Each document allows one run, so the Python lane's recorded run of it is
    the Rust lane's, byte for byte, but the lane it names."""
    rust = _recorded_path(model, "rust").read_bytes().decode("utf-8")
    rust_lane = '\n  "lane": "rust",\n'
    assert rust.count(rust_lane) == 1, f"the Rust run of {model} names its lane once"
    python = _recorded_path(model).read_bytes().decode("utf-8")
    assert python == rust.replace(rust_lane, '\n  "lane": "python",\n'), (
        f"the Python run of {model} is not the Rust run with its lane changed"
    )


def test_a_run_that_ended_tells_no_second_stop() -> None:
    """The exit of the interpreter is a step once per run: driving or stopping a
    run that ended, which exits nothing, tells the port nothing more."""
    trace, engine = _run(_w3c_machine("388"))
    told = len(trace.steps)
    engine.advance_time(_TICK_MS)
    engine.stop()
    assert len(trace.steps) == told
    assert [step.kind for step in trace.steps].count(StepKind.STOP) == 1


def test_a_stopped_run_is_a_stop_that_names_no_outcome() -> None:
    """A run the host stops before it ends is exited by a stop step that exits
    every active state in reverse document order and ends in no top-level
    final state."""
    machine = _computed_event_name_machine()
    trace = RunTrace()
    engine = machine.create_engine()
    engine.set_trace_port(trace.push)
    engine.initialize()
    assert not engine.reached_final, "the run waits for its delayed sends"
    policy = engine.policy
    active = [
        policy.get_state_name(state)
        for state in sorted(engine.active_configuration(), key=policy.get_document_order)
    ]
    assert trace.steps[-1].configuration == active
    engine.stop()
    last = trace.steps[-1]
    assert last.kind is StepKind.STOP
    assert last.outcome is None
    assert last.exited == list(reversed(active))
    assert last.configuration == []


def test_an_event_step_names_the_event_by_the_name_it_was_sent_under() -> None:
    """An event step names its event by the name ``_event.name`` holds while it
    is taken, which the run trace format defines the field as: the whole name it
    was sent under, and not the event of the document a door resolved it to
    (``request``, or the wildcard). The document sends six events whose names
    it computes, three to its external queue and three to its internal one, as
    the Rust lane's ``an_event_step_names_the_event_by_the_name_it_was_sent_under``
    and the C11 lane's ``c11_integration_trace_port`` hold of the same
    document."""
    trace, engine = _run(_computed_event_name_machine())
    assert str(engine.terminal_state) == "pass"
    _starts_and_stops(trace)
    events: List[Tuple[StepKind, Optional[str]]] = [
        (step.kind, step.event)
        for step in trace.steps
        if step.kind in (StepKind.INTERNAL, StepKind.EXTERNAL)
    ]
    assert events == [
        (StepKind.EXTERNAL, "request.new"),
        (StepKind.EXTERNAL, "other.thing"),
        (StepKind.INTERNAL, "request.again"),
        (StepKind.INTERNAL, "last.one"),
        (StepKind.INTERNAL, "request.third"),
        (StepKind.EXTERNAL, "last.two"),
    ]


def test_a_cleared_port_is_told_nothing_and_the_run_is_the_same() -> None:
    """A port set and then cleared is told nothing, and the run is the one an
    engine that never had one makes."""
    told: List[TraceStep] = []
    engine = _w3c_machine("388").create_engine()
    engine.set_trace_port(told.append)
    engine.clear_trace_port()
    engine.initialize()
    _drive(engine)
    assert str(engine.terminal_state) == "pass"
    assert told == []
