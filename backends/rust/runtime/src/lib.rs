// SCE Protocol-Synthesis RFC §synth-5-J-2 (C3 Atomic B-β): cfg-assert the
// incompatible feature combinations at compile time. The `no_std`
// feature is mutually exclusive with `http-send` (tokio/reqwest are
// std-coupled) and with both script-engine features (Lua and QuickJS
// require `alloc`, which `no_std` forbids per spec line 1989 zero-
// alloc mandate). `compile_error!` fires a clear, actionable message
// before the build reaches its first std-coupled symbol — without
// this guard a misconfigured Cargo profile would otherwise surface as
// "cannot find type `Vec` in module `core`" deep in the std-coupled
// modules, which is the textbook silent-broken-hook anti-pattern.
#[cfg(all(feature = "no_std", feature = "http-send"))]
compile_error!(
    "`no_std` and `http-send` are mutually exclusive: tokio/reqwest are std-coupled. \
     Either drop `http-send` (and any `<send type=\"BasicHTTPEventProcessor\">` from \
     your SCXML), or drop `no_std`. SCE Protocol-Synthesis RFC §5.J.2 line 1983."
);

// ── Bounded-collection type aliases (SCE Protocol-Synthesis RFC §synth-5-J-2) ──────
//
// Under `--features=no_std` the runtime crate is `#![no_std]` with **no
// `alloc` dependency** per spec line 1989-1994 ("zero `alloc`
// dependency"). String-typed event payload fields (`_event.data`,
// `_event.sendid`, `_event.origin`, `_event.origintype`,
// `_event.invokeid`) bound their capacity at `MAX_EVENT_STRING_LEN`
// bytes. `SceString` is `std::string::String` under the default std
// build (unchanged API) and `heapless::String<MAX_EVENT_STRING_LEN>`
// under `--features=no_std` (stack-allocated, `Result`-returning
// `push_str`). 256 is the v1 cap, sized to fit RFC §synth-5-D telemetry-event
// payloads + an origin URI without truncation; per-document tunable via
// `<scxml sce:event-string-capacity="N">` is deferred until a consumer
// surfaces a documented overflow.
//
// Pattern mirrors the §synth-5-D event-queue capacity (`EVENT_QUEUE_CAPACITY`
// emitted from codegen via `<sce:capacity>` per B-γ1) plus B-γ2b's
// microstep-dedup cap (`heapless::FnvIndexSet<_, 64>` reasoned
// constant). A per-document override is a codegen change, not a
// runtime one: the codegen would grow a parallel
// `EVENT_STRING_CAPACITY` const and this alias becomes generic over
// it. Fixing the constant here keeps every no_std document at one
// size until a document actually needs two.

/// Default no_std FIFO depth for a machine that declares no event-queue
/// capacity (internal + external queues).
///
/// This is the **default** for the const generic `N` on
/// [`EventQueueManager`] — *not*
/// a crate-wide cap. A machine's queue depth is per-machine: codegen resolves
/// `<scxml sce:capacity="N">` / deploy `default_event_queue_capacity` into the
/// generated `EVENT_QUEUE_CAPACITY` and emits it as the policy's
/// [`StatePolicy::EventQueue`] type argument, so
/// the bound's single source of truth is the machine. Only when a document
/// declares no capacity does the bare `EventQueueManager<T>` fall back to this
/// value. (The earlier deferral that cited a `generic_const_exprs` requirement
/// is resolved: the per-machine size rides as a literal in the generated
/// associated type, which needs no unstable feature.)
///
/// Distinct from [`MAX_SCHEDULED_EVENTS`] — the queue holds events *waiting to
/// be processed*, while the scheduler holds events *waiting on a delay timer*.
///
/// Value 64 covers typical statechart microstep depth: W3C SCXML Appendix D
/// drains the internal queue between external events, so the peak depth is the
/// maximum chained `<raise>` count in a single macrostep. The W3C 202 test
/// corpus tops out at ~16 chained raises (test 224's `done.invoke.*` fan-out);
/// 64 gives a ~4× margin. (Note: each `EventWithMetadata` is ~1.6 KiB — the
/// W3C `_event` metadata strings dominate — so 64-deep queues are *not* cheap
/// on an MCU; this is exactly why capacity-declaring machines size down via
/// `<sce:capacity>`.)
///
/// The std build's [`EventQueueManager`] keeps `std::collections::VecDeque<T>`
/// (unbounded, the spec's `Queue`) so this constant only affects the `--features=no_std` variant.
pub const MAX_EVENT_QUEUE_DEPTH: usize = 64;

/// Maximum number of simultaneously-pending delayed events in the no_std
/// [`PullScheduler`](crate::engine::PullScheduler) ring.
///
/// Bounds the `heapless::Vec<ScheduledEntry<E>, _>` capacity of the no_std
/// variant of the scheduler. `<send delay>` author surface; this is the
/// in-flight delay-pending dimension, distinct from the event queue capacity
/// (`<sce:capacity>` populates `EVENT_QUEUE_CAPACITY` per-document for the
/// ready-to-process queue — that's a different dimension).
///
/// v1 value 32 covers typical statechart in-flight `<send delay>` parallelism
/// (1-5 simultaneous timers in the W3C 202 test corpus) with a ~6× safety
/// margin. Profiler-driven per-document tunable (via a future
/// `StatePolicy::SCHEDULER_CAPACITY: usize` associated const + matching
/// `<sce:scheduler-capacity>` parser surface, mirroring B-γ1's `<sce:capacity>`
/// architecture) is not built because its input does not exist: the
/// right per-document number comes from a profile of that document's
/// in-flight timer count, and the corpus measurement above is the only
/// profile SCE has. A tunable whose value would still be guessed adds
/// a knob without adding an answer.
///
/// ## Per-entry footprint (no_std)
///
/// Each `ScheduledEntry`'s two `heapless::String<256>` fields (~264 B each)
/// are removed under no_std unless load-bearing:
///
/// - The delayed-send `event_data` JSON string is **elided** profile-wide:
///   the no_std build has no script engine and the scheduler drain discards
///   the data string anyway (see the `ScheduledEntry` doc-comment in
///   `engine.rs`), so removal has no behavioral effect.
/// - The `send_id` cancel key is **per-machine**: it is read only by
///   `PullScheduler::cancel_event` (§scxml-6.3 `<cancel sendid>` matches
///   by send id), so codegen selects the zero-size [`ElidedSendId`] via the
///   `StatePolicy::ScheduledSendId` associated type (mirroring the
///   `EventQueue` associated type) for documents with no `<cancel>`, and the
///   load-bearing `SceString` otherwise.
///
/// A cancel-free entry thus carries only the event value and its `ready_at`
/// time-point; the ring remains the largest single `Engine` contributor under
/// no_std, but at hundreds of bytes rather than kilobytes.
///
/// The std build's `PullScheduler` keeps `Vec<ScheduledEntry<E>>` (unbounded)
/// so this constant only affects the `--features=no_std` variant.
pub const MAX_SCHEDULED_EVENTS: usize = 32;

/// Maximum number of simultaneously-enabled transitions selected in a single
/// microstep under `--features=no_std`.
///
/// The no_std bound baked into the [`SceTransitionBuf`] / [`SceIndexBuf`]
/// aliases (`heapless::Vec<_, MAX_ENABLED_TRANSITIONS>`), which the
/// parallel-state transition algorithm uses for its conflict-resolution
/// buffers (`tools/codegen/templates/rust/{process_transition,conflict_resolution}.rs.jinja2`).
/// §scxml-D-selectTransitions selects at most one enabled transition per active
/// atomic state, and the active configuration is itself bounded by
/// [`crate::helpers::hierarchy::MAX_HIERARCHY_DEPTH`] (16), so the enabled set
/// cannot exceed that. v1 value 32 gives a 2× margin.
///
/// The std build keeps unbounded `Vec` so this constant only affects the
/// `--features=no_std` variant. Per-document tunable deferred until an MCU
/// consumer surfaces a concrete over/under-fit signal (`feedback_planned_not_yagni`).
pub const MAX_ENABLED_TRANSITIONS: usize = 32;

/// Capacity of the microstep transition-dedup set under `--features=no_std`.
///
/// The dedup set is the [`SceDedupSet`] alias (insert via [`dedup_insert`]):
/// `std::collections::HashSet` under std, `heapless::FnvIndexSet<_,
/// MAX_MICROSTEP_DEDUP_SLOTS>` under no_std, whose capacity must be a power of
/// two. 64 is the next power of two above 2× [`MAX_ENABLED_TRANSITIONS`], so
/// the set never rehashes-to-full for any microstep the buffers above can hold.
pub const MAX_MICROSTEP_DEDUP_SLOTS: usize = 64;

/// Maximum byte length of an event metadata string under `--features=no_std`.
///
/// Bounds the capacity of [`SceString`] for `EventMetadata.data`,
/// `EventMetadata.send_id`, `EventMetadata.origin`, `EventMetadata.origin_type`,
/// and `EventMetadata.invoke_id`. The std build's `SceString = String` is
/// unbounded; this constant only affects the no_std variant.
///
/// v1 value 256 covers §scxml-5.10.1 platform-event payloads + send-target
/// URIs without truncation. Author-tunable cap deferred to a future atomic
/// once an MCU consumer surfaces a concrete overflow signal (per
/// `feedback_planned_not_yagni` discipline — capacities ride consumer
/// signal, not speculation).
pub const MAX_EVENT_STRING_LEN: usize = 256;

/// Owned-string type used for event metadata fields across both std and
/// no_std builds.
///
/// - std build: `std::string::String` (unbounded, heap-allocated).
/// - no_std build: `heapless::String<MAX_EVENT_STRING_LEN>` (stack-allocated,
///   `push_str` is `Result`-returning).
///
/// Construction sites that need to convert from `&str` to `SceString` should
/// use [`sce_string_from_str`] which abstracts the API divergence.
#[cfg(not(feature = "no_std"))]
pub type SceString = ::std::string::String;
/// no_std variant of [`SceString`]: stack-allocated `heapless::String` capped
/// at [`MAX_EVENT_STRING_LEN`]. See the std-variant doc-comment above for the
/// full contract.
#[cfg(feature = "no_std")]
pub type SceString = ::heapless::String<MAX_EVENT_STRING_LEN>;

/// Owned byte-sequence type for typed `_event.data` payload fields whose
/// `sce:type="bytes"` carries a per-field `sce:max-size` bound.
///
/// This is the SAME concept the codec runtime needs for `{Codec}Owned` byte
/// fields, so the definition lives once in the shared `sce-portable-bytes`
/// crate and is re-exported here — `sce_rust_runtime::SceBytes` and
/// `sce_forge_runtime::codec::SceBytes` are now literally the same type, and
/// the construction logic (the fallible no-alloc copy) cannot drift between
/// the two runtimes.
///
/// The const parameter `N` is the field's declared `sce:max-size` (defaulted
/// to the codegen `BYTES_DEFAULT_MAX` when the author omits it). Because `N`
/// rides on the newtype rather than being erased to a bare `Vec<u8>` alias,
/// a consumer hand-assembling a typed payload (`raise_<event>(payload)`)
/// infers the cap from the field — `SceBytes::from_slice(&v)?` — instead of
/// hardcoding it.
///
/// - std / `alloc`: wraps `Vec<u8>` (unbounded, `N` advisory).
/// - `no_std` build (`--no-default-features --features=no_std`, which drops
///   the `backends/rust/portable-bytes/alloc` default): wraps `heapless::Vec<u8, N>`,
///   capacity exactly the author's bound; `from_slice` is fallible past `N`.
///
/// Derefs to `[u8]`, so `&payload.<field>` coerces to the `&[u8]` a generated
/// `Actions` trait method takes regardless of profile.
pub use sce_portable_bytes::SceBytes;

/// Convert a borrowed `&str` into an owned [`SceString`].
///
/// Under std this is `s.to_string()`. Under no_std this is
/// `heapless::String::try_from(s).unwrap_or_default()` — strings longer than
/// [`MAX_EVENT_STRING_LEN`] truncate to empty rather than panic, matching the
/// behavior `unwrap_or_default` provides on the std side for malformed inputs.
/// Callers that need to detect the truncation should use heapless's `try_from`
/// directly under `cfg(feature = "no_std")`.
#[inline]
pub fn sce_string_from_str(s: &str) -> SceString {
    #[cfg(not(feature = "no_std"))]
    {
        s.to_string()
    }
    #[cfg(feature = "no_std")]
    {
        SceString::try_from(s).unwrap_or_default()
    }
}

/// Conflict-resolution transition buffer for the W3C Appendix D.2 microstep,
/// resolving to the natural collection of each runtime profile.
///
/// - std build: [`std::vec::Vec<T>`] (unbounded, heap-allocated).
/// - no_std build: `heapless::Vec<T, MAX_ENABLED_TRANSITIONS>` (stack-allocated).
///
/// The capacity is global (every microstep is bounded by the same enabled-set
/// limit), so it is baked into the alias rather than carried as a generic const
/// — mirroring [`StateChain`](crate::helpers::hierarchy::StateChain), which
/// bakes [`crate::helpers::hierarchy::MAX_HIERARCHY_DEPTH`]. Push through
/// [`BoundedPush::push_bounded`]; clone a slice through [`bounded_clone_slice`].
#[cfg(not(feature = "no_std"))]
pub type SceTransitionBuf<T> = ::std::vec::Vec<T>;
/// no_std variant of [`SceTransitionBuf`]. See the std-variant doc-comment.
#[cfg(feature = "no_std")]
pub type SceTransitionBuf<T> = ::heapless::Vec<T, MAX_ENABLED_TRANSITIONS>;

/// Index buffer (transition positions) for the Appendix D.2 conflict pass, the
/// `usize` twin of [`SceTransitionBuf`]. Same per-profile resolution and cap.
#[cfg(not(feature = "no_std"))]
pub type SceIndexBuf = ::std::vec::Vec<usize>;
/// no_std variant of [`SceIndexBuf`]. See the std-variant doc-comment.
#[cfg(feature = "no_std")]
pub type SceIndexBuf = ::heapless::Vec<usize, MAX_ENABLED_TRANSITIONS>;

/// Dedup set for transitions bubbling up to a shared ancestor (§scxml-3.13;
/// test 504), resolving to the natural set type of each runtime profile.
///
/// - std build: [`std::collections::HashSet<K>`] (unbounded).
/// - no_std build: `heapless::FnvIndexSet<K, MAX_MICROSTEP_DEDUP_SLOTS>`
///   (stack-allocated; capacity is a power of two per heapless's requirement).
///
/// Insert through [`dedup_insert`], which absorbs the `bool` vs `Result` API
/// divergence between the two set types and fails loud on no_std overflow.
#[cfg(not(feature = "no_std"))]
pub type SceDedupSet<K> = ::std::collections::HashSet<K>;
/// no_std variant of [`SceDedupSet`]. See the std-variant doc-comment.
#[cfg(feature = "no_std")]
pub type SceDedupSet<K> = ::heapless::FnvIndexSet<K, MAX_MICROSTEP_DEDUP_SLOTS>;

/// Push into a microstep buffer uniformly under std and no_std.
///
/// Method form (not a free function) so generated call sites work through an
/// `&mut &mut Buf` collector binding via receiver auto-reborrow. Implemented
/// for both the std `Vec<T>` and the no_std `heapless::Vec<T, N>`, so it covers
/// the transition-count-bounded conflict-resolution buffers
/// (`TransitionList` / `IndexList`). Under no_std the push fails loud on
/// overflow — the capacity ([`MAX_ENABLED_TRANSITIONS`]) is sized to the W3C
/// Appendix D.2 enabled-set bound, so overflow indicates a capacity to raise,
/// not a recoverable condition. Mirrors the depth-bounded
/// [`crate::helpers::hierarchy::push_chain`] for `StateChain`.
pub trait BoundedPush<T> {
    /// Append `item`, panicking on a no_std capacity overflow (see trait docs).
    fn push_bounded(&mut self, item: T);
}

#[cfg(not(feature = "no_std"))]
impl<T> BoundedPush<T> for ::std::vec::Vec<T> {
    #[inline]
    fn push_bounded(&mut self, item: T) {
        self.push(item);
    }
}

#[cfg(feature = "no_std")]
impl<T, const N: usize> BoundedPush<T> for ::heapless::Vec<T, N> {
    #[inline]
    fn push_bounded(&mut self, item: T) {
        if self.push(item).is_err() {
            panic!(
                "SCE no_std microstep buffer overflow (capacity {N}); raise the \
                 relevant capacity constant (MAX_ENABLED_TRANSITIONS)"
            );
        }
    }
}

/// Insert `key` into a [`SceDedupSet`] uniformly under std and no_std, returning
/// `true` if the key was newly inserted (the §scxml-3.13 first-match-wins
/// dedup predicate for `retain`).
///
/// Absorbs the API divergence between the two set types: `HashSet::insert`
/// returns `bool`, while `heapless::FnvIndexSet::insert` returns
/// `Result<bool, K>` (handing back the key when the set is full). Under no_std
/// an overflow fails loud — the capacity ([`MAX_MICROSTEP_DEDUP_SLOTS`]) is
/// sized above the Appendix D.2 enabled-set bound, so a full set indicates a
/// capacity to raise, not a recoverable condition (silently dropping would
/// violate microstep semantics). Mirrors [`BoundedPush::push_bounded`].
#[cfg(not(feature = "no_std"))]
#[inline]
pub fn dedup_insert<K: Eq + ::core::hash::Hash>(set: &mut SceDedupSet<K>, key: K) -> bool {
    set.insert(key)
}

/// no_std variant of [`dedup_insert`]. See the std-variant doc-comment.
#[cfg(feature = "no_std")]
#[inline]
pub fn dedup_insert<K: Eq + ::core::hash::Hash>(set: &mut SceDedupSet<K>, key: K) -> bool {
    set.insert(key).unwrap_or_else(|_| {
        panic!(
            "SCE no_std microstep dedup-set overflow (capacity {}); raise \
             MAX_MICROSTEP_DEDUP_SLOTS",
            MAX_MICROSTEP_DEDUP_SLOTS
        )
    })
}

/// Clone a slice into an owned microstep buffer uniformly under std and no_std.
///
/// Under std this is `[T]::to_vec`. Under no_std this is
/// `heapless::Vec::from_slice` with the same fail-loud overflow contract as
/// [`BoundedPush::push_bounded`]. Used by the Appendix D.2 microstep executor to take an
/// owned, re-sortable copy of the enabled-transition slice.
#[cfg(not(feature = "no_std"))]
#[inline]
pub fn bounded_clone_slice<T: Clone>(src: &[T]) -> ::std::vec::Vec<T> {
    src.to_vec()
}

/// no_std variant of [`bounded_clone_slice`]. See the std-variant doc-comment.
#[cfg(feature = "no_std")]
#[inline]
pub fn bounded_clone_slice<T: Clone, const N: usize>(src: &[T]) -> ::heapless::Vec<T, N> {
    ::heapless::Vec::from_slice(src).unwrap_or_else(|_| {
        panic!(
            "SCE no_std transition buffer overflow (capacity {N}); raise \
             MAX_ENABLED_TRANSITIONS"
        )
    })
}

/// Stable in-place sort by a comparator, uniform across std and no_std.
///
/// Under std this is `[T]::sort_by`. Under no_std it is a stable in-place
/// insertion sort — `[T]::sort_by` requires `alloc` for its merge buffer, which
/// a no-allocator no_std build cannot provide. The W3C Appendix D.2 microstep
/// sorts states/transitions whose count is bounded by `MAX_HIERARCHY_DEPTH` /
/// [`MAX_ENABLED_TRANSITIONS`], so the O(n²) insertion sort is negligible. Both
/// variants are stable, so generated machines sort identically under std and
/// no_std (preserving W3C document-order tie-breaking among same-source
/// transitions).
#[cfg(not(feature = "no_std"))]
#[inline]
pub fn stable_sort_by<T, F: FnMut(&T, &T) -> ::core::cmp::Ordering>(buf: &mut [T], compare: F) {
    buf.sort_by(compare);
}

/// no_std variant of [`stable_sort_by`]. See the std-variant doc-comment.
#[cfg(feature = "no_std")]
pub fn stable_sort_by<T, F: FnMut(&T, &T) -> ::core::cmp::Ordering>(buf: &mut [T], mut compare: F) {
    for i in 1..buf.len() {
        let mut j = i;
        while j > 0 && compare(&buf[j - 1], &buf[j]) == ::core::cmp::Ordering::Greater {
            buf.swap(j - 1, j);
            j -= 1;
        }
    }
}

/// Stable in-place sort by an extracted key, uniform across std and no_std.
///
/// Under std this is `[T]::sort_by_key`; under no_std it delegates to the
/// insertion-sort [`stable_sort_by`]. See that function's doc-comment.
#[cfg(not(feature = "no_std"))]
#[inline]
pub fn stable_sort_by_key<T, K: Ord, F: FnMut(&T) -> K>(buf: &mut [T], f: F) {
    buf.sort_by_key(f);
}

/// no_std variant of [`stable_sort_by_key`]. See the std-variant doc-comment.
#[cfg(feature = "no_std")]
#[inline]
pub fn stable_sort_by_key<T, K: Ord, F: FnMut(&T) -> K>(buf: &mut [T], mut f: F) {
    stable_sort_by(buf, |a, b| f(a).cmp(&f(b)));
}

