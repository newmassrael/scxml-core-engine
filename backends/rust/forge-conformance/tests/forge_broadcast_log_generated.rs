//! The broadcast-log kind's generated module (ADR 0062), compiled and run.
//!
//! `sce-build`'s tests read what the generator writes for a log and compare
//! text, which shows the module says the right things and not that the names in
//! it are the names `sce-forge-runtime` has, or that the bytes it packs into a
//! slot read back as the element that was published. Here the modules the
//! generator writes for two logs are compiled into this test binary over the
//! element codecs they name, and the typed `publish` and `read` they define are
//! used, on one thread: a rename in the runtime, a width the template computes
//! wrongly, or a byte packed into the wrong word stops the build or fails an
//! assertion. What a log does under several threads is the runtime row's own
//! test (`forge_broadcast_log.rs`) and is not repeated here.
//!
//! Generated by `build.rs` Step 8 into OUT_DIR, from the document set and not
//! document by document: a slot is sized from the element document. The codec
//! crate's `alloc` feature is needed for the owned element's `encode_to_vec`, as
//! in the other generated-fixture tests; the log itself needs no allocation.
#![cfg(feature = "alloc")]

mod log_modules {
    // The generated modules open with `#![allow(...)]`, which `build.rs`
    // strips because an inner attribute cannot sit at an `include!` point; each
    // module carries them as outer attributes. `dead_code` is added: a
    // generated module's constants are its public contract, and are unused only
    // because this test includes it into a private module.
    #[allow(clippy::all, unused_imports, dead_code)]
    pub mod broadcast_log_conformance_event {
        include!(concat!(
            env!("OUT_DIR"),
            "/broadcast_log_conformance_event.rs"
        ));
    }
    #[allow(clippy::all, unused_imports, dead_code)]
    pub mod broadcast_log_conformance_record {
        include!(concat!(
            env!("OUT_DIR"),
            "/broadcast_log_conformance_record.rs"
        ));
    }
    #[allow(clippy::all, unused_imports, dead_code)]
    pub mod broadcast_log_conformance_literal {
        include!(concat!(
            env!("OUT_DIR"),
            "/broadcast_log_conformance_literal.rs"
        ));
    }
    #[allow(clippy::all, unused_imports, dead_code)]
    pub mod broadcast_log_conformance_deployed {
        include!(concat!(
            env!("OUT_DIR"),
            "/broadcast_log_conformance_deployed.rs"
        ));
    }
}

use log_modules::broadcast_log_conformance_deployed as deployed;
use log_modules::broadcast_log_conformance_event::BroadcastLogConformanceEvent;
use log_modules::broadcast_log_conformance_literal as literal;
use log_modules::broadcast_log_conformance_literal::BroadcastLogConformanceLiteralRead as Read;
use log_modules::broadcast_log_conformance_record::BroadcastLogConformanceRecord;
use sce_forge_runtime::codec::CodecError;

fn event(sensor_id: u8, value: u16) -> BroadcastLogConformanceEvent {
    BroadcastLogConformanceEvent { sensor_id, value }
}

// ─── The contract the modules state ───

#[test]
fn the_literal_log_states_its_retention_and_sizes_its_slots_from_its_element() {
    assert_eq!(literal::RETENTION, 3, "<sce:retention entries=\"3\"/>");
    assert_eq!(
        literal::SLOTS,
        4,
        "one more than the retention: the slot being overwritten is in flux"
    );
    // The element is an 8-bit id and a 16-bit value: 1 + 2 = 3 bytes.
    assert_eq!(literal::MAX_ENCODED_BYTES, 3);
    // One length word, then ceil(3 / 8) = 1 word of bytes.
    assert_eq!(literal::WORDS, 2);
    assert_eq!(literal::DECLARED_PROGRESS, "wait-free");
}

#[test]
fn the_deployed_log_takes_its_retention_from_the_deploy_and_its_size_from_the_element() {
    // `build.rs` gives machine mcu_node the limit `event_retention: 5`.
    assert_eq!(deployed::RETENTION, 5);
    assert_eq!(deployed::SLOTS, 6);
    // A one-byte tag and a payload of at most eight bytes: 1 + 8 = 9 bytes.
    assert_eq!(deployed::MAX_ENCODED_BYTES, 9);
    // One length word, then ceil(9 / 8) = 2 words of bytes: 1 + 2 = 3.
    assert_eq!(deployed::WORDS, 3);
    assert_eq!(deployed::DECLARED_PROGRESS, "wait-free");
}

// ─── The log it defines is the log the runtime has ───

#[test]
fn entries_come_back_whole_and_in_order_through_the_typed_functions() {
    let log = literal::BroadcastLogConformanceLiteral::new();
    let mut publisher = log.publisher().expect("the first publisher");
    let mut reader = log.reader_oldest();
    assert_eq!(literal::read(&log, &mut reader), Ok(Read::Empty));

    // Values that fill every byte of the packed word and differ in each.
    let sent = [event(1, 0x0102), event(2, 0xFFEE), event(255, 0)];
    for (n, element) in sent.iter().enumerate() {
        assert_eq!(
            literal::publish(&mut publisher, element),
            Ok(n as u64),
            "an entry takes the next sequence number"
        );
    }
    for (n, element) in sent.iter().enumerate() {
        assert_eq!(
            literal::read(&log, &mut reader),
            Ok(Read::Item {
                seq: n as u64,
                element: element.clone()
            }),
            "entry {n} comes back whole, in the order it was published"
        );
    }
    assert_eq!(literal::read(&log, &mut reader), Ok(Read::Empty));
    assert_eq!(reader.lost(), 0, "a reader that kept up lost nothing");
}

#[test]
fn a_reader_the_publisher_laps_is_told_how_many_it_missed_and_resumes_at_the_oldest() {
    let log = literal::BroadcastLogConformanceLiteral::new();
    let mut publisher = log.publisher().expect("the first publisher");
    let mut slow = log.reader_oldest();

    // Six entries, sequence numbers 0 to 5, into a log that retains three: the
    // window is [6 - 3, 6) = [3, 6), so the reader at 0 missed 3 - 0 = 3.
    for n in 0..6u16 {
        literal::publish(&mut publisher, &event(9, n)).expect("an entry within the bound");
    }
    assert_eq!(
        literal::read(&log, &mut slow),
        Ok(Read::Lagged { skipped: 3 })
    );
    assert_eq!(slow.cursor(), 3, "it resumes at the oldest entry held");
    assert_eq!(slow.lost(), 3);

    for n in 3..6u16 {
        assert_eq!(
            literal::read(&log, &mut slow),
            Ok(Read::Item {
                seq: u64::from(n),
                element: event(9, n)
            })
        );
    }
    assert_eq!(literal::read(&log, &mut slow), Ok(Read::Empty));
    assert_eq!(slow.lost(), 3, "reading what is held loses nothing more");
}

#[test]
fn two_readers_keep_separate_cursors() {
    let log = literal::BroadcastLogConformanceLiteral::new();
    let mut publisher = log.publisher().expect("the first publisher");
    literal::publish(&mut publisher, &event(1, 10)).expect("sequence 0");
    literal::publish(&mut publisher, &event(2, 20)).expect("sequence 1");

    // Opened at the oldest entry held (0, as nothing was forgotten) and at
    // sequence 1.
    let mut first = log.reader_oldest();
    let mut second = log.reader_at(1);
    let mut late = log.reader_head();

    assert_eq!(
        literal::read(&log, &mut first),
        Ok(Read::Item {
            seq: 0,
            element: event(1, 10)
        })
    );
    assert_eq!(first.cursor(), 1);
    assert_eq!(second.cursor(), 1, "reading with one reader moves no other");

    assert_eq!(
        literal::read(&log, &mut second),
        Ok(Read::Item {
            seq: 1,
            element: event(2, 20)
        })
    );
    assert_eq!(
        literal::read(&log, &mut first),
        Ok(Read::Item {
            seq: 1,
            element: event(2, 20)
        }),
        "the entry the second reader took is still there for the first"
    );
    assert_eq!(literal::read(&log, &mut first), Ok(Read::Empty));
    assert_eq!(literal::read(&log, &mut second), Ok(Read::Empty));

    // A reader opened at the head sees only what is published after it.
    assert_eq!(literal::read(&log, &mut late), Ok(Read::Empty));
    literal::publish(&mut publisher, &event(3, 30)).expect("sequence 2");
    assert_eq!(
        literal::read(&log, &mut late),
        Ok(Read::Item {
            seq: 2,
            element: event(3, 30)
        })
    );
}

// ─── What the element's bound does ───

#[test]
fn an_element_larger_than_its_bound_is_refused_by_the_codec_and_not_truncated() {
    let log = deployed::BroadcastLogConformanceDeployed::new();
    let mut publisher: deployed::BroadcastLogConformanceDeployedPublisher<'_> =
        log.publisher().expect("the first publisher");

    // 1 + 20 = 21 bytes into a log whose entries hold at most 9.
    let too_long = [0xAAu8; 20];
    let refused = deployed::publish(
        &mut publisher,
        &BroadcastLogConformanceRecord {
            tag: 1,
            payload: &too_long,
        },
    );
    assert!(
        refused.is_err(),
        "a payload past its declared bound is refused: {refused:?}"
    );
    assert_eq!(log.head(), 0, "a refused element publishes nothing");

    // Exactly the bound, and under it: the length word keeps what was written.
    let full = [1u8, 2, 3, 4, 5, 6, 7, 8];
    let short = [7u8, 7, 7];
    assert_eq!(
        deployed::publish(
            &mut publisher,
            &BroadcastLogConformanceRecord {
                tag: 0x5A,
                payload: &full
            }
        ),
        Ok(0)
    );
    assert_eq!(
        deployed::publish(
            &mut publisher,
            &BroadcastLogConformanceRecord {
                tag: 0x5B,
                payload: &short
            }
        ),
        Ok(1)
    );

    // The log hands the record back as its owned form, which encodes to the
    // bytes that were stored.
    let mut reader = log.reader_oldest();
    let mut stored: Vec<Vec<u8>> = Vec::new();
    loop {
        match deployed::read(&log, &mut reader) {
            Ok(deployed::BroadcastLogConformanceDeployedRead::Item { element, .. }) => {
                stored.push(element.encode_to_vec().expect("the owned record encodes"));
            }
            Ok(deployed::BroadcastLogConformanceDeployedRead::Empty) => break,
            other => panic!("unexpected answer: {other:?}"),
        }
    }
    assert_eq!(
        stored,
        vec![vec![0x5A, 1, 2, 3, 4, 5, 6, 7, 8], vec![0x5B, 7, 7, 7],]
    );
}

#[test]
fn a_stored_length_above_the_bound_is_a_codec_error_and_never_a_slice() {
    // The runtime row takes any words, so an entry whose length word is not one
    // this log wrote (a corrupt slot, a log of another size) can be offered to the
    // typed read. A length of MAX_ENCODED_BYTES + 1 is the nearest; the largest
    // `u64` is the one a cast to `usize` would wrap.
    for stored in [literal::MAX_ENCODED_BYTES as u64 + 1, u64::MAX] {
        let log = literal::BroadcastLogConformanceLiteral::new();
        let mut publisher = log.publisher().expect("the first publisher");
        let mut entry = [0u64; literal::WORDS];
        entry[0] = stored;
        publisher.publish(&entry);

        let mut reader = log.reader_oldest();
        assert_eq!(
            literal::read(&log, &mut reader),
            Err(CodecError::LengthOutOfRange),
            "stored length {stored}"
        );
        assert_eq!(reader.cursor(), 1, "the reader moved past the entry");
    }
}
