fn event(sensor_id: u8, value: u16) -> QueueConformanceEvent {
    QueueConformanceEvent { sensor_id, value }
}

fn pair(e: &QueueConformanceEvent) -> (u8, u16) {
    (e.sensor_id, e.value)
}

