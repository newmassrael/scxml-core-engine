#[test]
fn the_lamport_ring_hands_elements_over_in_order_and_refuses_when_full() {
    let mut q = spsc::QueueConformanceSpsc::new();
    let (mut producer, mut consumer) = q.split();

    assert!(consumer.try_pop().is_none(), "a new queue is empty");
    for i in 0..spsc::CAPACITY as u16 {
        producer
            .try_push(event(1, i))
            .unwrap_or_else(|_| panic!("push {i} of {} must fit", spsc::CAPACITY));
    }
    let refused = producer
        .try_push(event(9, 99))
        .expect_err("a full queue refuses the push");
    assert_eq!(
        pair(&refused.into_inner()),
        (9, 99),
        "the refused element comes back"
    );

    for i in 0..spsc::CAPACITY as u16 {
        let got = consumer.try_pop().expect("an element is waiting");
        assert_eq!(pair(&got), (1, i), "first in, first out");
    }
    assert!(consumer.try_pop().is_none(), "drained");
}

#[test]
fn the_scq_queue_holds_exactly_its_capacity_at_rest_and_keeps_order() {
    let q = scq::QueueConformanceScq::new();
    let producer = q.producer().expect("a producer handle");
    let consumer = q.consumer().expect("a consumer handle");

    for i in 0..scq::CAPACITY as u16 {
        producer
            .try_push(event(2, i))
            .unwrap_or_else(|_| panic!("push {i} of {} must fit", scq::CAPACITY));
    }
    assert!(
        producer.try_push(event(9, 99)).is_err(),
        "a seventh element does not fit a queue of six"
    );
    for i in 0..scq::CAPACITY as u16 {
        assert_eq!(pair(&consumer.try_pop().expect("waiting")), (2, i));
    }
    assert!(consumer.try_pop().is_none());
}

#[test]
fn the_scq_queue_hands_out_no_more_handles_than_its_ring_has_slots() {
    let q = scq::QueueConformanceScq::new();
    let mut producers = Vec::new();
    while let Some(p) = q.producer() {
        producers.push(p);
        assert!(
            producers.len() <= scq::RING_SLOTS,
            "more producer handles than ring slots"
        );
    }
    assert_eq!(
        producers.len(),
        scq::RING_SLOTS,
        "the ring is correct for as many participants a side as it has slots, and no more"
    );
}

/// The module says a queue "may be a `static`": it owns its storage and
/// allocates nothing.
#[test]
fn the_scq_queue_can_be_a_static() {
    static QUEUE: scq::QueueConformanceScq = scq::QueueConformanceScq::new();
    let producer = QUEUE.producer().expect("producer");
    let consumer = QUEUE.consumer().expect("consumer");
    producer.try_push(event(3, 7)).unwrap_or_else(|_| panic!());
    assert_eq!(pair(&consumer.try_pop().expect("waiting")), (3, 7));
}

/// Two producers and two consumers on real threads: nothing is lost,
/// nothing is duplicated, and each producer's elements leave in the order
/// they went in.
#[test]
fn the_scq_queue_loses_nothing_between_threads() {
    const PER_PRODUCER: u16 = 500;
    const TOTAL: usize = 2 * PER_PRODUCER as usize;
    let q = scq::QueueConformanceScq::new();
    // The consumers stop when every element sent has been taken, not after a
    // quiet spell, so a slow producer is never mistaken for a lost element.
    // The deadline turns a genuinely lost element into a failure.
    let taken = AtomicUsize::new(0);
    let deadline = Instant::now() + Duration::from_secs(60);
    let received = thread::scope(|scope| {
        let mut consumers = Vec::new();
        for _ in 0..2 {
            let consumer = q.consumer().expect("consumer handle");
            let taken = &taken;
            consumers.push(scope.spawn(move || {
                let mut got = Vec::new();
                while taken.load(Ordering::Acquire) < TOTAL {
                    assert!(
                        Instant::now() < deadline,
                        "{} of {TOTAL} elements arrived before the deadline",
                        taken.load(Ordering::Acquire)
                    );
                    match consumer.try_pop() {
                        Some(e) => {
                            taken.fetch_add(1, Ordering::AcqRel);
                            got.push(pair(&e));
                        }
                        None => thread::yield_now(),
                    }
                }
                got
            }));
        }
        for sensor in 1..=2u8 {
            let producer = q.producer().expect("producer handle");
            scope.spawn(move || {
                for i in 0..PER_PRODUCER {
                    let mut e = event(sensor, i);
                    loop {
                        match producer.try_push(e) {
                            Ok(()) => break,
                            Err(refused) => {
                                e = refused.into_inner();
                                thread::yield_now();
                            }
                        }
                    }
                }
            });
        }
        consumers
            .into_iter()
            .map(|c| c.join().expect("consumer thread"))
            .collect::<Vec<_>>()
    });

    let mut per_sensor: BTreeMap<u8, Vec<u16>> = BTreeMap::new();
    for consumer_log in &received {
        // A consumer sees one producer's elements in the order they went in.
        let mut last: BTreeMap<u8, u16> = BTreeMap::new();
        for &(sensor, value) in consumer_log {
            if let Some(&previous) = last.get(&sensor) {
                assert!(value > previous, "sensor {sensor} went backwards");
            }
            last.insert(sensor, value);
            per_sensor.entry(sensor).or_default().push(value);
        }
    }
    for sensor in 1..=2u8 {
        let mut values = per_sensor.remove(&sensor).unwrap_or_default();
        values.sort_unstable();
        let expected: Vec<u16> = (0..PER_PRODUCER).collect();
        assert_eq!(
            values, expected,
            "sensor {sensor}: every element exactly once"
        );
    }
}

