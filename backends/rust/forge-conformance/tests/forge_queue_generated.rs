//! The queue kind's generated module (SCE Protocol-Synthesis RFC §synth-5-P),
//! compiled and run.
//!
//! `sce-build`'s tests read what the generator writes for a queue and parse it
//! with `syn`, which shows the text is Rust and says nothing about whether the
//! names in it are the names `sce-forge-runtime` has. Here the module the
//! generator writes for each bounded algorithm row is compiled into this test
//! binary over the element codec it names, and the queue it defines is used:
//! a rename in the runtime, or a constant the template computes wrongly,
//! stops the build or fails an assertion.
//!
//! Generated by `build.rs` Step 6 into OUT_DIR. The codec crate's `alloc`
//! feature is needed for the element codec's `encode_to_vec`, as in the other
//! generated-fixture tests; the queue itself needs no allocation.
#![cfg(feature = "alloc")]

mod queue_modules {
    pub mod queue_conformance_event {
        include!(concat!(env!("OUT_DIR"), "/queue_conformance_event.rs"));
    }
    // The generated queue modules open with `#![allow(...)]`, which `build.rs`
    // strips because an inner attribute cannot sit at an `include!` point; the
    // module carries them as outer attributes. `dead_code` is added: a
    // generated module's constants are its public contract, and are unused
    // only because this test includes it into a private module.
    #[allow(clippy::all, unused_imports, dead_code)]
    pub mod queue_conformance_spsc {
        include!(concat!(env!("OUT_DIR"), "/queue_conformance_spsc.rs"));
    }
    #[allow(clippy::all, unused_imports, dead_code)]
    pub mod queue_conformance_scq {
        include!(concat!(env!("OUT_DIR"), "/queue_conformance_scq.rs"));
    }
    pub mod queue_conformance_node {
        include!(concat!(env!("OUT_DIR"), "/queue_conformance_node.rs"));
    }
    #[allow(clippy::all, unused_imports, dead_code)]
    pub mod queue_conformance_intrusive {
        include!(concat!(env!("OUT_DIR"), "/queue_conformance_intrusive.rs"));
    }
    #[allow(clippy::all, unused_imports, dead_code)]
    pub mod queue_conformance_intrusive_many {
        include!(concat!(
            env!("OUT_DIR"),
            "/queue_conformance_intrusive_many.rs"
        ));
    }
}

