//
// datamodel="sce-static" (docs/SCE_ACCEPTED_SUBSET.md §2.15) — scenarios
// every backend that lowers the model replays, the twin of the Kotlin
// `StaticScenarioTest`.
//
// A scenario (`sce-build/tests/fixtures/static_datamodel/scenarios/*.json`)
// is data: a list of steps, each an external event with its payload and
// what the machine must hold after it runs to quiescence — its current
// state and any of its variables. What the machine holds is read from its
// saved state, the text every backend saves byte for byte, so one scenario
// judges every backend by the same answer and needs no per-type glue.
//
// The committed machines are regenerated by
// `scripts/regen_static_datamodel_rust.sh`.

use sce_rust_runtime::saved_state::SavedState;
use sce_rust_runtime::{Engine, StatePolicy};
use sce_rust_tests::integration::static_datamodel::sync_client_sm::{
    SyncClientPersist, SyncClientPolicy,
};
use serde_json::Value;

/// Replay `scenario` against `engine`, reading the machine back with
/// `save` after every step. An event name the machine does not declare
/// fails the replay: the engine drops one silently, which would otherwise
/// pass a misspelt step without running it.
fn replay<P: StatePolicy>(
    mut engine: Engine<P>,
    save: impl Fn(&Engine<P>) -> SavedState,
    scenario: &str,
) {
    let scenario: Value = serde_json::from_str(scenario).expect("a scenario is JSON");
    let steps = scenario["steps"].as_array().expect("steps");
    assert!(!steps.is_empty(), "a scenario with no steps judges nothing");
    engine.initialize();
    for (n, step) in steps.iter().enumerate() {
        if let Some(event) = step.get("event").and_then(Value::as_str) {
            assert!(
                P::get_event_from_name(event).is_some(),
                "step {n}: the machine declares no event `{event}`"
            );
            let data = step.get("data").map(Value::to_string).unwrap_or_default();
            engine.raise_external_by_name(event, &data);
            engine.step();
        }
        let saved: Value =
            serde_json::from_str(&save(&engine).to_json()).expect("a saved state is JSON");
        let expect = &step["expect"];
        let note = step.get("note").and_then(Value::as_str).unwrap_or("");
        if let Some(state) = expect.get("state") {
            assert_eq!(
                &saved["current"], state,
                "step {n} ({note}): the current state"
            );
        }
        if let Some(variables) = expect.get("variables").and_then(Value::as_object) {
            for (name, want) in variables {
                let got = &saved["variables"][name];
                assert!(
                    holds(got, want),
                    "step {n} ({note}): variable `{name}` is {got}, not {want}"
                );
            }
        }
    }
}

/// Whether a saved value is the scenario's. The saved state writes a 64-bit
/// integer as its decimal text (a JSON number past 2^53 is not exact
/// everywhere), so an expected number matches that text of the same
/// integer; everything else must be equal as written.
fn holds(got: &Value, want: &Value) -> bool {
    match (got, want) {
        (Value::String(text), Value::Number(n)) => {
            (n.is_i64() || n.is_u64()) && *text == n.to_string()
        }
        _ => got == want,
    }
}

#[test]
fn sync_client_runs_its_scenario() {
    replay(
        Engine::new(SyncClientPolicy::new()),
        |engine| engine.save().expect("saves"),
        include_str!(
            "../../../../sce-build/tests/fixtures/static_datamodel/scenarios/sync_client.json"
        ),
    );
}
