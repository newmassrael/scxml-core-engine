/// The classification of an event (§scxml-5.10.1).
///
/// Ports `EventType` from `backends/rust/runtime/src/event.rs`. The cases are
/// named for what the engine does with them, not for the spelling of the
/// `_event.type` value, which `description` gives.
public enum EventType: Sendable, Equatable, CustomStringConvertible {
    /// Raised internally by `<raise>` or a targetless `<send>` (§scxml-5.10.1).
    case internalEvent

    /// From an external source: the default classification (§scxml-5.10.1).
    case externalEvent

    /// Generated by the platform, such as `error.execution` and `done.state.*`.
    case platformEvent

    /// The type `_event.type` reads as, decided where the engine dequeues the event: by name for
    /// the events the processor itself raises (`error.*`, `done.*`), otherwise by the queue it was
    /// taken from (§scxml-5.10.1). Ports `EventType::classify` of the Rust runtime, so a producer
    /// that builds metadata for the queue has no say in what a document reads.
    public static func classify(eventName: String, fromExternalQueue: Bool) -> EventType {
        if eventName.hasPrefix("error.") || eventName.hasPrefix("done.") {
            return .platformEvent
        }
        return fromExternalQueue ? .externalEvent : .internalEvent
    }

    /// The spelling the Rust and C++ runtimes give, for interop and logging.
    public var description: String {
        switch self {
        case .internalEvent: return "internal"
        case .externalEvent: return "external"
        case .platformEvent: return "platform"
        }
    }
}

/// The reply address an event carries (docs/adr/0090, section 1): the Event I/O
/// Processor that delivered it and the address that processor accepts as a `<send>`
/// target.
///
/// The document reads the two as `_event.origintype` and `_event.origin`
/// (§scxml-5.10.1); they are one value because the address means something only
/// relative to its processor. The processor that delivers an event writes the pair
/// once, where it builds the event, and nothing converts it later. Constructed whole:
/// both fields are required and neither can be changed afterwards, so a pair with one
/// field set cannot be spelled. An event with no origin holds nil instead. Port of the
/// C++ `Core::EventOrigin`.
public struct EventOrigin: Sendable, Equatable {
    /// The canonical type URI of the Event I/O Processor that delivered the event
    /// (`_event.origintype`).
    public let processor: String

    /// A URI that processor accepts as a `<send>` target (`_event.origin`).
    public let address: String

    public init(processor: String, address: String) {
        self.processor = processor
        self.address = address
    }
}

/// The §scxml-5.10 metadata an event carries.
///
/// Every event flowing through the engine carries one, and it is copied into
/// the `_event.*` fields of the script engine.
public struct EventMetadata {
    /// The `_event.name` the event arrived under (§scxml-5.10), when that is not
    /// the name of the enum value that carries it. The event is carried as the
    /// value of a name the document writes, and §scxml-3.12.1 lets `request.new`
    /// take a transition on `request`, so the value alone loses the longer name.
    /// Set by a door that resolved a name through a prefix; empty means the
    /// value's own name is the name, which is every event the document itself
    /// raises or sends.
    public var name: String

    /// The `_event.data` payload as a JSON string; empty when there is none.
    public var data: String

    /// The `_event.type` classification.
    public var eventType: EventType

    /// The `_event.sendid` of the originating `<send>`; empty if none.
    public var sendID: String

    /// `_event.origin` and `_event.origintype` as the one pair the delivering processor
    /// wrote (docs/adr/0090); nil for an event no processor stamped, whose two fields
    /// the binding leaves blank (§scxml-5.10.1), which a document reads as undefined.
    public var origin: EventOrigin?

    /// The id of the session that sent the event, written by the processor that
    /// delivered it from that session: the SCXML Event I/O Processor for a local
    /// session, and the Mesh transport for a remote child or parent session (SCE_MESH.md,
    /// Child Sessions in Mesh). Nil
    /// for every other sender (a host, BasicHTTP, a Mesh peer that is no session of
    /// ours). Independent of `origin`, which is the reply address that processor
    /// wrote, a remote child's endpoint among them (docs/adr/0090). Not an `_event`
    /// field: it is what the lookups that find a session read (`<finalize>`), and
    /// nothing reads the origin's address to find one.
    public var sender: String?

    /// The `_event.invokeid` when the event came from a child invoke (§scxml-6.4.1).
    public var invokeID: String

    /// The token of the host-run invocation this event completes, set only by
    /// `Engine.completeHostInvoke` after it confirmed the invocation was still
    /// running. A host invoke's `done.invoke.<id>` that arrives without one did
    /// not come through that check, so the engine refuses it (§scxml-6.4). Not
    /// script-visible: `_event` has no field for it.
    public var hostInvokeToken: UInt64?

    /// The typed `_event.data` payload of an event injected through the
    /// generated `<Machine>Raise<Event>` seam. The generated policy's
    /// `populateEventMetadata` casts it back to the policy's typed pending
    /// payload, which the natively lowered guards read with no script engine.
    /// Nil for every event raised without a typed payload, against which the
    /// native guards' tag check simply fails. The name-to-type pairing is
    /// enforced at the one generated raise constructor, so it cannot be built
    /// inconsistently.
    public var typedPayload: Any?

    public init(
        name: String = "",
        data: String = "",
        eventType: EventType = .externalEvent,
        sendID: String = "",
        origin: EventOrigin? = nil,
        sender: String? = nil,
        invokeID: String = "",
        hostInvokeToken: UInt64? = nil,
        typedPayload: Any? = nil
    ) {
        self.name = name
        self.data = data
        self.eventType = eventType
        self.sendID = sendID
        self.origin = origin
        self.sender = sender
        self.invokeID = invokeID
        self.hostInvokeToken = hostInvokeToken
        self.typedPayload = typedPayload
    }

    /// Metadata of an event the platform raised, such as `error.execution` and
    /// `done.state.*`.
    public static func platform() -> EventMetadata {
        EventMetadata(eventType: .platformEvent)
    }

    /// Metadata of an event raised internally, such as by `<raise>`.
    public static func internalRaise() -> EventMetadata {
        EventMetadata(eventType: .internalEvent)
    }

    /// Metadata of an external event the session `sender` sends through the SCXML Event
    /// I/O Processor, as for `<send>`: the pair that processor writes for the sender
    /// (`scxmlOrigin(sender:)`) and the sender beside it (docs/adr/0090, section 2).
    /// An empty `sender` is a machine that holds no session id, whose event carries no
    /// origin.
    public static func external(sendID: String, sender: String) -> EventMetadata {
        EventMetadata(
            eventType: .externalEvent,
            sendID: sendID,
            origin: scxmlOrigin(of: sender),
            sender: sender.isEmpty ? nil : sender
        )
    }

    /// `_event.origin` of this event: the origin's address, or the empty text when it
    /// has none (§scxml-5.10.1).
    public var originAddress: String {
        origin?.address ?? ""
    }

    /// `_event.origintype` of this event: the origin's processor, or the empty text
    /// when it has none (§scxml-5.10.1).
    public var originProcessor: String {
        origin?.processor ?? ""
    }
}

/// A typed event value with its full §scxml-5.10 metadata.
///
/// `Event` is the generated policy's event enum.
public struct EventWithMetadata<Event> {
    /// The typed event value.
    public var event: Event

    /// The event data, type, sendid, origin, origintype and invokeid.
    public var metadata: EventMetadata

    /// The §scxml-C-2 HTTP POST target URL; empty if the send is not an HTTP one.
    public var target: String

    /// A bare event with default (external) metadata.
    public init(_ event: Event) {
        self.event = event
        self.metadata = EventMetadata()
        self.target = ""
    }

    /// An event with the metadata and target given.
    public init(_ event: Event, metadata: EventMetadata, target: String = "") {
        self.event = event
        self.metadata = metadata
        self.target = target
    }

    /// A platform event, with its type set to platform (§scxml-5.10.1).
    public static func platform(_ event: Event) -> EventWithMetadata<Event> {
        EventWithMetadata(event, metadata: .platform())
    }

    /// An `error.*` event the processor itself raised, carrying a description of
    /// what failed.
    ///
    /// The one way generated code raises a platform error, so that what a reader
    /// is owed is filled in at one place and not at each site that happens to
    /// remember. `platform(_:)` sets the type and leaves the data empty, which
    /// handed a document that answers `error.execution` an undefined
    /// `_event.data`: it could see that something failed and never what.
    ///
    /// `message` describes the failing construct and is a literal formed at
    /// generation time, not the engine's own error text. The dynamic detail stays
    /// on the log line beside the call, which is where it can afford to be built.
    public static func platformError(_ event: Event, message: String) -> EventWithMetadata<Event> {
        // §scxml-3.12.2: the processor signals its own failures as error.*, and
        // "platforms MAY include additional information about the nature of the
        // error in the 'data' field". Cited in the body rather than the doc
        // comment so the ledger binds it to this symbol.
        var metadata = EventMetadata.platform()
        metadata.data = message
        return EventWithMetadata(event, metadata: metadata)
    }

    /// An event with the full metadata, in the order of the Rust `with_fields`.
    /// `origin` is the pair the delivering processor wrote and `sender` the session that
    /// sent it, when that processor is the SCXML one (docs/adr/0090).
    public static func withFields(
        _ event: Event,
        data: String,
        origin: EventOrigin?,
        sender: String?,
        sendID: String,
        eventType: EventType,
        invokeID: String,
        target: String
    ) -> EventWithMetadata<Event> {
        EventWithMetadata(
            event,
            metadata: EventMetadata(
                data: data,
                eventType: eventType,
                sendID: sendID,
                origin: origin,
                sender: sender,
                invokeID: invokeID
            ),
            target: target
        )
    }
}
