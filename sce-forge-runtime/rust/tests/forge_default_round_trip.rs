// RFC variant-default-uniformity Atomic β-Rust runtime round-trip test.
//
// The pattern-check tests in `sce-build/tests/forge_conformance.rs` assert
// that the generated source carries the expected `impl Default` and
// `Variant::default()` arm pick. This file goes further — it actually
// compiles the generated codecs into the test binary and runs the
// round-trip invariant `T::default().encode().decode() == T::default()`
// to prove the watching-zenoh R87 defect cannot recur on the new branch.
//
// The 3 fixtures are generated by `build.rs` Step 4 into OUT_DIR. They
// live under a shared parent module here so the outer codec's
// `use super::codec_default_marker_arm_*` references resolve.

// The generated codec sources are written to OUT_DIR by build.rs with
// the `#![doc = "SCE-MAP: ..."]` inner attribute stripped so they can
// be `include!()`-ed inside a parent `mod {}` block (inner attributes
// are not permitted at that injection position). The same SCE-MAP info
// is preserved as a regular `// SCE-MAP:` comment on the next line.
mod default_marker_codecs {
    pub mod codec_default_marker_arm_a {
        include!(concat!(env!("OUT_DIR"), "/codec_default_marker_arm_a.rs"));
    }
    pub mod codec_default_marker_arm_b {
        include!(concat!(env!("OUT_DIR"), "/codec_default_marker_arm_b.rs"));
    }
    pub mod codec_variant_default_marker {
        include!(concat!(env!("OUT_DIR"), "/codec_variant_default_marker.rs"));
    }
}

use default_marker_codecs::codec_variant_default_marker::{
    CodecVariantDefaultMarker, CodecVariantDefaultMarkerVariant,
};
use sce_forge_runtime::codec::SceCursor;

/// `Default::default()` of the outer codec round-trips byte-exactly through
/// `encode()` → `decode()`. Without RFC variant-default-uniformity Atomic
/// β-Rust both `Variant::default()` would pick arm A (legacy first-declared)
/// and `CodecDefaultMarkerArmA::default()` would zero-fill its header byte
/// to `0x00` — which is outside the dispatch table `{0x01, 0x02}` and
/// would fall through to the catch-all `<sce:default>` arm, breaking the
/// body-arm match and the cursor.remaining() == 0 invariant.
///
/// After β-Rust:
///   - `Variant::default()` picks arm B (marked `default="true"`).
///   - `CodecDefaultMarkerArmB::default()` initializes `header` to `0x02`
///     via `<sce:flag value="0x02"/>`.
///   - Round-trip is total.
#[test]
fn default_marker_round_trips_via_declared_default_arm() {
    let original = CodecVariantDefaultMarker::default();
    let bytes = original.encode();

    // Sanity: encode must emit at least the inner arm B's wire shape
    // (1 byte header + 2 byte uint16 payload = 3 bytes).
    assert_eq!(
        bytes.len(),
        3,
        "Default-emit + arm B (uint16 payload) ⇒ 3 wire bytes; got {} byte(s): {:?}",
        bytes.len(),
        bytes
    );
    // The peeked byte (low 2 bits) MUST be `0x02` — the declared
    // wire-MID of arm B. If this fails, the inner Default branch
    // didn't fire and the carrier zero-filled.
    assert_eq!(
        bytes[0] & 0x03,
        0x02,
        "first byte's low 2 bits must encode arm B's MID (0x02); got 0x{:02X}",
        bytes[0]
    );

    let mut cursor = SceCursor::new(&bytes);
    let decoded = CodecVariantDefaultMarker::decode(&mut cursor)
        .expect("freshly-constructed codec must decode without error");

    // Cursor consumes every emitted byte (no leftover that would have
    // signaled an arm-type mismatch).
    assert_eq!(
        cursor.remaining(),
        0,
        "decode must consume every emitted byte; {} byte(s) leftover",
        cursor.remaining()
    );

    // Critical invariant: the decoded body lands in the SAME arm
    // variant as the original. If this fails, the dispatch dropped
    // into the catch-all branch — i.e. round-trip is broken.
    match decoded.body {
        CodecVariantDefaultMarkerVariant::CodecDefaultMarkerArmB(_) => {}
        CodecVariantDefaultMarkerVariant::CodecDefaultMarkerArmA(_) => {
            panic!(
                "round-trip dropped into arm A — the legacy first-declared \
                 arm — meaning the Atomic β-Rust outer Default change didn't \
                 take effect"
            )
        }
        CodecVariantDefaultMarkerVariant::Default { tag, .. } => {
            panic!(
                "round-trip dropped into the catch-all <sce:default> arm \
                 (tag=0x{tag:02X}) — meaning the inner Default zero-filled \
                 the header byte (β-Rust inner Default change didn't take \
                 effect) or the outer dispatch table missed the declared \
                 MID"
            )
        }
    }

    // Re-encode must produce byte-equal output to the first encode.
    let re_encoded = decoded.encode();
    assert_eq!(
        bytes, re_encoded,
        "decode → encode produced different bytes; round-trip is not \
         byte-stable"
    );
}
