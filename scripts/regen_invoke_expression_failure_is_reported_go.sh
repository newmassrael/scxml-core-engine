# Regenerate backends/go/tests/integration/invoke_expression_failure_is_reported/*_sm.go
# from the canonical fixture at
# integration_resources/invoke_expression_failure_is_reported/invoke_expression_failure_is_reported.scxml.
#
# Mirrors scripts/regen_invoke_expression_failure_is_reported.sh (Rust),
# including its child pass: the fixture's `<invoke>` names its target
# through an expression, so codegen writes an immediate-`<final>` stub
# beside the parent (docs/SCE_ACCEPTED_SUBSET.md §2.13) and the parent
# instantiates that stub by name.
#
# Idempotency: re-runs are byte-stable for unchanged inputs and generator.
#
# Usage (from repo root):
#   scripts/regen_invoke_expression_failure_is_reported_go.sh
#
# Requires:
#   sce-codegen (resolved by scripts/lib/sce_codegen.sh, built when missing).

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

STEM="invoke_expression_failure_is_reported"
FIXTURE="integration_resources/$STEM/$STEM.scxml"
GENERATED_DIR="backends/go/tests/integration/$STEM"

source "$REPO_ROOT/scripts/lib/sce_codegen.sh"
CODEGEN="$(sce_codegen_require "$REPO_ROOT")"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

"$CODEGEN" generate "$FIXTURE" -l go -o "$TMP/"

# `--parent-stem` rewrites the child's `package <child>` header to the
# parent's. Go allows one package per directory, so without it the two
# generated files in the tracked tree declare two packages and the
# directory does not build at all — which is how this was found.
# `--source-root "$TMP"` because the child is SYNTHESISED into the staging
# directory and has no home in the tree to be named after. Without it the
# `// From:` line carries `$TMP` itself — a name that differs on every run,
# so the committed artefact could never be regenerated byte-for-byte and
# `regen-reproduces` fails on a document nobody edited.
for child in "$TMP"/*_hybrid*.scxml; do
    [ -e "$child" ] || continue
    "$CODEGEN" generate "$child" --as-child --parent-stem "$STEM" -l go -o "$TMP/" \
        --source-root "$TMP"
done

mkdir -p "$GENERATED_DIR"
find "$GENERATED_DIR" -maxdepth 1 -name '*_sm.go' -delete
cp "$TMP"/*_sm.go "$GENERATED_DIR/"

echo "Regenerated: $GENERATED_DIR/ from $FIXTURE"
