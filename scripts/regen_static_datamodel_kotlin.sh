# Regenerate backends/kotlin/tests/src/main/kotlin/com/sce/integration/<machine>/
# from sce-build/tests/fixtures/static_datamodel/<machine>.scxml, for every
# machine in MACHINES.
#
# The Kotlin compile+run gate for datamodel="sce-static"
# (docs/SCE_ACCEPTED_SUBSET.md §2.15). The committed machines compile as part
# of `:sce-kotlin-tests`, so their variables really are Kotlin fields and every
# lowered expression really type-checks; StaticDatamodelTest.kt drives them
# with no script engine. Driven by its own script rather than the
# `generate-integration` fan-out because only Kotlin lowers the model today —
# the other backends refuse the document (`STATIC_DATAMODEL_BACKENDS`).
#
# Usage (from repo root):
#   scripts/regen_static_datamodel_kotlin.sh
#
# Requires:
#   sce-codegen (resolved by scripts/lib/sce_codegen.sh, built when missing).

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

source "$REPO_ROOT/scripts/lib/sce_codegen.sh"
CODEGEN="$(sce_codegen_require "$REPO_ROOT")"
INPUT_ROOT="sce-build/tests/fixtures/static_datamodel"
GENERATED_ROOT="${SCE_KOTLIN_GENERATED_ROOT:-backends/kotlin/tests/src/main/kotlin}/com/sce/integration"
PACKAGE_PREFIX="com.sce.integration"

# static_counter:   variables, a typed guard and assignments.
# static_host_call: a native host action taking typed datamodel arguments.
# static_record:    a record variable built whole and updated field by field,
#                   whose schema is imported from a sibling document.
# static_list:      a list variable filled by <sce:append>, emptied by
#                   <sce:clear>, and held to its capacity.
# static_overflow:  an integer operation that overflows — the statement is
#                   skipped, the condition is false, and error.execution
#                   says so (SCE_FORGE.md §3.4.1).
# static_payload:   an event's typed payload read in a guard and in
#                   assignments, one of which fails into error.execution.
# sync_client:      a sync run composed of the standard sync rules.
# Every scenarios/*.json is replayed against the machine it names.
#
# Derived, not listed: every statechart the directory declares under
# datamodel="sce-static" that the generator lowers for Kotlin. A list here was one
# more place a new fixture had to be remembered, and one it was left out of would
# have been generated by no script and gated by no test. The generator is asked,
# so a construct Kotlin gains the lowering of joins the gate by itself, and a
# fixture another backend lowers first is not Kotlin's to generate until then. A
# refusal by name is exit status 7 (generate/unsupported-feature); any other
# failure is a defect, not a machine to skip.
mapfile -t CANDIDATES < <(grep -l 'datamodel="sce-static"' "$INPUT_ROOT"/*.scxml | sort)
if [ "${#CANDIDATES[@]}" -lt 1 ]; then
    echo "error: no sce-static statechart found under $INPUT_ROOT" >&2
    exit 1
fi
MACHINES=()
for source in "${CANDIDATES[@]}"; do
    status=0
    "$CODEGEN" check -l kotlin "$source" > /dev/null 2>&1 || status=$?
    case "$status" in
        0) MACHINES+=("$(basename "$source" .scxml)") ;;
        7) ;;
        *)
            echo "error: sce-codegen check -l kotlin $source failed with status $status" >&2
            exit 1
            ;;
    esac
done
if [ "${#MACHINES[@]}" -lt 1 ]; then
    echo "error: the Kotlin backend lowers no sce-static statechart" >&2
    exit 1
fi
# Derived, not listed: the stem of every document a machine here declares in
# `sce:candidates`. Such a document is a child of the machine that invokes it,
# generated into THAT machine's package (below) because the parent names its
# children as package-local classes. Generated again as a machine of its own it
# would be a second copy nothing runs.
CANDIDATE_STEMS="$(grep -ho 'sce:candidates="[^"]*"' "$INPUT_ROOT"/*.scxml | cut -d'"' -f2 | tr ' ' '\n' | sed -e 's|.*/||' -e 's|\.scxml$||' | sort -u || true)"
STANDALONE=()
for machine in "${MACHINES[@]}"; do
    if ! grep -qx -- "$machine" <<< "$CANDIDATE_STEMS"; then
        STANDALONE+=("$machine")
    fi
done
MACHINES=("${STANDALONE[@]}")

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

for machine in "${MACHINES[@]}"; do
    "$CODEGEN" generate "$INPUT_ROOT/$machine.scxml" -l kotlin -o "$TMP/$machine/" \
        --input-root "$INPUT_ROOT" \
        --kotlin-package-prefix "$PACKAGE_PREFIX"
    # The documents the machine's hybrid invokes declare in `sce:candidates` are
    # real machines: `--parent-stem` puts each in the parent's package. Read from
    # the parent's own attributes rather than from what the generator staged
    # beside its output, which also holds the documents of its inline children.
    # Generated from the TRACKED document, not from a staged copy, so the
    # `// Source:` line of a committed file does not carry a temporary path.
    while IFS= read -r base; do
        [ -n "$base" ] || continue
        "$CODEGEN" generate "$INPUT_ROOT/$base" --as-child --parent-stem "$machine" -l kotlin -o "$TMP/$machine/" \
            --input-root "$INPUT_ROOT" \
            --kotlin-package-prefix "$PACKAGE_PREFIX"
    done < <(grep -ho 'sce:candidates="[^"]*"' "$INPUT_ROOT/$machine.scxml" | cut -d'"' -f2 | tr ' ' '\n' | sed 's|.*/||' | sort -u)
    dir="$GENERATED_ROOT/$machine"
    mkdir -p "$dir"
    find "$dir" -maxdepth 1 -name '*Sm.kt' -delete
    for src in "$TMP/$machine"/*Sm.kt; do
        [[ -f "$src" ]] || continue
        sed -i "s|// Source: ${TMP}/${machine}/|// Source: ${INPUT_ROOT}/|g" "$src"
        cp "$src" "$dir/"
    done
done

# The algorithms a machine above imports. `sce-codegen generate` does not
# generate a document's imports (a forge kind's are generated on their own
# too), and an algorithm's package is `com.sce.generated.<snake>` whatever
# the machine's prefix — the package the machine's import line names.
ALGORITHM_ROOT="${SCE_KOTLIN_GENERATED_ROOT:-backends/kotlin/tests/src/main/kotlin}/com/sce/generated"
#
# Derived from what the machines import, for the reason the machines are: a list
# here was one more place a new algorithm had to be remembered, and one left out
# is a machine that imports a package nothing generated. A document is named as
# the generator takes it — a local one by its path, a standard one by its library
# name (`sce:std/...`) — and read for its own imports where it lies: a standard
# one under stdlib/.

# The file a document named as the generator takes it is read from.
document_file() {
    case "$1" in
        sce:std/*) printf '%s\n' "stdlib/${1#sce:std/}" ;;
        *) printf '%s\n' "$1" ;;
    esac
}

# The documents of kind $1 that document $2 imports, each named as the generator
# takes it: a standard one as it is written, any other beside the document that
# imports it — which, for a standard document, is the library again.
imports_of() {
    local kind="$1" document="$2" import
    while IFS= read -r import; do
        case "$import" in
            sce:*) printf '%s\n' "$import" ;;
            *) printf '%s\n' "$(dirname "$document")/$import" ;;
        esac
    done < <(grep "<sce:import kind=\"$kind\"" "$(document_file "$document")" | grep -o 'src="[^"]*"' | cut -d'"' -f2)
}

# Every algorithm a machine calls, and every algorithm one of those calls in its
# turn: an algorithm's file imports the package of each it calls, as a machine's
# does.
ALGORITHMS=()
declare -A REACHED=()
PENDING=()
for machine in "${MACHINES[@]}"; do
    while IFS= read -r algorithm; do
        PENDING+=("$algorithm")
    done < <(imports_of algorithm "$INPUT_ROOT/$machine.scxml")
done
while [ "${#PENDING[@]}" -gt 0 ]; do
    algorithm="${PENDING[0]}"
    PENDING=("${PENDING[@]:1}")
    if [ -n "${REACHED[$algorithm]:-}" ]; then
        continue
    fi
    REACHED[$algorithm]=1
    ALGORITHMS+=("$algorithm")
    while IFS= read -r called; do
        PENDING+=("$called")
    done < <(imports_of algorithm "$algorithm")
done
if [ "${#ALGORITHMS[@]}" -gt 0 ]; then
    mapfile -t ALGORITHMS < <(printf '%s\n' "${ALGORITHMS[@]}" | sort -u)
fi
# The records a machine hands those algorithms and takes back are the payload
# classes of the event-schemas an algorithm imports: its file imports the package
# of each, which is named for the schema, and so does the machine that holds one.
SCHEMAS=()
for algorithm in "${ALGORITHMS[@]}"; do
    while IFS= read -r schema; do
        SCHEMAS+=("$schema")
    done < <(imports_of event-schema "$algorithm")
done
if [ "${#SCHEMAS[@]}" -gt 0 ]; then
    mapfile -t SCHEMAS < <(printf '%s\n' "${SCHEMAS[@]}" | sort -u)
fi

# A generated file's directory is the last name of the package it declares, which
# the generator takes from the document's own name and not from the path it was
# read from.
PACKAGES=()
install_generated() {
    local staged="$1" generated package dir
    for generated in "$staged"/*.kt; do
        package="$(sed -n 's/^package com\.sce\.generated\.\([A-Za-z0-9_]*\)$/\1/p' "$generated")"
        if [ -z "$package" ]; then
            echo "error: $generated declares no com.sce.generated package" >&2
            exit 1
        fi
        dir="$ALGORITHM_ROOT/$package"
        mkdir -p "$dir"
        find "$dir" -maxdepth 1 -name '*.kt' -delete
        cp "$generated" "$dir/"
        PACKAGES+=("$package")
    done
}
for i in "${!SCHEMAS[@]}"; do
    "$CODEGEN" generate "${SCHEMAS[$i]}" -l kotlin -o "$TMP/schema_$i/"
    install_generated "$TMP/schema_$i"
done
for i in "${!ALGORITHMS[@]}"; do
    "$CODEGEN" generate "${ALGORITHMS[$i]}" -l kotlin -o "$TMP/algorithm_$i/"
    install_generated "$TMP/algorithm_$i"
done

echo "Regenerated: ${MACHINES[*]} under $GENERATED_ROOT/ and ${PACKAGES[*]:-none} under $ALGORITHM_ROOT/ from $INPUT_ROOT"
