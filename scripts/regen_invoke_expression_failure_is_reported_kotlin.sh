# Regenerate the Kotlin integration tree for
# invoke_expression_failure_is_reported from the canonical fixture at
# integration_resources/invoke_expression_failure_is_reported/invoke_expression_failure_is_reported.scxml.
#
# Mirrors scripts/regen_invoke_expression_failure_is_reported.sh (Rust).
# The child pass is kept even though Kotlin's parent template resolves a
# hybrid `<invoke>` through its own runtime loader rather than importing
# the generated stub: the stub costs one small file, and a regen whose
# output set depends on which backend it is would make the four scripts
# stop being mirrors of one another.
#
# Idempotency: re-runs are byte-stable except for the embedded
# `generated-at: <unix-seconds>` header line that the codegen emits
# on every invocation.
#
# Usage (from repo root):
#   scripts/regen_invoke_expression_failure_is_reported_kotlin.sh
#
# Requires:
#   sce-codegen (resolved by scripts/lib/sce_codegen.sh, built when missing).

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

STEM="invoke_expression_failure_is_reported"
FIXTURE="integration_resources/$STEM/$STEM.scxml"
GENERATED_DIR="${SCE_KOTLIN_GENERATED_ROOT:-backends/kotlin/tests/src/main/kotlin}/com/sce/integration/$STEM"
PACKAGE_PREFIX="com.sce.integration"

source "$REPO_ROOT/scripts/lib/sce_codegen.sh"
CODEGEN="$(sce_codegen_require "$REPO_ROOT")"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

"$CODEGEN" generate "$FIXTURE" -l kotlin -o "$TMP/" \
    --kotlin-package-prefix "$PACKAGE_PREFIX"
# `--as-child --parent-stem` puts the child in the parent's package. Kotlin
# gives each document a package of its own, so without it the parent's
# unqualified reference to the stub class does not resolve — measured, as an
# `Unresolved reference` at compile time.
# `--source-root "$TMP"` because the child is SYNTHESISED into the staging
# directory and has no home in the tree to be named after. Without it the
# `// From:` line carries `$TMP` itself — a name that differs on every run,
# so the committed artefact could never be regenerated byte-for-byte and
# `regen-reproduces` fails on a document nobody edited.
for child in "$TMP"/*_hybrid*.scxml; do
    [ -e "$child" ] || continue
    "$CODEGEN" generate "$child" --as-child --parent-stem "$STEM" -l kotlin -o "$TMP/" \
        --kotlin-package-prefix "$PACKAGE_PREFIX" \
        --source-root "$TMP"
done

mkdir -p "$GENERATED_DIR"
find "$GENERATED_DIR" -maxdepth 1 -name '*Sm.kt' -delete
cp "$TMP"/*Sm.kt "$GENERATED_DIR/"

echo "Regenerated: $GENERATED_DIR/ from $FIXTURE"
