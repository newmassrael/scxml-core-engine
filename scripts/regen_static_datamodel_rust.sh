# Regenerate backends/rust/tests/src/integration/static_datamodel/ from
# sce-build/tests/fixtures/static_datamodel/<machine>.scxml, for every machine
# in MACHINES, and the algorithms they call; and the test profile's templates
# from sce-build/tests/fixtures/test_profile/ with the documents they name.
#
# The Rust compile+run gate for datamodel="sce-static"
# (docs/SCE_ACCEPTED_SUBSET.md §2.15), the twin of
# scripts/regen_static_datamodel_kotlin.sh over the same fixtures. The
# committed machines compile as part of `cargo test -p sce-rust-tests`, so
# their variables really are fields of the policy and every lowered
# expression — the checked integer operations and the `error.execution` they
# fail into included — really type-checks; tests/static_datamodel.rs drives
# them with no script engine.
#
# Usage (from repo root):
#   scripts/regen_static_datamodel_rust.sh
#
# Requires:
#   sce-codegen (resolved by scripts/lib/sce_codegen.sh, built when missing).

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

source "$REPO_ROOT/scripts/lib/sce_codegen.sh"
CODEGEN="$(sce_codegen_require "$REPO_ROOT")"
INPUT_ROOT="sce-build/tests/fixtures/static_datamodel"
GENERATED_DIR="backends/rust/tests/src/integration/static_datamodel"

# The machines of scripts/regen_static_datamodel_kotlin.sh, for the same
# reasons: variables, typed guards and assignments; a host action with typed
# datamodel arguments; a record variable; a bounded list; an integer
# operation that overflows into error.execution; an event's typed payload;
# sync_client, a sync run composed of the standard sync rules. Every
# scenarios/*.json is replayed against the machine it names.
#
# Derived, not listed: every statechart the directory declares under
# datamodel="sce-static" that the generator lowers for Rust. A list here was one
# more place a new fixture had to be remembered, and one it was left out of would
# have been generated by no script and gated by no test. The generator is asked,
# so a construct Rust gains the lowering of joins the gate by itself, and a
# fixture another backend lowers first is not Rust's to generate until then — as
# for the scripts of Kotlin, Go and Python. A refusal by name is exit status 7
# (generate/unsupported-feature); any other failure is a defect, not a machine
# to skip.
mapfile -t CANDIDATES < <(grep -l 'datamodel="sce-static"' "$INPUT_ROOT"/*.scxml | sort)
if [ "${#CANDIDATES[@]}" -lt 1 ]; then
    echo "error: no sce-static statechart found under $INPUT_ROOT" >&2
    exit 1
fi
MACHINES=()
for source in "${CANDIDATES[@]}"; do
    status=0
    "$CODEGEN" check -l rust "$source" > /dev/null 2>&1 || status=$?
    case "$status" in
        0) MACHINES+=("$(basename "$source" .scxml)") ;;
        7) ;;
        *)
            echo "error: sce-codegen check -l rust $source failed with status $status" >&2
            exit 1
            ;;
    esac
done
if [ "${#MACHINES[@]}" -lt 1 ]; then
    echo "error: the Rust backend lowers no sce-static statechart" >&2
    exit 1
fi
# The statecharts of the standard library a scenario names by its library name
# (`"machine": "sce:std/shared/record_list"`): each is generated by that name, as a
# module of the stem of it, beside the machines. The library holds only what every
# backend generates, so none is asked about first.
mapfile -t STANDARD_MACHINES < <(grep -ho '"machine": "sce:std/[^"]*"' "$INPUT_ROOT"/scenarios/*.json | cut -d'"' -f4 | sort -u)
# algorithm_days_in_month: called from static_record's guard. algorithm_day_run:
# its list is what static_list_assign takes whole. A machine's import names
# each as `super::<name>`, so it is generated beside the machines.
ALGORITHMS=(days_in_month day_run day_repeat ledger_add ledger_total ledger_amount ledger_bump ledger_ids ledger_larger ledger_has ids_above)
# static_state_algorithm_enum's: a list of records with an enum field, and a value
# of the enum, in and out.
ALGORITHMS+=(item_status_set item_status_count item_status_of)
# static_state_algorithm_optional's: a list of records whose day may be absent, and
# an optional day, in and out (docs/adr/0055).
ALGORITHMS+=(goal_earliest goal_until goal_undated goal_day_sum)
# static_optional_record's: a list of records in, an optional record out
# (docs/adr/0055, step 9).
ALGORITHMS+=(item_pick_first)
# The records static_state_algorithm hands those algorithms and takes back: an
# algorithm names one as `super::schema_<name>`, so it is generated beside them.
SCHEMAS=(schema_entry schema_total)
# ... and static_state_algorithm_enum's record, with the enum its field holds, which
# the schema, the algorithms and the machine's adapters name as `super::enum_item_status`.
SCHEMAS+=(schema_item enum_item_status)
# ... and static_state_algorithm_optional's record, whose `day` may be absent.
SCHEMAS+=(schema_goal)
# ... and static_optional_record's, the record it may hold none of.
SCHEMAS+=(schema_item_pick)
# The text template static_render renders (docs/adr/0087, section 3), whose unit
# the machine calls as `super::text_notice::render`.
SCHEMAS+=(text_notice)
# ... and the two templates the reference harness static_model_harness renders, the
# prompt it asks with and the one it repairs with (docs/adr/0087, section 6.1).
SCHEMAS+=(harness_ask harness_repair)
# The schedule todo_peer reads from the fields a to-do holds: the occurrence and schedule
# records, the rules that order two writes, read a field, tell a conflict, select a day
# and expand a repetition. Each is named by its file, which a machine's import names as
# `super::<file>`.
SCHEMAS+=(event_occurrence event_schedule event_later event_latest event_conflict event_selects event_agenda event_member event_roster)
# The standard algorithms sync_client imports, by their library names; each
# is generated beside the machines under its own name, as a local one is.
STD_ALGORITHMS=(sync/sync_failure sync/sync_retry_at sync/sync_delete_outcome sync/sync_upload_outcome)
# The standard merge rules todo_peer and sheet_peer are made of: the algorithms the
# two import, the one those call (hlc_compare), and the records they take and give
# back, which a machine and an algorithm both name as `super::<name>`.
STD_ALGORITHMS+=(merge/hlc_timestamp merge/hlc_compare merge/hlc_send merge/hlc_receive)
STD_ALGORITHMS+=(merge/lww_cell merge/lww_write)
STD_ALGORITHMS+=(merge/rga_node merge/rga_gone merge/rga_insert merge/rga_holds merge/rga_remove)
STD_ALGORITHMS+=(merge/orset_entry merge/orset_union merge/orset_live merge/orset_observed)
# The values a field of the to-do list holds beside the dots, with their text.
STD_ALGORITHMS+=(merge/mv_value merge/mv_value_holds merge/mv_value_keep merge/mv_value_drop)
# The standard text rules static_text_record hands a record that holds text, and
# the record's own schema.
STD_ALGORITHMS+=(text/text_slot text/text_slot_latest text/text_slot_retitled text/text_slot_holds)
# The standard digest of a set of changes and its rules, which the standard library keeps
# and every backend generates, though no shared list keeps a digest since its layer below
# repairs it (docs/adr/0085).
STD_ALGORITHMS+=(merge/merkle_node merge/merkle_insert merge/merkle_change_hash)
# The time zone todo_peer turns its schedule's wall-clock readings into instants by.
STD_ALGORITHMS+=(time/utc_from_local)
# What the sheet shows of its cells: the formulas settled and the values sorted.
STD_ALGORITHMS+=(merge/sheet_value merge/sheet_shown merge/sheet_apply merge/sheet_settle merge/sheet_show)
# The standard shared record list's own rules (sce:std/shared/record_list, a
# scenario's machine, and the child record_list_parent invokes): the roster and the member record it
# keeps, and a register's values in the order of their dots.
STD_ALGORITHMS+=(shared/record_member shared/record_roster shared/register_values)
# static_forge_calls's: a condition, a transform, two lookups, an interpolation and a
# validator, which it calls as the functions of their inputs they are
# (docs/adr/0048). A machine's import names each as `super::<name>`, so it is
# generated beside the machines.
CALLED=(forge_call_high forge_call_offset forge_call_ratio forge_call_code forge_call_limit forge_call_range)
# ... and a transform, a lookup and a validator a value of an enum or a text is handed
# to, with the enums that value crosses into each by, which a called document and the
# machine's crossing both name as `super::<name>` (docs/adr/0051).
CALLED+=(forge_call_next forge_call_weight forge_call_named forge_call_status forge_call_level)
# The test profile's templates (docs/SCE_TEST_PROFILE.md §11.4, §11.9), each a document
# of its own kind whose unit declares its `matches` and, for a specific one, its `value`,
# generated beside the records, enums and unions their units name as `super::<name>`;
# tests/a_test_template_matches_its_values.rs matches them against values. The C++
# suite generates the same templates (tests/CMakeLists.txt); Rust, which lowers a union,
# generates the two over a union besides.
TEST_PROFILE_DIR="sce-build/tests/fixtures/test_profile"
TEST_PROFILE=(job_status elapsed_at_most every_matcher job_report job_report_of report_within shape_is_circle)
TEST_PROFILE_IMPORTS=(paint_color order_line quantity_two quantity_at_most order_line_exact order_line_bounded)
TEST_PROFILE_IMPORTS+=(card_payment card_within voucher_payment voucher_is)
TEST_PROFILE_IMPORTS+=(payment_kind order_customer order_payment order_placed order_placed_match)
# ... and the union shape_is_circle matches, with its tag's enum and its cases' records.
UNIONS=(shape_kind shape_radius_minimal shape_rect_minimal union_shape_minimal)
# ... and the enum of an open set form_extras holds a value of (below).
UNIONS+=(shape_kind_open)
# The test components tests/a_test_component_runs_through_its_doors.rs runs through the
# profile's runtime (docs/SCE_TEST_PROFILE.md §12.3), each its statechart machine and the
# component beside it, generated beside the records and the templates their machines
# name as `super::<name>`. The port types are read where the components are and write
# no file; param_asker reads the module parameter the suite below gives it. The C++
# suite runs the same components (tests/integration/ATestComponentRunsThroughItsDoorsTest.cpp).
TEST_PROFILE_RUNTIME_DIR="$TEST_PROFILE_DIR/runtime"
TEST_PROFILE_RUNTIME=(job_request job_reply request_of any_request reply_ok reply_of)
TEST_COMPONENTS=(asker coordinator answerer ptc_keeper idler param_asker)
# The tables of the suite tests/a_test_suite_runs_through_its_runner.rs runs through the
# profile's runner (docs/SCE_TEST_PROFILE.md §11.6 to §11.8, §12.2): each configuration's
# unit names the machines of its components above as `super::<name>_sm`, each test
# case's its configuration's and the suite's its test cases' as `super::<name>`. The
# feature model writes no file. The C++ suite runs the same tables
# (tests/integration/ATestSuiteRunsEndToEndTest.cpp).
TEST_TABLES=(asking_configuration serving_configuration keeping_configuration)
TEST_TABLES+=(answers_the_job answers_before_the_guard serves_a_ptc keeps_a_ptc runtime_suite)
# The configuration whose system port takes a record of every form of the canonical value
# (docs/SCE_TTCN3_LANE.md §10.3, §10.5), so its unit's reader and writer of each form are
# compiled; tests/a_record_reads_back_the_form_it_writes.rs round-trips a value of each and
# replays a trace of them. Its records beside form_extras (order_placed, job_status) and the
# enums and union they hold are generated above. The port type writes no file.
TRACE_FORMS_DIR="$TEST_PROFILE_DIR/trace_forms"
TRACE_FORMS=(form_extras forms_listener forms_configuration replays_every_form)

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

for machine in "${MACHINES[@]}"; do
    "$CODEGEN" generate "$INPUT_ROOT/$machine.scxml" -l rust -o "$TMP/"
done
for standard in "${STANDARD_MACHINES[@]}"; do
    "$CODEGEN" generate "$standard.scxml" -l rust -o "$TMP/"
done
for schema in "${SCHEMAS[@]}"; do
    "$CODEGEN" generate "$INPUT_ROOT/$schema.scxml" -l rust -o "$TMP/"
done
for algorithm in "${ALGORITHMS[@]}"; do
    "$CODEGEN" generate "$INPUT_ROOT/algorithm_$algorithm.scxml" -l rust -o "$TMP/"
done
for algorithm in "${STD_ALGORITHMS[@]}"; do
    "$CODEGEN" generate "sce:std/$algorithm.scxml" -l rust -o "$TMP/"
done
for document in "${CALLED[@]}"; do
    "$CODEGEN" generate "$INPUT_ROOT/$document.scxml" -l rust -o "$TMP/"
done
for document in "${TEST_PROFILE[@]}"; do
    "$CODEGEN" generate "$TEST_PROFILE_DIR/$document.scxml" -l rust -o "$TMP/"
done
for document in "${TEST_PROFILE_IMPORTS[@]}"; do
    "$CODEGEN" generate "$TEST_PROFILE_DIR/imports/$document.scxml" -l rust -o "$TMP/"
done
for document in "${UNIONS[@]}"; do
    "$CODEGEN" generate "sce-build/tests/fixtures/union/$document.scxml" -l rust -o "$TMP/"
done
for document in "${TEST_PROFILE_RUNTIME[@]}" "${TEST_COMPONENTS[@]}" "${TEST_TABLES[@]}"; do
    "$CODEGEN" generate "$TEST_PROFILE_RUNTIME_DIR/$document.scxml" -l rust -o "$TMP/"
done
for document in "${TRACE_FORMS[@]}"; do
    "$CODEGEN" generate "$TRACE_FORMS_DIR/$document.scxml" -l rust -o "$TMP/"
done

mkdir -p "$GENERATED_DIR"
source "$REPO_ROOT/scripts/lib/sce_generated_tree.sh"
sce_generated_tree_clear "$GENERATED_DIR"
cp "$TMP"/*.rs "$GENERATED_DIR/"

# Derived from what was generated, not from the three lists above: a machine
# whose `<invoke>` holds an inline child is generated beside it as
# `<machine>__sce_synth_invoke__<id>_sm`, and the machine names that module
# (`super::...`), so a list that named only the machines would leave the
# generated tree uncompilable.
MODRS="$GENERATED_DIR/mod.rs"
{
    echo "// GENERATED -- DO NOT EDIT (scripts/regen_static_datamodel_rust.sh)"
    echo ""
    for generated in "$TMP"/*.rs; do
        echo "pub mod $(basename "$generated" .rs);"
    done
} > "$MODRS"

source "$REPO_ROOT/scripts/lib/sce_rustfmt.sh"
sce_rustfmt_dir "$GENERATED_DIR" "$REPO_ROOT"

echo "Regenerated: ${MACHINES[*]} ${STANDARD_MACHINES[*]}, ${SCHEMAS[*]}, ${ALGORITHMS[*]}, ${STD_ALGORITHMS[*]} and ${CALLED[*]} under $GENERATED_DIR/ from $INPUT_ROOT, and ${TEST_PROFILE[*]} ${TEST_PROFILE_IMPORTS[*]} ${UNIONS[*]} ${TEST_PROFILE_RUNTIME[*]} ${TEST_COMPONENTS[*]} ${TEST_TABLES[*]} ${TRACE_FORMS[*]} from $TEST_PROFILE_DIR and sce-build/tests/fixtures/union"
