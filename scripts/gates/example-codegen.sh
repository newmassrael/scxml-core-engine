# Example SCXML codegen smoke + authored-document lint.
#
# The emscripten-backed doom_wasm / visualizer builds are too heavy for a
# push-time gate, but codegen failures (the kind that broke the
# `urn:sce:extensions` -> `http://sce.dev/ext` namespace migration) surface
# well before link time. Run sce-codegen over each example SCXML in a
# scratch output dir and fail if any produce no artifacts.
#
# The second sweep runs `check --lint` over every document this repository
# AUTHORS. The statechart lints are off by default because the W3C corpus
# declares unreachable states on purpose (a fixture proving `initial` is
# respected has states no event can enter), so a lint that rejected them
# would be wrong about conformance fixtures. Documents we write ourselves
# carry no such excuse, and until this sweep existed nothing in the repo
# turned `--lint` on at all — the flag shipped and no caller used it.
#
# Measured when it was added: three of the doom examples had a compound
# state whose children disagreed about an event, each an intentional gap now
# declared on the child that has it with `sce:unhandled` and the reason
# beside it. Two of the three prose comments were wrong about which child
# the gap belonged to; declaring it per child is what surfaced that.
#
# `--lint` now also carries the ECMAScript acceptance verdict. A refused
# expression is generated rather than refused — §scxml-5.9.1 obliges the
# machine to raise `error.execution` instead — so it is reported on every
# run and fatal only here, where the author has no conformance excuse for
# writing one. `sce-build/tests/cli_expression_refusal.rs` asserts the
# same sweep from Rust, so the refusal has a check that runs with the
# workspace tests rather than only where this gate runs.
#
# This gate is `ci_only`: the registry gives it no push-time trigger,
# because generating from every authored document is work proportional to
# the corpus (99s measured against a declared 4s — the widest gap in the
# table). `example-codegen.yml` is what runs it, and it calls
# `scripts/gate example-codegen` rather than restating these commands, so
# the check has one spelling for both callers.

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

CODEGEN="$(sce_gate_codegen)"

GEN_OUT="$(mktemp -d)"
sce_gate_on_exit "rm -rf '$GEN_OUT'"

failures=0
for scxml in examples/doom_wasm/scxml/*.scxml examples/smart_light/smart_light.scxml; do
    [[ -f "$scxml" ]] || continue
    if ! "$CODEGEN" generate "$scxml" \
            --language cpp \
            --output-dir "$GEN_OUT/" >/dev/null 2>&1; then
        printf '  FAIL: %s\n' "$scxml" >&2
        failures=$((failures + 1))
    fi
done
(( failures == 0 )) || sce_gate_fail "$failures example(s) failed codegen"

# Authored documents must be lint-clean. `check` runs the whole pipeline and
# discards the result, so this costs a parse and no disk.
lint_failures=0
lint_checked=0
while IFS= read -r scxml; do
    [[ -f "$scxml" ]] || continue
    lint_checked=$((lint_checked + 1))
    # No `--language`: the lints are a document-axis question and
    # naming a backend answered a different one. `smart_light.scxml`
    # writes `cond="cpp:hardware.hasPower()"` — a native C++ guard only
    # the C++ backend lowers — so pinning Rust here turned "this
    # document is lint-clean" into "Rust can lower this document", and
    # the two stopped agreeing the moment a native cond became a
    # backend-axis refusal instead of silently-broken output. Without
    # the flag the per-backend verdict rides the manifest's `languages`
    # and the exit stays 0, which is `check`'s contract for it
    # (SCE_ERROR_CONTRACT.md §10.3.1).
    if ! manifest="$("$CODEGEN" check "$scxml" --lint 2>/dev/null)"; then
        printf '  LINT: %s\n' "$scxml" >&2
        "$CODEGEN" check "$scxml" --lint 2>&1 | sed 's/^/        /' >&2
        lint_failures=$((lint_failures + 1))
        continue
    fi
    # Dropping `--language` costs one claim, so it is made explicitly:
    # a backend-axis refusal is non-fatal on this route, so a document
    # every backend rejects would exit 0 and read as lint-clean. A
    # document this repository authors is written to be generated by
    # something.
    if ! printf '%s' "$manifest" | grep -q '"status":"ok"'; then
        printf '  NO-BACKEND: %s\n' "$scxml" >&2
        printf '%s\n' "$manifest" | sed 's/^/        /' >&2
        lint_failures=$((lint_failures + 1))
    fi
done < <(git ls-files 'examples/*.scxml' 'integration_resources/*/*.scxml')

# A discovery bug that swept nothing would otherwise read as a pass. The
# corpus was 26 documents when this bound was set.
if (( lint_checked < 20 )); then
    sce_gate_fail "lint swept only $lint_checked authored document(s); expected at least 20"
fi
(( lint_failures == 0 )) || sce_gate_fail "$lint_failures authored document(s) failed --lint"
