# Regenerate backends/swift/tests/Sources/StaticDatamodelMachines/ from
# sce-build/tests/fixtures/static_datamodel/<machine>.scxml, for every machine
# the Swift backend lowers, every algorithm those machines call, and every event
# schema the Swift backend lowers; and the test profile's templates from
# sce-build/tests/fixtures/test_profile/ with the documents they name, a file each
# beside the machines.
#
# The Swift compile+run gate for datamodel="sce-static"
# (docs/SCE_ACCEPTED_SUBSET.md §2.15), the twin of
# scripts/regen_static_datamodel_go.sh, _kotlin.sh and _rust.sh over the same
# fixtures. The committed machines are one SwiftPM target of backends/swift/tests, so
# their variables really are properties of the policy and every lowered expression
# — the checked integer operations and the `error.execution` they fail into
# included — really type-checks; the tests beside them replay the shared scenarios
# against them with no script engine.
#
# Usage (from repo root):
#   scripts/regen_static_datamodel_swift.sh
#
# Requires:
#   sce-codegen (resolved by scripts/lib/sce_codegen.sh, built when missing).

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

source "$REPO_ROOT/scripts/lib/sce_codegen.sh"
CODEGEN="$(sce_codegen_require "$REPO_ROOT")"
INPUT_ROOT="sce-build/tests/fixtures/static_datamodel"
# The conformance corpus: the documents of every forge kind that the numerical conformance
# harness runs on each backend (`tests/forge/conformance/fixtures.json`). A kind with no
# document in the fixture directory or the standard library is held to the compiler here.
# The directory holds documents that are not fixtures (one is invalid on purpose), so the
# documents to generate are the catalog's, asked of the generator as the other backends'
# harnesses ask; the event schemas and enums they import are read from the directory.
CORPUS_ROOT="tests/forge/resources"
CORPUS_MANIFEST="tests/forge/conformance/fixtures.json"
GENERATED_DIR="backends/swift/tests/Sources/StaticDatamodelMachines"

# Derived, not listed: every statechart the fixture directory declares under
# datamodel="sce-static" that the generator lowers for Swift. The generator is
# asked, so a construct Swift gains the lowering of joins the gate by itself. A
# refusal by name is exit status 7 (generate/unsupported-feature); any other
# failure is a defect, not a machine to skip.
mapfile -t CANDIDATES < <(grep -l 'datamodel="sce-static"' "$INPUT_ROOT"/*.scxml | LC_ALL=C sort)
if [ "${#CANDIDATES[@]}" -lt 1 ]; then
    echo "error: no sce-static statechart found under $INPUT_ROOT" >&2
    exit 1
fi
# The Mesh request (SCE_MESH.md §9.5) of the host-processor fixtures: the one machine whose
# host-run invoke names its peer by a `srcexpr` and hands the router the `_mesh_*` envelope, so
# the compile gate holds the lowering of a request's `src` to the Swift compiler.
CANDIDATES+=("sce-build/tests/fixtures/host_processor/statechart_static_mesh_request.scxml")
MACHINES=()
SOURCES=()
# What a machine that is not lowered yet is refused for, one line each, so a run reads
# what stands between Swift and the rest of the fixtures.
REFUSED=()
for source in "${CANDIDATES[@]}"; do
    status=0
    verdict="$("$CODEGEN" check -l swift --error-format=json "$source" 2>&1)" || status=$?
    case "$status" in
        0)
            MACHINES+=("$(basename "$source" .scxml)")
            SOURCES+=("$source")
            ;;
        7)
            REFUSED+=("$(basename "$source" .scxml): $(printf '%s' "$verdict" | grep -o '"message":"[^"]*"' | head -n 1 | cut -c1-170)")
            ;;
        *)
            echo "error: sce-codegen check -l swift $source failed with status $status" >&2
            exit 1
            ;;
    esac
done
# The statecharts of the standard library a scenario names by its library name
# (`"machine": "sce:std/shared/record_list"`): each is generated by that name when the
# generator lowers it, as a fixture is. The library holds what every backend
# generates whole, not what Swift generates yet, so each is asked about too.
mapfile -t STANDARD_MACHINES < <(grep -ho '"machine": "sce:std/[^"]*"' "$INPUT_ROOT"/scenarios/*.json | cut -d'"' -f4 | sort -u)
for standard in "${STANDARD_MACHINES[@]}"; do
    # `check` reads a file, and a library name is one only to `generate`: the document
    # is read from where the library keeps it.
    status=0
    "$CODEGEN" check -l swift "stdlib/${standard#sce:std/}.scxml" > /dev/null 2>&1 || status=$?
    case "$status" in
        0)
            MACHINES+=("$(basename "$standard")")
            SOURCES+=("$standard.scxml")
            ;;
        7) ;;
        *)
            echo "error: sce-codegen check -l swift $standard.scxml failed with status $status" >&2
            exit 1
            ;;
    esac
done
if [ "${#MACHINES[@]}" -lt 1 ]; then
    echo "error: the Swift backend lowers no sce-static statechart" >&2
    exit 1
fi

# Derived from what the lowered machines import, for the reason the machines are:
# a list here is one more place a new algorithm has to be remembered, and one left
# out is a machine that calls an enum nothing declared. Each algorithm a machine
# calls is generated beside the machines, a file of the same SwiftPM target, as
# scripts/regen_static_datamodel_go.sh generates each as a package of its own. An
# algorithm is the one kind a Swift machine calls, and one that imports a document
# other than an event schema is refused where the machine imports it
# (`StaticCallee::unlowered_by`), so the algorithms the machines name directly are
# generated, and then every other algorithm the generator lowers (below).

# The file a document named as the generator takes it is read from.
document_file() {
    case "$1" in
        sce:std/*) printf '%s\n' "stdlib/${1#sce:std/}" ;;
        *) printf '%s\n' "$1" ;;
    esac
}

# The algorithms document $1 imports, each named as the generator takes it: a
# standard one as it is written, any other beside the document that imports it.
algorithms_of() {
    local import
    while IFS= read -r import; do
        case "$import" in
            sce:*) printf '%s\n' "$import" ;;
            *) printf '%s\n' "$(dirname "$1")/$import" ;;
        esac
    done < <(grep '<sce:import kind="algorithm"' "$(document_file "$1")" | grep -o 'src="[^"]*"' | cut -d'"' -f2)
}

ALGORITHMS=()
for source in "${SOURCES[@]}"; do
    while IFS= read -r algorithm; do
        ALGORITHMS+=("$algorithm")
    done < <(algorithms_of "$source")
done
# The documents of the kinds the Swift backend writes as a unit of one file (an algorithm,
# a condition, a lookup, an interpolation, a filter, a transform, a validator, a timer, an
# observer, a procedure and a codec), which the fixture directory, the
# standard library and the conformance catalog declare, whether or not a machine the Swift
# backend lowers calls one: a unit is compiled for what it is, not for who happens to call
# it, so a construct Swift gains the lowering of is held to the compiler before a machine
# reaches it. A kind Swift gains is added here, to the one list. Derived, and a refusal by
# name (status 7) is listed, as the machines' are.
UNIT_KINDS='(algorithm|condition|lookup|interpolation|filter|transform|validator|timer|observer|procedure|codec|text-template)'
# The conformance documents of the other backends' oracle that the catalog does not list, whose
# units a test of the Swift backend reads: a codec that embeds a variant and says which of its own
# flags selects the arm (ADR 0058), with the variant it embeds, and a CBOR map with an entry of an
# open enum.
CONFORMANCE_UNITS=(
    backends/rust/forge-conformance/fixtures/codec_source_leaf.scxml
    backends/rust/forge-conformance/fixtures/codec_source_parent_tag.scxml
    tests/forge/conformance/codec_cbor_open_enum/codec_cbor_open_enum.scxml
)
mapfile -t ALGORITHM_CANDIDATES < <(
    {
        printf '%s\n' "${CONFORMANCE_UNITS[@]}"
        grep -lE "sce:kind=\"$UNIT_KINDS\"" "$INPUT_ROOT"/*.scxml
        grep -rlE "sce:kind=\"$UNIT_KINDS\"" stdlib --include='*.scxml' | sed 's|^stdlib/|sce:std/|'
        # The catalog's documents of the kinds Swift writes: a path under the corpus, or
        # the `sce:std/...` name of a standard document (which stdlib already lists).
        while IFS= read -r document; do
            case "$document" in
                sce:std/*) ;;
                *) grep -lE "sce:kind=\"$UNIT_KINDS\"" "$document" || true ;;
            esac
        done < <("$CODEGEN" list-fixtures --manifest "$CORPUS_MANIFEST" --resource-dir "$CORPUS_ROOT" --format plain --documents)
    } | LC_ALL=C sort -u
)
ALGORITHMS_REFUSED=()
for candidate in "${ALGORITHM_CANDIDATES[@]}"; do
    status=0
    verdict="$("$CODEGEN" check -l swift --error-format=json "$(document_file "$candidate")" 2>&1)" || status=$?
    case "$status" in
        0) ALGORITHMS+=("$candidate") ;;
        7)
            ALGORITHMS_REFUSED+=("$(basename "$candidate" .scxml): $(printf '%s' "$verdict" | grep -o '"message":"[^"]*"' | head -n 1 | cut -c1-170)")
            ;;
        *)
            echo "error: sce-codegen check -l swift $candidate failed with status $status" >&2
            exit 1
            ;;
    esac
done
if [ "${#ALGORITHMS[@]}" -gt 0 ]; then
    mapfile -t ALGORITHMS < <(printf '%s\n' "${ALGORITHMS[@]}" | LC_ALL=C sort -u)
fi

# The event schemas the fixture directory and the standard library declare that the
# generator lowers for Swift, each a unit of the same SwiftPM target: the struct a record
# is handed to an algorithm in, which an algorithm of the target names whichever
# directory its schema is in. Derived for the reason the machines are, and a refusal by
# name (status 7) is listed, not skipped: a schema of a field Swift does not lower yet
# is one more thing standing between it and the rest of the fixtures. The enums are
# swept with them: the type a field of a record or a value of an algorithm holds a
# variant in is a unit of the same target, written for what it is.
mapfile -t SCHEMA_CANDIDATES < <(
    {
        grep -lE 'sce:kind="(event-schema|enum)"' "$INPUT_ROOT"/*.scxml "$CORPUS_ROOT"/*.scxml
        grep -rlE 'sce:kind="(event-schema|enum)"' stdlib --include='*.scxml' | sed 's|^stdlib/|sce:std/|'
    } | LC_ALL=C sort -u
)
SCHEMAS=()
SCHEMAS_REFUSED=()
for source in "${SCHEMA_CANDIDATES[@]}"; do
    status=0
    verdict="$("$CODEGEN" check -l swift --error-format=json "$(document_file "$source")" 2>&1)" || status=$?
    case "$status" in
        0) SCHEMAS+=("$source") ;;
        7)
            SCHEMAS_REFUSED+=("$(basename "$source" .scxml): $(printf '%s' "$verdict" | grep -o '"message":"[^"]*"' | head -n 1 | cut -c1-170)")
            ;;
        *)
            echo "error: sce-codegen check -l swift $source failed with status $status" >&2
            exit 1
            ;;
    esac
done

# The broadcast logs (ADR 0062) and the elements they store, which the Swift backend writes in part:
# a log over an element whose codec Swift writes. A log is generated from its document SET and never
# alone, because its entry is sized from the largest number of bytes the element document's codec
# encodes to, which only the set compile reads (a single-document `generate` of a log is refused,
# naming what is missing), so `orchestrate` compiles the documents of the directory together. They
# are kept in a directory of their own, which the sweeps above do not read: the element is a codec
# the set generates beside the log, and generated twice it would be two units of one name. A set
# that is refused is a defect of the documents, not a unit to skip: the fixtures are the ones Swift
# writes.
BROADCAST_LOG_DIR="$INPUT_ROOT/broadcast_log"
mapfile -t BROADCAST_LOG_DOCUMENTS < <(printf '%s\n' "$BROADCAST_LOG_DIR"/*.scxml | LC_ALL=C sort)
if [ ! -e "${BROADCAST_LOG_DOCUMENTS[0]}" ]; then
    echo "error: no broadcast log fixture found under $BROADCAST_LOG_DIR" >&2
    exit 1
fi
# The logs over an element whose codec asks its caller for a flag input or a variant tag, which an
# entry stores beside the bytes (ADR 0062 section 4). They are the shared conformance documents the
# other backends generate theirs from, in a directory of the corpus and not of the fixtures above,
# so that a document added here does not move the hash of every generated fixture. A set of its own
# for the reason the first is one: the log is sized from the elements the set compiles together.
BROADCAST_LOG_CONTEXT_DIR="tests/forge/conformance/broadcast_log_context"
mapfile -t BROADCAST_LOG_CONTEXT_DOCUMENTS < <(printf '%s\n' "$BROADCAST_LOG_CONTEXT_DIR"/*.scxml | LC_ALL=C sort)
if [ ! -e "${BROADCAST_LOG_CONTEXT_DOCUMENTS[0]}" ]; then
    echo "error: no broadcast log context fixture found under $BROADCAST_LOG_CONTEXT_DIR" >&2
    exit 1
fi
# The bounded collections (RFC section synth-5-L) and the codec they hold. A collection is generated
# from its document SET and never alone, because the type of its index field is read from the element
# document, which only the set compile has in hand; the element is a codec of the same directory, which
# the set generates beside them (a set is read from one root, and generated twice the element would be
# two units of one name).
BOUNDED_COLLECTION_DIR="tests/forge/conformance/bounded_collection"
mapfile -t BOUNDED_COLLECTION_DOCUMENTS < <(printf '%s\n' "$BOUNDED_COLLECTION_DIR"/*.scxml | LC_ALL=C sort)
if [ ! -e "${BOUNDED_COLLECTION_DOCUMENTS[0]}" ]; then
    echo "error: no bounded collection fixture found under $BOUNDED_COLLECTION_DIR" >&2
    exit 1
fi
# The queues (RFC section synth-5-P) and the codec they hold, the fixtures every backend's generated-queue
# test is built from. A queue is generated from its document SET and never alone, because the element
# it holds is a document of the set. The two `intrusive` fixtures are not among them: that storage is
# refused for Swift by name, and a document refused by name has no unit to run.
QUEUE_DIR="tests/forge/resources"
QUEUE_DOCUMENTS=(
    "$QUEUE_DIR/queue_conformance_event.scxml"
    "$QUEUE_DIR/queue_conformance_spsc.scxml"
    "$QUEUE_DIR/queue_conformance_scq.scxml"
    "$QUEUE_DIR/queue_conformance_segmented.scxml"
    "$QUEUE_DIR/queue_conformance_segmented_many.scxml"
)
for document in "${QUEUE_DOCUMENTS[@]}"; do
    if [ ! -e "$document" ]; then
        echo "error: no queue fixture $document" >&2
        exit 1
    fi
done
# The test profile's templates (docs/SCE_TEST_PROFILE.md §11.4, §11.9), each a document of its own
# kind whose unit declares its `matches` and, for a specific one, its `value`, members of an enum
# named by the document, generated as a file of the same target beside the records and enums their
# units name; ATestTemplateMatchesItsValuesTests.swift matches them against values. The Rust,
# Kotlin, Go, Python and C11 trees generate the same templates (scripts/regen_static_datamodel_rust.sh
# and its siblings), Rust and Kotlin the two over a union besides, which Swift, lowering no union,
# refuses by name. They are not swept by the directory reads above: the fixture directory of the
# profile holds documents refused on purpose, so the documents generated are the ones named here.
TEST_PROFILE_DIR="sce-build/tests/fixtures/test_profile"
TEST_PROFILE=(job_status elapsed_at_most every_matcher job_report job_report_of report_within)
TEST_PROFILE_IMPORTS=(paint_color order_line quantity_two quantity_at_most order_line_exact order_line_bounded)
TEST_PROFILE_IMPORTS+=(card_payment card_within voucher_payment voucher_is)

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

for i in "${!MACHINES[@]}"; do
    "$CODEGEN" generate "${SOURCES[$i]}" -l swift -o "$TMP/${MACHINES[$i]}/"
done
# A file is named for the document's own name, not for the path it was read from.
for i in "${!ALGORITHMS[@]}"; do
    "$CODEGEN" generate "${ALGORITHMS[$i]}" -l swift -o "$TMP/algorithm_$i/"
done
for i in "${!SCHEMAS[@]}"; do
    "$CODEGEN" generate "${SCHEMAS[$i]}" -l swift -o "$TMP/schema_$i/"
done
BROADCAST_LOG_ARGUMENTS=()
for document in "${BROADCAST_LOG_DOCUMENTS[@]}"; do
    BROADCAST_LOG_ARGUMENTS+=(--forge "$document")
done
"$CODEGEN" orchestrate "${BROADCAST_LOG_ARGUMENTS[@]}" --language swift --output-dir "$TMP/broadcast_log/" > /dev/null
BROADCAST_LOG_CONTEXT_ARGUMENTS=()
for document in "${BROADCAST_LOG_CONTEXT_DOCUMENTS[@]}"; do
    BROADCAST_LOG_CONTEXT_ARGUMENTS+=(--forge "$document")
done
"$CODEGEN" orchestrate "${BROADCAST_LOG_CONTEXT_ARGUMENTS[@]}" --language swift --output-dir "$TMP/broadcast_log_context/" > /dev/null
BOUNDED_COLLECTION_ARGUMENTS=()
for document in "${BOUNDED_COLLECTION_DOCUMENTS[@]}"; do
    BOUNDED_COLLECTION_ARGUMENTS+=(--forge "$document")
done
"$CODEGEN" orchestrate "${BOUNDED_COLLECTION_ARGUMENTS[@]}" --language swift --output-dir "$TMP/bounded_collection/" > /dev/null
QUEUE_ARGUMENTS=()
for document in "${QUEUE_DOCUMENTS[@]}"; do
    QUEUE_ARGUMENTS+=(--forge "$document")
done
"$CODEGEN" orchestrate "${QUEUE_ARGUMENTS[@]}" --language swift --output-dir "$TMP/queue/" > /dev/null
for document in "${TEST_PROFILE[@]}"; do
    "$CODEGEN" generate "$TEST_PROFILE_DIR/$document.scxml" -l swift -o "$TMP/profile_$document/"
done
for document in "${TEST_PROFILE_IMPORTS[@]}"; do
    "$CODEGEN" generate "$TEST_PROFILE_DIR/imports/$document.scxml" -l swift -o "$TMP/profile_$document/"
done

mkdir -p "$GENERATED_DIR"
# Every file below is generated and the tests beside them are not: clearing by
# what each file says it is takes the first and leaves the second.
source "$REPO_ROOT/scripts/lib/sce_generated_tree.sh"
sce_generated_tree_clear --recursive "$GENERATED_DIR"
for machine in "${MACHINES[@]}"; do
    cp "$TMP/$machine"/*_sm.swift "$GENERATED_DIR/"
done
# A unit is named for its document, and the units are files of one SwiftPM target, so
# two documents of one name (a fixture and a standard algorithm both called
# `days_in_month`) would be one file that holds whichever was copied last, and a caller
# of the other would be compiled against the wrong function. That is a defect of the
# documents, not something to order: one of them needs another name
# (`a_fixture_algorithm_is_named_apart_from_the_standard_library`).
declare -A UNIT_FROM=()
UNITS=()
for i in "${!ALGORITHMS[@]}"; do
    for generated in "$TMP/algorithm_$i"/*.swift; do
        unit="$(basename "$generated" .swift)"
        if [ -n "${UNIT_FROM[$unit]:-}" ]; then
            echo "error: ${UNIT_FROM[$unit]} and ${ALGORITHMS[$i]} are both written as $unit; one of them needs another name" >&2
            exit 1
        fi
        cp "$generated" "$GENERATED_DIR/"
        UNIT_FROM[$unit]="${ALGORITHMS[$i]}"
        UNITS+=("$unit")
    done
done
SCHEMA_UNITS=()
for i in "${!SCHEMAS[@]}"; do
    for generated in "$TMP/schema_$i"/*.swift; do
        unit="$(basename "$generated" .swift)"
        # The same defect as two algorithms of one name, and a schema or an enum is no
        # exception: the copy of the later would replace the earlier without a word.
        if [ -n "${UNIT_FROM[$unit]:-}" ]; then
            echo "error: ${UNIT_FROM[$unit]} and ${SCHEMAS[$i]} are both written as $unit; one of them needs another name" >&2
            exit 1
        fi
        cp "$generated" "$GENERATED_DIR/"
        UNIT_FROM[$unit]="${SCHEMAS[$i]}"
        SCHEMA_UNITS+=("$unit")
    done
done
# The same defect again for a log or an element of the set: a unit of the name of one above.
BROADCAST_LOG_UNITS=()
for generated in "$TMP/broadcast_log"/*.swift; do
    unit="$(basename "$generated" .swift)"
    if [ -n "${UNIT_FROM[$unit]:-}" ]; then
        echo "error: ${UNIT_FROM[$unit]} and the broadcast log fixtures are both written as $unit; one of them needs another name" >&2
        exit 1
    fi
    cp "$generated" "$GENERATED_DIR/"
    UNIT_FROM[$unit]="$BROADCAST_LOG_DIR"
    BROADCAST_LOG_UNITS+=("$unit")
done
for generated in "$TMP/broadcast_log_context"/*.swift; do
    unit="$(basename "$generated" .swift)"
    if [ -n "${UNIT_FROM[$unit]:-}" ]; then
        echo "error: ${UNIT_FROM[$unit]} and the broadcast log context fixtures are both written as $unit; one of them needs another name" >&2
        exit 1
    fi
    cp "$generated" "$GENERATED_DIR/"
    UNIT_FROM[$unit]="$BROADCAST_LOG_CONTEXT_DIR"
    BROADCAST_LOG_UNITS+=("$unit")
done
BOUNDED_COLLECTION_UNITS=()
for generated in "$TMP/bounded_collection"/*.swift; do
    unit="$(basename "$generated" .swift)"
    if [ -n "${UNIT_FROM[$unit]:-}" ]; then
        echo "error: ${UNIT_FROM[$unit]} and the bounded collection fixtures are both written as $unit; one of them needs another name" >&2
        exit 1
    fi
    cp "$generated" "$GENERATED_DIR/"
    UNIT_FROM[$unit]="$BOUNDED_COLLECTION_DIR"
    BOUNDED_COLLECTION_UNITS+=("$unit")
done
QUEUE_UNITS=()
for generated in "$TMP/queue"/*.swift; do
    unit="$(basename "$generated" .swift)"
    if [ -n "${UNIT_FROM[$unit]:-}" ]; then
        echo "error: ${UNIT_FROM[$unit]} and the queue fixtures are both written as $unit; one of them needs another name" >&2
        exit 1
    fi
    cp "$generated" "$GENERATED_DIR/"
    UNIT_FROM[$unit]="$QUEUE_DIR"
    QUEUE_UNITS+=("$unit")
done
# The same defect again for a template or a document it names: a unit of the name of one above.
TEST_PROFILE_UNITS=()
for document in "${TEST_PROFILE[@]}" "${TEST_PROFILE_IMPORTS[@]}"; do
    for generated in "$TMP/profile_$document"/*.swift; do
        unit="$(basename "$generated" .swift)"
        if [ -n "${UNIT_FROM[$unit]:-}" ]; then
            echo "error: ${UNIT_FROM[$unit]} and the test profile fixture $document are both written as $unit; one of them needs another name" >&2
            exit 1
        fi
        cp "$generated" "$GENERATED_DIR/"
        UNIT_FROM[$unit]="$TEST_PROFILE_DIR/$document"
        TEST_PROFILE_UNITS+=("$unit")
    done
done

# The numerical conformance harness (tests/forge/conformance): the oracle's cases for the
# units above, held to what each computes. The harness lists the fixtures this backend's
# generator writes and nothing else (`conformance::lang_supports_fixture`), so it holds
# exactly the units the sweep wrote and a refusal by name leaves a fixture out of both.
HARNESS_DIR="backends/swift/tests/Tests/StaticDatamodelTests"
"$CODEGEN" generate-conformance \
    --language swift \
    --manifest "$CORPUS_MANIFEST" \
    --output-dir "$HARNESS_DIR" > /dev/null

echo "Regenerated: ${MACHINES[*]}, the algorithms ${UNITS[*]:-none}, the event schemas ${SCHEMA_UNITS[*]:-none} and the broadcast logs ${BROADCAST_LOG_UNITS[*]:-none} and the bounded collections ${BOUNDED_COLLECTION_UNITS[*]:-none} and the queues ${QUEUE_UNITS[*]:-none} and the test profile's units ${TEST_PROFILE_UNITS[*]:-none} under $GENERATED_DIR/"
if [ "${#REFUSED[@]}" -gt 0 ]; then
    echo "Not lowered yet (${#REFUSED[@]}), refused by name:"
    printf '  %s\n' "${REFUSED[@]}"
fi
if [ "${#ALGORITHMS_REFUSED[@]}" -gt 0 ]; then
    echo "Algorithms not lowered yet (${#ALGORITHMS_REFUSED[@]}), refused by name:"
    printf '  %s\n' "${ALGORITHMS_REFUSED[@]}"
fi
if [ "${#SCHEMAS_REFUSED[@]}" -gt 0 ]; then
    echo "Event schemas not lowered yet (${#SCHEMAS_REFUSED[@]}), refused by name:"
    printf '  %s\n' "${SCHEMAS_REFUSED[@]}"
fi
