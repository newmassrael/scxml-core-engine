# Regenerate backends/swift/tests/Sources/StaticDatamodelMachines/ from
# sce-build/tests/fixtures/static_datamodel/<machine>.scxml, for every machine
# the Swift backend lowers, every algorithm those machines call, and every event
# schema the Swift backend lowers.
#
# The Swift compile+run gate for datamodel="sce-static"
# (docs/SCE_ACCEPTED_SUBSET.md §2.15), the twin of
# scripts/regen_static_datamodel_go.sh, _kotlin.sh and _rust.sh over the same
# fixtures. The committed machines are one SwiftPM target of backends/swift/tests, so
# their variables really are properties of the policy and every lowered expression
# — the checked integer operations and the `error.execution` they fail into
# included — really type-checks; the tests beside them replay the shared scenarios
# against them with no script engine.
#
# Usage (from repo root):
#   scripts/regen_static_datamodel_swift.sh
#
# Requires:
#   sce-codegen (resolved by scripts/lib/sce_codegen.sh, built when missing).

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

source "$REPO_ROOT/scripts/lib/sce_codegen.sh"
CODEGEN="$(sce_codegen_require "$REPO_ROOT")"
INPUT_ROOT="sce-build/tests/fixtures/static_datamodel"
# The conformance corpus: the documents of every forge kind that the numerical conformance
# harness runs on each backend (`tests/forge/conformance/fixtures.json`). A kind with no
# document in the fixture directory or the standard library is held to the compiler here.
# The directory holds documents that are not fixtures (one is invalid on purpose), so the
# documents to generate are the catalog's, asked of the generator as the other backends'
# harnesses ask; the event schemas and enums they import are read from the directory.
CORPUS_ROOT="tests/forge/resources"
CORPUS_MANIFEST="tests/forge/conformance/fixtures.json"
GENERATED_DIR="backends/swift/tests/Sources/StaticDatamodelMachines"

# Derived, not listed: every statechart the fixture directory declares under
# datamodel="sce-static" that the generator lowers for Swift. The generator is
# asked, so a construct Swift gains the lowering of joins the gate by itself. A
# refusal by name is exit status 7 (generate/unsupported-feature); any other
# failure is a defect, not a machine to skip.
mapfile -t CANDIDATES < <(grep -l 'datamodel="sce-static"' "$INPUT_ROOT"/*.scxml | LC_ALL=C sort)
if [ "${#CANDIDATES[@]}" -lt 1 ]; then
    echo "error: no sce-static statechart found under $INPUT_ROOT" >&2
    exit 1
fi
MACHINES=()
SOURCES=()
# What a machine that is not lowered yet is refused for, one line each, so a run reads
# what stands between Swift and the rest of the fixtures.
REFUSED=()
for source in "${CANDIDATES[@]}"; do
    status=0
    verdict="$("$CODEGEN" check -l swift --error-format=json "$source" 2>&1)" || status=$?
    case "$status" in
        0)
            MACHINES+=("$(basename "$source" .scxml)")
            SOURCES+=("$source")
            ;;
        7)
            REFUSED+=("$(basename "$source" .scxml): $(printf '%s' "$verdict" | grep -o '"message":"[^"]*"' | head -n 1 | cut -c1-170)")
            ;;
        *)
            echo "error: sce-codegen check -l swift $source failed with status $status" >&2
            exit 1
            ;;
    esac
done
# The statecharts of the standard library a scenario names by its library name
# (`"machine": "sce:std/shared/record_list"`): each is generated by that name when the
# generator lowers it, as a fixture is. The library holds what every backend
# generates whole, not what Swift generates yet, so each is asked about too.
mapfile -t STANDARD_MACHINES < <(grep -ho '"machine": "sce:std/[^"]*"' "$INPUT_ROOT"/scenarios/*.json | cut -d'"' -f4 | sort -u)
for standard in "${STANDARD_MACHINES[@]}"; do
    # `check` reads a file, and a library name is one only to `generate`: the document
    # is read from where the library keeps it.
    status=0
    "$CODEGEN" check -l swift "stdlib/${standard#sce:std/}.scxml" > /dev/null 2>&1 || status=$?
    case "$status" in
        0)
            MACHINES+=("$(basename "$standard")")
            SOURCES+=("$standard.scxml")
            ;;
        7) ;;
        *)
            echo "error: sce-codegen check -l swift $standard.scxml failed with status $status" >&2
            exit 1
            ;;
    esac
done
if [ "${#MACHINES[@]}" -lt 1 ]; then
    echo "error: the Swift backend lowers no sce-static statechart" >&2
    exit 1
fi

# Derived from what the lowered machines import, for the reason the machines are:
# a list here is one more place a new algorithm has to be remembered, and one left
# out is a machine that calls an enum nothing declared. Each algorithm a machine
# calls is generated beside the machines, a file of the same SwiftPM target, as
# scripts/regen_static_datamodel_go.sh generates each as a package of its own. An
# algorithm is the one kind a Swift machine calls, and one that imports a document
# other than an event schema is refused where the machine imports it
# (`StaticCallee::unlowered_by`), so the algorithms the machines name directly are
# generated, and then every other algorithm the generator lowers (below).

# The file a document named as the generator takes it is read from.
document_file() {
    case "$1" in
        sce:std/*) printf '%s\n' "stdlib/${1#sce:std/}" ;;
        *) printf '%s\n' "$1" ;;
    esac
}

# The algorithms document $1 imports, each named as the generator takes it: a
# standard one as it is written, any other beside the document that imports it.
algorithms_of() {
    local import
    while IFS= read -r import; do
        case "$import" in
            sce:*) printf '%s\n' "$import" ;;
            *) printf '%s\n' "$(dirname "$1")/$import" ;;
        esac
    done < <(grep '<sce:import kind="algorithm"' "$(document_file "$1")" | grep -o 'src="[^"]*"' | cut -d'"' -f2)
}

ALGORITHMS=()
for source in "${SOURCES[@]}"; do
    while IFS= read -r algorithm; do
        ALGORITHMS+=("$algorithm")
    done < <(algorithms_of "$source")
done
# The documents of the kinds the Swift backend writes as a unit of one file (an algorithm,
# a condition, a lookup, an interpolation and a filter), which the fixture directory, the
# standard library and the conformance catalog declare, whether or not a machine the Swift
# backend lowers calls one: a unit is compiled for what it is, not for who happens to call
# it, so a construct Swift gains the lowering of is held to the compiler before a machine
# reaches it. A kind Swift gains is added here, to the one list. Derived, and a refusal by
# name (status 7) is listed, as the machines' are.
UNIT_KINDS='(algorithm|condition|lookup|interpolation|filter)'
mapfile -t ALGORITHM_CANDIDATES < <(
    {
        grep -lE "sce:kind=\"$UNIT_KINDS\"" "$INPUT_ROOT"/*.scxml
        grep -rlE "sce:kind=\"$UNIT_KINDS\"" stdlib --include='*.scxml' | sed 's|^stdlib/|sce:std/|'
        # The catalog's documents of the kinds Swift writes: a path under the corpus, or
        # the `sce:std/...` name of a standard document (which stdlib already lists).
        while IFS= read -r document; do
            case "$document" in
                sce:std/*) ;;
                *) grep -lE "sce:kind=\"$UNIT_KINDS\"" "$document" || true ;;
            esac
        done < <("$CODEGEN" list-fixtures --manifest "$CORPUS_MANIFEST" --resource-dir "$CORPUS_ROOT" --format plain --documents)
    } | LC_ALL=C sort -u
)
ALGORITHMS_REFUSED=()
for candidate in "${ALGORITHM_CANDIDATES[@]}"; do
    status=0
    verdict="$("$CODEGEN" check -l swift --error-format=json "$(document_file "$candidate")" 2>&1)" || status=$?
    case "$status" in
        0) ALGORITHMS+=("$candidate") ;;
        7)
            ALGORITHMS_REFUSED+=("$(basename "$candidate" .scxml): $(printf '%s' "$verdict" | grep -o '"message":"[^"]*"' | head -n 1 | cut -c1-170)")
            ;;
        *)
            echo "error: sce-codegen check -l swift $candidate failed with status $status" >&2
            exit 1
            ;;
    esac
done
if [ "${#ALGORITHMS[@]}" -gt 0 ]; then
    mapfile -t ALGORITHMS < <(printf '%s\n' "${ALGORITHMS[@]}" | LC_ALL=C sort -u)
fi

# The event schemas the fixture directory and the standard library declare that the
# generator lowers for Swift, each a unit of the same SwiftPM target: the struct a record
# is handed to an algorithm in, which an algorithm of the target names whichever
# directory its schema is in. Derived for the reason the machines are, and a refusal by
# name (status 7) is listed, not skipped: a schema of a field Swift does not lower yet
# is one more thing standing between it and the rest of the fixtures. The enums are
# swept with them: the type a field of a record or a value of an algorithm holds a
# variant in is a unit of the same target, written for what it is.
mapfile -t SCHEMA_CANDIDATES < <(
    {
        grep -lE 'sce:kind="(event-schema|enum)"' "$INPUT_ROOT"/*.scxml "$CORPUS_ROOT"/*.scxml
        grep -rlE 'sce:kind="(event-schema|enum)"' stdlib --include='*.scxml' | sed 's|^stdlib/|sce:std/|'
    } | LC_ALL=C sort -u
)
SCHEMAS=()
SCHEMAS_REFUSED=()
for source in "${SCHEMA_CANDIDATES[@]}"; do
    status=0
    verdict="$("$CODEGEN" check -l swift --error-format=json "$(document_file "$source")" 2>&1)" || status=$?
    case "$status" in
        0) SCHEMAS+=("$source") ;;
        7)
            SCHEMAS_REFUSED+=("$(basename "$source" .scxml): $(printf '%s' "$verdict" | grep -o '"message":"[^"]*"' | head -n 1 | cut -c1-170)")
            ;;
        *)
            echo "error: sce-codegen check -l swift $source failed with status $status" >&2
            exit 1
            ;;
    esac
done

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

for i in "${!MACHINES[@]}"; do
    "$CODEGEN" generate "${SOURCES[$i]}" -l swift -o "$TMP/${MACHINES[$i]}/"
done
# A file is named for the document's own name, not for the path it was read from.
for i in "${!ALGORITHMS[@]}"; do
    "$CODEGEN" generate "${ALGORITHMS[$i]}" -l swift -o "$TMP/algorithm_$i/"
done
for i in "${!SCHEMAS[@]}"; do
    "$CODEGEN" generate "${SCHEMAS[$i]}" -l swift -o "$TMP/schema_$i/"
done

mkdir -p "$GENERATED_DIR"
# Every file below is generated and the tests beside them are not: clearing by
# what each file says it is takes the first and leaves the second.
source "$REPO_ROOT/scripts/lib/sce_generated_tree.sh"
sce_generated_tree_clear --recursive "$GENERATED_DIR"
for machine in "${MACHINES[@]}"; do
    cp "$TMP/$machine"/*_sm.swift "$GENERATED_DIR/"
done
# A unit is named for its document, and the units are files of one SwiftPM target, so
# two documents of one name (a fixture and a standard algorithm both called
# `days_in_month`) would be one file that holds whichever was copied last, and a caller
# of the other would be compiled against the wrong function. That is a defect of the
# documents, not something to order: one of them needs another name
# (`a_fixture_algorithm_is_named_apart_from_the_standard_library`).
declare -A UNIT_FROM=()
UNITS=()
for i in "${!ALGORITHMS[@]}"; do
    for generated in "$TMP/algorithm_$i"/*.swift; do
        unit="$(basename "$generated" .swift)"
        if [ -n "${UNIT_FROM[$unit]:-}" ]; then
            echo "error: ${UNIT_FROM[$unit]} and ${ALGORITHMS[$i]} are both written as $unit; one of them needs another name" >&2
            exit 1
        fi
        cp "$generated" "$GENERATED_DIR/"
        UNIT_FROM[$unit]="${ALGORITHMS[$i]}"
        UNITS+=("$unit")
    done
done
SCHEMA_UNITS=()
for i in "${!SCHEMAS[@]}"; do
    for generated in "$TMP/schema_$i"/*.swift; do
        unit="$(basename "$generated" .swift)"
        # The same defect as two algorithms of one name, and a schema or an enum is no
        # exception: the copy of the later would replace the earlier without a word.
        if [ -n "${UNIT_FROM[$unit]:-}" ]; then
            echo "error: ${UNIT_FROM[$unit]} and ${SCHEMAS[$i]} are both written as $unit; one of them needs another name" >&2
            exit 1
        fi
        cp "$generated" "$GENERATED_DIR/"
        UNIT_FROM[$unit]="${SCHEMAS[$i]}"
        SCHEMA_UNITS+=("$unit")
    done
done

echo "Regenerated: ${MACHINES[*]}, the algorithms ${UNITS[*]:-none} and the event schemas ${SCHEMA_UNITS[*]:-none} under $GENERATED_DIR/"
if [ "${#REFUSED[@]}" -gt 0 ]; then
    echo "Not lowered yet (${#REFUSED[@]}), refused by name:"
    printf '  %s\n' "${REFUSED[@]}"
fi
if [ "${#ALGORITHMS_REFUSED[@]}" -gt 0 ]; then
    echo "Algorithms not lowered yet (${#ALGORITHMS_REFUSED[@]}), refused by name:"
    printf '  %s\n' "${ALGORITHMS_REFUSED[@]}"
fi
if [ "${#SCHEMAS_REFUSED[@]}" -gt 0 ]; then
    echo "Event schemas not lowered yet (${#SCHEMAS_REFUSED[@]}), refused by name:"
    printf '  %s\n' "${SCHEMAS_REFUSED[@]}"
fi
