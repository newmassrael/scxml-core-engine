# Regenerate backends/go/tests/integration/static_datamodel/<machine>/ from
# sce-build/tests/fixtures/static_datamodel/<machine>.scxml, for every machine
# the Go backend lowers; the test profile's templates from
# sce-build/tests/fixtures/test_profile/ with the documents they name, a package
# each beside the machines; and the test components of
# sce-build/tests/fixtures/test_profile/runtime/, a package each, with the
# records and templates they name and the tables of the suite that runs them.
#
# The Go compile+run gate for datamodel="sce-static"
# (docs/SCE_ACCEPTED_SUBSET.md §2.15), the twin of
# scripts/regen_static_datamodel_rust.sh and
# scripts/regen_static_datamodel_kotlin.sh over the same fixtures. The
# committed machines compile as part of `go test ./...` in backends/go/tests, so
# their variables really are fields of the policy and every lowered expression
# — the checked integer operations and the `error.execution` they fail into
# included — really type-checks; static_scenarios_test.go replays the shared
# scenarios against them with no script engine.
#
# A Go package is a directory, so each machine has one of its own.
#
# Usage (from repo root):
#   scripts/regen_static_datamodel_go.sh
#
# Requires:
#   sce-codegen (resolved by scripts/lib/sce_codegen.sh, built when missing).

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

source "$REPO_ROOT/scripts/lib/sce_codegen.sh"
CODEGEN="$(sce_codegen_require "$REPO_ROOT")"
INPUT_ROOT="sce-build/tests/fixtures/static_datamodel"
GENERATED_DIR="backends/go/tests/integration/static_datamodel"
# The Go module path the generated packages live under: the module sce-go-tests
# (backends/go/tests/go.mod) and the directory GENERATED_DIR is in it. A
# machine imports each algorithm it calls as `<this>/<package>`, and a Go import
# path has no valid bare form, so every generation below is given it.
GO_MODULE_PREFIX="github.com/newmassrael/sce-go-tests/integration/static_datamodel"

# Derived, not listed: every statechart the fixture directory declares under
# datamodel="sce-static" that the generator lowers for Go — and the ones a test
# keeps beside itself, under tests/integration, which only that test reads. The
# generator is asked, so a construct Go gains the lowering of joins the gate by
# itself. A refusal by name is exit status 7 (generate/unsupported-feature); any
# other failure is a defect, not a machine to skip.
mapfile -t CANDIDATES < <(grep -l 'datamodel="sce-static"' "$INPUT_ROOT"/*.scxml tests/integration/*.scxml | sort)
if [ "${#CANDIDATES[@]}" -lt 1 ]; then
    echo "error: no sce-static statechart found under $INPUT_ROOT" >&2
    exit 1
fi
# Derived, not listed: the stem of every document a machine here declares in
# `sce:candidates`. Such a document is a child of the machine that invokes it,
# generated into THAT machine's package (below) because a Go package is a
# directory and the parent names its children as package-local symbols. Generated
# again as a machine of its own it would be a second copy nothing runs.
CANDIDATE_STEMS="$(grep -ho 'sce:candidates="[^"]*"' "$INPUT_ROOT"/*.scxml tests/integration/*.scxml | cut -d'"' -f2 | tr ' ' '\n' | sed -e 's|.*/||' -e 's|\.scxml$||' | sort -u || true)"
MACHINES=()
SOURCES=()
for source in "${CANDIDATES[@]}"; do
    if grep -qx -- "$(basename "$source" .scxml)" <<< "$CANDIDATE_STEMS"; then
        continue
    fi
    status=0
    "$CODEGEN" check -l go --go-module-prefix "$GO_MODULE_PREFIX" "$source" > /dev/null 2>&1 || status=$?
    case "$status" in
        0)
            MACHINES+=("$(basename "$source" .scxml)")
            SOURCES+=("$source")
            ;;
        7) ;;
        *)
            echo "error: sce-codegen check -l go $source failed with status $status" >&2
            exit 1
            ;;
    esac
done
if [ "${#MACHINES[@]}" -lt 1 ]; then
    echo "error: the Go backend lowers no sce-static statechart" >&2
    exit 1
fi
# The statecharts of the standard library a scenario names by its library name
# (`"machine": "sce:std/shared/record_list"`): each is generated by that name into a
# package of the stem of it, as a fixture is into one of its own. The library holds
# only what every backend generates, so none is asked about first.
mapfile -t STANDARD_MACHINES < <(grep -ho '"machine": "sce:std/[^"]*"' "$INPUT_ROOT"/scenarios/*.json | cut -d'"' -f4 | sort -u)
for standard in "${STANDARD_MACHINES[@]}"; do
    MACHINES+=("$(basename "$standard")")
    SOURCES+=("$standard.scxml")
done

# Derived from what the lowered machines import, for the reason the machines
# are: a list here is one more place a new algorithm has to be remembered, and
# one left out is a machine that imports a package nothing generated. Each
# algorithm a machine calls is generated beside the machines as a package of its
# own. A document is named as the generator takes it — a local one by its path, a
# standard one by its library name (`sce:std/...`) — and read for its own imports
# where it lies: a standard one under stdlib/.

# The file a document named as the generator takes it is read from.
document_file() {
    case "$1" in
        sce:std/*) printf '%s\n' "stdlib/${1#sce:std/}" ;;
        *) printf '%s\n' "$1" ;;
    esac
}

# The documents of kind $1 that document $2 imports, each named as the generator
# takes it: a standard one as it is written, any other beside the document that
# imports it — which, for a standard document, is the library again.
imports_of() {
    local kind="$1" document="$2" import
    while IFS= read -r import; do
        case "$import" in
            sce:*) printf '%s\n' "$import" ;;
            *) printf '%s\n' "$(dirname "$document")/$import" ;;
        esac
    done < <(grep "<sce:import kind=\"$kind\"" "$(document_file "$document")" | grep -o 'src="[^"]*"' | cut -d'"' -f2)
}

# The kinds a machine calls as functions: an algorithm, and a transform, a condition,
# a lookup, an interpolation or a validator (docs/adr/0048), and the text template a
# `<sce:render>` renders through its unit (docs/adr/0087, section 3).
CALLED_KINDS=(algorithm transform condition lookup interpolation validator text-template)

# The documents document $1 calls, of every kind it calls.
callees_of() {
    local kind
    for kind in "${CALLED_KINDS[@]}"; do
        imports_of "$kind" "$1"
    done
}

# Every document a machine calls, and every document one of those calls in its
# turn: a callee's package imports the package of each it calls, as a
# machine's does.
ALGORITHMS=()
declare -A REACHED=()
PENDING=()
for source in "${SOURCES[@]}"; do
    while IFS= read -r algorithm; do
        PENDING+=("$algorithm")
    done < <(callees_of "$source")
done
while [ "${#PENDING[@]}" -gt 0 ]; do
    algorithm="${PENDING[0]}"
    PENDING=("${PENDING[@]:1}")
    if [ -n "${REACHED[$algorithm]:-}" ]; then
        continue
    fi
    REACHED[$algorithm]=1
    ALGORITHMS+=("$algorithm")
    while IFS= read -r called; do
        PENDING+=("$called")
    done < <(callees_of "$algorithm")
done
if [ "${#ALGORITHMS[@]}" -gt 0 ]; then
    mapfile -t ALGORITHMS < <(printf '%s\n' "${ALGORITHMS[@]}" | sort -u)
fi
# The records an algorithm takes or returns are the payload structs of the
# event-schemas it imports, each a package of its own that the algorithm's package
# imports, and so does the machine that holds one. Derived from the algorithms, as
# they are from the machines, a standard one's from the library.
SCHEMAS=()
for algorithm in "${ALGORITHMS[@]}"; do
    while IFS= read -r schema; do
        SCHEMAS+=("$schema")
    done < <(imports_of event-schema "$algorithm")
done
if [ "${#SCHEMAS[@]}" -gt 0 ]; then
    mapfile -t SCHEMAS < <(printf '%s\n' "${SCHEMAS[@]}" | sort -u)
fi
# The enums those records and algorithms hold a value of: a record's enum field and
# an algorithm's enum slot are of the enum document's own type, a package of its own
# that the schema, the algorithm and the adapter a machine maps its own constants
# through import (SCE Accepted Subset §2.15).
ENUMS=()
for document in "${SCHEMAS[@]}" "${ALGORITHMS[@]}"; do
    while IFS= read -r enum; do
        ENUMS+=("$enum")
    done < <(imports_of enum "$document")
done
if [ "${#ENUMS[@]}" -gt 0 ]; then
    mapfile -t ENUMS < <(printf '%s\n' "${ENUMS[@]}" | sort -u)
fi
# The test profile's templates (docs/SCE_TEST_PROFILE.md §11.4, §11.9), each a document
# of its own kind whose unit declares its `Matches` and, for a specific one, its
# `Specific`, generated as a package of its own beside the records and enums their
# units name through their packages; a_test_template_matches_its_values_test.go matches
# them against values. The Rust and Kotlin trees generate the same templates
# (scripts/regen_static_datamodel_rust.sh, scripts/regen_static_datamodel_kotlin.sh),
# the two over a union among them, beside the unions their units name by package.
TEST_PROFILE_DIR="sce-build/tests/fixtures/test_profile"
TEST_PROFILE=(job_status elapsed_at_most every_matcher job_report job_report_of report_within shape_is_circle)
TEST_PROFILE_IMPORTS=(paint_color order_line quantity_two quantity_at_most order_line_exact order_line_bounded)
TEST_PROFILE_IMPORTS+=(card_payment card_within voucher_payment voucher_is)
TEST_PROFILE_IMPORTS+=(payment_kind order_customer order_payment order_placed order_placed_match)
# ... and the union shape_is_circle matches, with its tag's enum and its cases' records.
UNIONS=(shape_kind shape_radius_minimal shape_rect_minimal union_shape_minimal)
# The test components a_test_component_runs_through_its_doors_test.go runs through the
# profile's runtime (docs/SCE_TEST_PROFILE.md §12.3): each its statechart machine and the
# component beside it, generated into a package of its own as a fixture's machine is,
# beside the records and the templates its machine imports by their packages, which are
# generated as the templates above are. The port types are read where the components are
# and write no file; param_asker reads the module parameter the suite below gives it. The
# Rust and Kotlin trees generate the same components (scripts/regen_static_datamodel_rust.sh,
# scripts/regen_static_datamodel_kotlin.sh).
TEST_PROFILE_RUNTIME_DIR="$TEST_PROFILE_DIR/runtime"
TEST_PROFILE_RUNTIME=(job_request job_reply request_of any_request reply_ok reply_of)
TEST_COMPONENTS=(asker coordinator answerer ptc_keeper idler param_asker)
# The tables of the suite a_test_suite_runs_through_its_runner_test.go runs through the
# profile's runner (docs/SCE_TEST_PROFILE.md §11.6 to §11.8, §12.2), each a package of its
# own: each configuration's unit imports the package of each component's machine, which is
# the directory named by the component's document below the module path, as each component
# above is placed; each test case's imports its configuration's, and the suite's its test
# cases'. The feature model writes no file. The Rust and Kotlin trees generate the same
# tables (scripts/regen_static_datamodel_rust.sh, scripts/regen_static_datamodel_kotlin.sh).
TEST_TABLES=(asking_configuration serving_configuration keeping_configuration)
TEST_TABLES+=(answers_the_job answers_before_the_guard serves_a_ptc keeps_a_ptc runtime_suite)

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

for i in "${!MACHINES[@]}"; do
    "$CODEGEN" generate "${SOURCES[$i]}" -l go -o "$TMP/${MACHINES[$i]}/" --go-module-prefix "$GO_MODULE_PREFIX"
    # The documents the machine's hybrid invokes declare in `sce:candidates` are
    # real machines: `--parent-stem` puts each in the parent's package. Read from
    # the parent's own attributes rather than from what the generator staged
    # beside its output, which also holds the documents of its inline children.
    # Generated from the TRACKED document, not from a staged copy, so the
    # `// From:` line of a committed file does not carry a temporary path.
    while IFS= read -r base; do
        [ -n "$base" ] || continue
        "$CODEGEN" generate "$(dirname "${SOURCES[$i]}")/$base" --as-child --parent-stem "${MACHINES[$i]}" -l go -o "$TMP/${MACHINES[$i]}/" --go-module-prefix "$GO_MODULE_PREFIX"
    done < <(grep -ho 'sce:candidates="[^"]*"' "$(document_file "${SOURCES[$i]}")" | cut -d'"' -f2 | tr ' ' '\n' | sed 's|.*/||' | sort -u)
done
# An algorithm's directory is its package's name, which is its file's: the
# generator names the file for the document, not for the path it was read from.
for i in "${!ALGORITHMS[@]}"; do
    "$CODEGEN" generate "${ALGORITHMS[$i]}" -l go -o "$TMP/algorithm_$i/" --go-module-prefix "$GO_MODULE_PREFIX"
done
for i in "${!SCHEMAS[@]}"; do
    "$CODEGEN" generate "${SCHEMAS[$i]}" -l go -o "$TMP/schema_$i/" --go-module-prefix "$GO_MODULE_PREFIX"
done
for i in "${!ENUMS[@]}"; do
    "$CODEGEN" generate "${ENUMS[$i]}" -l go -o "$TMP/enum_$i/" --go-module-prefix "$GO_MODULE_PREFIX"
done
for document in "${TEST_PROFILE[@]}"; do
    "$CODEGEN" generate "$TEST_PROFILE_DIR/$document.scxml" -l go -o "$TMP/profile_$document/" --go-module-prefix "$GO_MODULE_PREFIX"
done
for document in "${TEST_PROFILE_IMPORTS[@]}"; do
    "$CODEGEN" generate "$TEST_PROFILE_DIR/imports/$document.scxml" -l go -o "$TMP/profile_$document/" --go-module-prefix "$GO_MODULE_PREFIX"
done
for document in "${UNIONS[@]}"; do
    "$CODEGEN" generate "sce-build/tests/fixtures/union/$document.scxml" -l go -o "$TMP/union_$document/" --go-module-prefix "$GO_MODULE_PREFIX"
done
for document in "${TEST_PROFILE_RUNTIME[@]}"; do
    "$CODEGEN" generate "$TEST_PROFILE_RUNTIME_DIR/$document.scxml" -l go -o "$TMP/runtime_$document/" --go-module-prefix "$GO_MODULE_PREFIX"
done
for component in "${TEST_COMPONENTS[@]}"; do
    "$CODEGEN" generate "$TEST_PROFILE_RUNTIME_DIR/$component.scxml" -l go -o "$TMP/component_$component/" --go-module-prefix "$GO_MODULE_PREFIX"
done
for document in "${TEST_TABLES[@]}"; do
    "$CODEGEN" generate "$TEST_PROFILE_RUNTIME_DIR/$document.scxml" -l go -o "$TMP/table_$document/" --go-module-prefix "$GO_MODULE_PREFIX"
done

mkdir -p "$GENERATED_DIR"
# Every package below is generated, and the tests beside them are not: clearing
# by what each file says it is takes the first and leaves the second, at any depth.
source "$REPO_ROOT/scripts/lib/sce_generated_tree.sh"
sce_generated_tree_clear --recursive "$GENERATED_DIR"
for machine in "${MACHINES[@]}"; do
    mkdir -p "$GENERATED_DIR/$machine"
    cp "$TMP/$machine"/*_sm.go "$GENERATED_DIR/$machine/"
done
PACKAGES=()
for i in "${!ALGORITHMS[@]}"; do
    for generated in "$TMP/algorithm_$i"/*.go; do
        package="$(basename "$generated" .go)"
        mkdir -p "$GENERATED_DIR/$package"
        cp "$generated" "$GENERATED_DIR/$package/"
        PACKAGES+=("$package")
    done
done
for i in "${!SCHEMAS[@]}"; do
    for generated in "$TMP/schema_$i"/*.go; do
        package="$(basename "$generated" .go)"
        mkdir -p "$GENERATED_DIR/$package"
        cp "$generated" "$GENERATED_DIR/$package/"
        PACKAGES+=("$package")
    done
done
for i in "${!ENUMS[@]}"; do
    for generated in "$TMP/enum_$i"/*.go; do
        package="$(basename "$generated" .go)"
        mkdir -p "$GENERATED_DIR/$package"
        cp "$generated" "$GENERATED_DIR/$package/"
        PACKAGES+=("$package")
    done
done
for document in "${TEST_PROFILE[@]}" "${TEST_PROFILE_IMPORTS[@]}"; do
    for generated in "$TMP/profile_$document"/*.go; do
        package="$(basename "$generated" .go)"
        mkdir -p "$GENERATED_DIR/$package"
        cp "$generated" "$GENERATED_DIR/$package/"
        PACKAGES+=("$package")
    done
done
for document in "${UNIONS[@]}"; do
    for generated in "$TMP/union_$document"/*.go; do
        package="$(basename "$generated" .go)"
        mkdir -p "$GENERATED_DIR/$package"
        cp "$generated" "$GENERATED_DIR/$package/"
        PACKAGES+=("$package")
    done
done
for document in "${TEST_PROFILE_RUNTIME[@]}"; do
    for generated in "$TMP/runtime_$document"/*.go; do
        package="$(basename "$generated" .go)"
        mkdir -p "$GENERATED_DIR/$package"
        cp "$generated" "$GENERATED_DIR/$package/"
        PACKAGES+=("$package")
    done
done
for document in "${TEST_TABLES[@]}"; do
    for generated in "$TMP/table_$document"/*.go; do
        package="$(basename "$generated" .go)"
        mkdir -p "$GENERATED_DIR/$package"
        cp "$generated" "$GENERATED_DIR/$package/"
        PACKAGES+=("$package")
    done
done
# A component's machine is copied as a fixture's is: its `_sm.go` alone, into the package
# named by its document, which the test's factory of machines and each configuration's
# table above import (`<module path>/<snake of the machine's name>`).
for component in "${TEST_COMPONENTS[@]}"; do
    mkdir -p "$GENERATED_DIR/$component"
    cp "$TMP/component_$component"/*_sm.go "$GENERATED_DIR/$component/"
    MACHINES+=("$component")
done

echo "Regenerated: ${MACHINES[*]} and the algorithms ${PACKAGES[*]:-none} under $GENERATED_DIR/"
